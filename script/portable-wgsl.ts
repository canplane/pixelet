#!/usr/bin/env -S deno run -A
// pxl-portable's WGSL: the entries gpu-query/shader makes of the one Rust
// source the CPU compiles too (crates/portable, over xpute-kit's
// math/rng.rs), through rust-gpu inside a Linux container, into the
// checked-in crates/client/render/src/frame/shader/cast.gen.wgsl. An
// everyday build reads that file and needs neither rust-gpu nor its nightly
// nor the container.
//
//   deno run -A script/portable-wgsl.ts            write it
//   deno run -A script/portable-wgsl.ts --check    fail if it is not current
//
// The check judges only that the checked-in file is what the source makes
// now; it never compares two implementations, since there is one.

import { dirname, fromFileUrl, join } from "@std/path";

const root = dirname(dirname(fromFileUrl(import.meta.url)));
const target = join(root, "crates/client/render/src/frame/shader/cast.gen.wgsl");
// rust-gpu's own pin (rustc_codegen_spirv 0.10.0-alpha.1 build.rs), as gpu-query/rust-toolchain.toml holds it.
const NIGHTLY = "nightly-2026-04-11";
const IMAGE = "rust:1-bookworm";
const BUILT = "gpu-query/target-linux/spirv-builder/spirv-unknown-naga-wgsl/release/deps/gpu_query_shader.wgsl";

const HEADER = [
  "// GENERATED by script/portable-wgsl.ts; do not edit. Regenerate with",
  "// `deno run -A script/portable-wgsl.ts`; `--check` fails when it is stale.",
  "// Source: crates/portable (pxl-portable) over xpute/rust/kit/src/math/rng.rs,",
  "// through gpu-query/shader, by",
  `// rust-gpu 0.10.0-alpha.1 (${NIGHTLY}) for spirv-unknown-naga-wgsl.`,
  "",
].join("\n");

function generate(): string {
  // The toolchain comes from gpu-query/rust-toolchain.toml, which rustup's
  // cargo installs on first use.
  const script = "cargo run -q --release -p gpu-query-builder";
  const out = new Deno.Command("docker", {
    args: [
      "run",
      "--rm",
      "--platform",
      "linux/arm64",
      "-v",
      `${root}:/w`,
      "-w",
      "/w/gpu-query",
      "-e",
      "CARGO_TARGET_DIR=/w/gpu-query/target-linux",
      "-e",
      "CARGO_HOME=/w/gpu-query/cargo-home",
      IMAGE,
      "bash",
      "-c",
      script,
    ],
    stdout: "inherit",
    stderr: "inherit",
  }).outputSync();
  if (!out.success) throw new Error("the rust-gpu build failed");
  return HEADER + Deno.readTextFileSync(join(root, BUILT));
}

const check = Deno.args.includes("--check");
const made = generate();
if (check) {
  let held = "";
  try {
    held = Deno.readTextFileSync(target);
  } catch {
    // Missing is stale.
  }
  if (held !== made) {
    console.error(`stale: ${target} is not what the source makes now; run script/portable-wgsl.ts`);
    Deno.exit(1);
  }
  console.log(`current: ${target}`);
} else {
  Deno.writeTextFileSync(target, made);
  console.log(`wrote ${target} (${made.length} bytes)`);
}
