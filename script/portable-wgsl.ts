#!/usr/bin/env -S deno run -A
// pxl-portable's WGSL: the entries gpu-query/shader makes of the one Rust
// source the CPU compiles too (crates/portable, over xpute-kit's
// math/rng.rs), through rust-gpu inside a Linux container, each a module of
// its own checked in beside the renderer's shaders — the cast's
// (crates/client/render/src/frame/shader/cast.gen.wgsl) and the ground's
// grid's, its cells (heights.gen.wgsl) and their bound (bound.gen.wgsl). An
// everyday build reads that file and needs neither rust-gpu nor its nightly
// nor the container. The harness's entries are built too, beside them in
// gpu-query's target, for gpu-query/runner; they are not checked in.
//
//   deno run -A script/portable-wgsl.ts            write them
//   deno run -A script/portable-wgsl.ts --check    fail if one is not current
//
// The check judges only that each checked-in file is what the source makes
// now; it never compares two implementations, since there is one.

import { dirname, fromFileUrl, join } from "@std/path";

const root = dirname(dirname(fromFileUrl(import.meta.url)));
const shaders = join(root, "crates/client/render/src/frame/shader");
// Each entry and the file it is checked in as.
const ENTRIES = [["cast_cs", "cast.gen.wgsl"], ["heights_cs", "heights.gen.wgsl"], ["bound_cs", "bound.gen.wgsl"]];
// rust-gpu's own pin (rustc_codegen_spirv 0.10.0-alpha.1 build.rs), as gpu-query/rust-toolchain.toml holds it.
const NIGHTLY = "nightly-2026-04-11";
const IMAGE = "rust:1-bookworm";
const BUILT = "gpu-query/target-linux/spirv-builder/spirv-unknown-naga-wgsl/release/deps/gpu_query_shader.spvs";

const HEADER = [
  "// GENERATED by script/portable-wgsl.ts; do not edit. Regenerate with",
  "// `deno run -A script/portable-wgsl.ts`; `--check` fails when it is stale.",
  "// Source: crates/portable (pxl-portable) over xpute/rust/kit/src/math/rng.rs,",
  "// through gpu-query/shader, by",
  `// rust-gpu 0.10.0-alpha.1 (${NIGHTLY}) for spirv-unknown-naga-wgsl.`,
  "",
].join("\n");

function generate(): Map<string, string> {
  // The toolchain comes from gpu-query/rust-toolchain.toml, which rustup's
  // cargo installs on first use.
  const script = "cargo run -q --release -p gpu-query-builder && cargo run -q --release -p gpu-query-builder -- --harness";
  const out = new Deno.Command("docker", {
    args: [
      "run",
      "--rm",
      "--platform",
      "linux/arm64",
      "-v",
      `${root}:/w`,
      "-w",
      "/w/gpu-query",
      "-e",
      "CARGO_TARGET_DIR=/w/gpu-query/target-linux",
      "-e",
      "CARGO_HOME=/w/gpu-query/cargo-home",
      IMAGE,
      "bash",
      "-c",
      script,
    ],
    stdout: "inherit",
    stderr: "inherit",
  }).outputSync();
  if (!out.success) throw new Error("the rust-gpu build failed");
  return new Map(ENTRIES.map(([entry, file]) => [join(shaders, file), HEADER + Deno.readTextFileSync(join(root, BUILT, `${entry}.wgsl`))]));
}

const check = Deno.args.includes("--check");
let stale = false;
for (const [target, made] of generate()) {
  if (check) {
    let held = "";
    try {
      held = Deno.readTextFileSync(target);
    } catch {
      // Missing is stale.
    }
    if (held !== made) {
      console.error(`stale: ${target} is not what the source makes now; run script/portable-wgsl.ts`);
      stale = true;
    } else {
      console.log(`current: ${target}`);
    }
  } else {
    Deno.writeTextFileSync(target, made);
    console.log(`wrote ${target} (${made.length} bytes)`);
  }
}
if (stale) Deno.exit(1);
