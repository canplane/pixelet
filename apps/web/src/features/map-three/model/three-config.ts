// 이 파일은 외부 라이브러리 의존성이 없는 순수 설정(Configuration) 파일입니다.

/**
 * 1. MAX_DISTANCE (카메라 줌의 한계)
 *   의미: "카메라가 원점(또는 타겟)에서 얼마나 멀어질 수 있는가?"
 *   목적: 사용자가 데이터를 넘어서 아무것도 없는 빈 공간을 보지 못하게 막는 조작의 벽입니다.
 *   설정 이유: 데이터 리밋이 1000m인데 카메라가 2000m까지 뒤로 물러나면, 화면 중앙에만 작은 섬처럼 데이터가 보이고 주변은 텅 비게 됩니다. 이를 방지하기 위해 줌 아웃을 데이터 범위 내로 제한하는 것입니다.
 *
 * 2. FADE_END (시각적 부드러움의 한계)
 *   의미: "그리드나 사물이 완전히 투명해져서 사라지는 지점"
 *   목적: 데이터의 '날카로운 절단면'을 숨기는 마술사 역할을 합니다.
 *   설정 이유: DATA_LIMIT인 1000m 지점에서 건물이나 그리드가 툭 끊기면 매우 부자연스럽습니다. 따라서 그보다 조금 앞선 900m(FADE_END) 지점에서 미리 투명하게 만들어 지평선과 자연스럽게 섞이도록 유도합니다.
 *
 * 3. FAR_CLIP (GPU 렌더링의 절대 한계)
 *   의미: "그래픽 카드가 계산을 수행할 가장 먼 평면"
 *   목적: 연산 자원을 아끼기 위한 성능의 마지노선입니다.
 *   설정 이유: 아무리 멀리 있는 산이라도 이 지점을 넘어가면 GPU는 아예 그리지 않습니다. 보통 안개나 페이드보다 훨씬 넉넉하게(2000m) 잡아서, 멀리 있는 큰 지형이 갑자기 사라지는(Clipping) 현상을 방지하면서도 무한한 연산을 막아줍니다."
 */

const DATA_LIMIT = 1000; // OSM_CONFIG.DEFAULT_RADIUS와 동기화

const DEFAULT_TILT = 30; // 지면 기준 각도 (사용자 친화적 수치)

export const THREE_CONFIG = {
  /**
   * 카메라 물리 설정 및 뷰포트 기준 (Three.js 내장 속성 위주)
   */
  CAMERA: {
    FOV: 50,
    NEAR: 0.1,

    DEFAULT_DISTANCE: 200,
    DEFAULT_POLAR_ANGLE: ((90 - DEFAULT_TILT) * Math.PI) / 180,
    // DEFAULT_TILT, // UI나 다른 계산에서 참조용

    // 🚀 계산식 기반 거리 제한
    MIN_DISTANCE: 10,
    MAX_DISTANCE: DATA_LIMIT, // 데이터가 있는 곳까지만 줌 아웃 허용
  },

  /**
   * 렌더링 및 시각 효과 (가시거리 제어)
   * 최적화 포인트: 가시거리를 1km~1.5km 내외로 좁혀 렌더링 부하를 줄입니다.
   */
  RENDERING: {
    // 🚀 데이터 끝(1000m) 전부터 페이드 시작
    FADE_START: DATA_LIMIT * 0.6, // 서서히 투명해짐
    FADE_END: DATA_LIMIT * 0.9, // 완전히 사라짐

    // 🚀 안개는 데이터가 사라지기 전에 화면을 가려야 함
    // FOG_NEAR: DATA_LIMIT * 0.5, // 안개가 더 일찍 시작되어 멀리 있는 끊김을 방어 (너무 일찍 뿌얘지면 답답할 수 있음)
    // FOG_FAR: DATA_LIMIT * 0.9, // UserMarker 가시성과 동기화
    FAR_CLIP: 2000, // 카메라가 그리는 최대 한계선

    // density 값이 커질수록 안개가 짙어집니다.
    // 보통 0.0001 ~ 0.002 사이의 아주 작은 값을 사용합니다.
    FOG_DENSITY: 0.0008,

    /**
     * 🔄 Floating Origin 리셋 임계값
     * 안개가 완전히 끝나는 지점(FOG_FAR)보다 조금 더 여유를 둡니다.
     * 이 지점에 도달하면 세상을 원점으로 당겨 정밀도를 회복합니다.
     */
    RESET_THRESHOLD: DATA_LIMIT * 0.9 * 1.25,
  },
} as const; // 값을 고정하여 타입 추론 최적화
