// @pxl/api/bake/asset/table.ts
//
// The ingested-asset table as source: packages/pxl/shared/src/record/
// ingested.ts for the TypeScript and crates/pxl/shared/src/record/
// ingested.rs for its Rust pair, rendered from the same rows so the two
// cannot drift (tool/ingest_asset.ts writes both).

/** One ingested file: its path under asset/, bucket key, size and, for a
 * model, its extent. */
export type TableRow = { path: string; key: string; bytes: number; extent: readonly [number, number, number] | null };

export type Sheet = { key: string; bytes: number; cell: number; columns: number; tiles: readonly string[] };

export function render_table(rows: readonly TableRow[], sheet: Sheet): string {
  const lines = rows.map((r) => {
    const extent = r.extent ? `, extent: [${r.extent.join(", ")}]` : "";
    return `  "${r.path}": { key: "${r.key}", bytes: ${r.bytes}${extent} },`;
  });
  return `// @pxl/shared/record/ingested.ts
//
// GENERATED by apps/api/src/bake/asset/tool/ingest_asset.ts — do not edit.
// Every shipped asset by its path under asset/: the bucket key (the SHA-256
// of its bytes under the \`asset/\` prefix), its size, and for a model its
// extent in ENU world units, measured from the glb. The shipped palette
// reads this; the bytes themselves are in the bucket.

export type IngestedAsset = {
  key: string;
  bytes: number;
  /** ENU (x, y, z-up); absent for an image. */
  extent?: readonly [number, number, number];
};

export const INGESTED: Readonly<Record<string, IngestedAsset>> = {
${lines.join("\n")}
};

/** The texture pack as one sheet: \`columns\` tiles of \`cell\` pixels per
 * row, tile n at column n % columns and row n / columns, \`tiles\` the asset
 * path each holds. */
export const SHEET = {
  key: "${sheet.key}",
  bytes: ${sheet.bytes},
  cell: ${sheet.cell},
  columns: ${sheet.columns},
  tiles: [
${sheet.tiles.map((t) => `    "${t}",`).join("\n")}
  ],
} as const;
`;
}

/** A number as a Rust f64 literal: JavaScript prints an integral double
 * without a point, which Rust reads as an integer. */
function f64_literal(x: number): string {
  const text = String(x);
  return /[.eE]/.test(text) ? text : `${text}.0`;
}

export function render_rust_table(rows: readonly TableRow[], sheet: Sheet): string {
  const lines = rows.map((r) => {
    const extent = r.extent ? `Some([${r.extent.map(f64_literal).join(", ")}])` : "None";
    return `    ("${r.path}", IngestedAsset { key: "${r.key}", bytes: ${r.bytes}, extent: ${extent} }),`;
  });
  return `// pxl_shared/record/ingested.rs
//
// GENERATED by apps/api/src/bake/asset/tool/ingest_asset.ts — do not edit.
// Every shipped asset by its path under asset/: the bucket key (the SHA-256
// of its bytes under the \`asset/\` prefix), its size, and for a model its
// extent in ENU world units, measured from the glb. The shipped palette
// reads this; the bytes themselves are in the bucket.

use std::collections::HashMap;
use std::sync::LazyLock;

#[derive(Clone, Copy, Debug, PartialEq)]
pub struct IngestedAsset {
    pub key: &'static str,
    pub bytes: u64,
    /// ENU (x, y, z-up); None for an image.
    pub extent: Option<[f64; 3]>,
}

const ROWS: &[(&str, IngestedAsset)] = &[
${lines.join("\n")}
];

pub static INGESTED: LazyLock<HashMap<&'static str, IngestedAsset>> = LazyLock::new(|| ROWS.iter().copied().collect());

/// The texture pack as one sheet: \`columns\` tiles of \`cell\` pixels per
/// row, tile n at column n % columns and row n / columns, \`tiles\` the asset
/// path each holds.
pub struct Sheet {
    pub key: &'static str,
    pub bytes: u64,
    pub cell: u32,
    pub columns: u32,
    pub tiles: &'static [&'static str],
}

pub const SHEET: Sheet = Sheet {
    key: "${sheet.key}",
    bytes: ${sheet.bytes},
    cell: ${sheet.cell},
    columns: ${sheet.columns},
    tiles: &[
${sheet.tiles.map((t) => `        "${t}",`).join("\n")}
    ],
};

#[cfg(test)]
#[path = "ingested.test.rs"]
mod test;
`;
}
