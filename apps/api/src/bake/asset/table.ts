// @pxl/api/bake/asset/table.ts
//
// The ingested-asset table as source: packages/pxl/shared/src/asset/
// ingested.ts for the TypeScript and crates/pxl/shared/src/asset/
// ingested.rs for its Rust pair, rendered from the same rows so the two
// cannot drift (tool/ingest_asset.ts writes both).

/** One ingested file: its path under asset/, bucket key, size and, for a
 * model, its extent. */
export type TableRow = { path: string; key: string; bytes: number; extent: readonly [number, number, number] | null };

export type Sheet = { key: string; bytes: number; cell: number; columns: number; tiles: readonly string[] };

export function render_table(rows: readonly TableRow[], sheet: Sheet): string {
  const lines = rows.map((r) => {
    const extent = r.extent ? `, extent: [${r.extent.join(", ")}]` : "";
    return `  "${r.path}": { key: "${r.key}", bytes: ${r.bytes}${extent} },`;
  });
  return `// @pxl/shared/asset/ingested.ts
//
// GENERATED by apps/api/src/bake/asset/tool/ingest_asset.ts — do not edit.
// Every shipped asset by its path under asset/: the bucket key (the SHA-256
// of its bytes under the \`asset/\` prefix), its size, and for a model its
// extent in ENU world units, measured from the glb. A catalog names an asset
// by its path and reads its key here; the bytes themselves are in the bucket.

export type IngestedAsset = {
  key: string;
  bytes: number;
  /** ENU (x, y, z-up); absent for an image. */
  extent?: readonly [number, number, number];
};

export const INGESTED: Readonly<Record<string, IngestedAsset>> = {
${lines.join("\n")}
};

/** The texture pack as one sheet: \`columns\` tiles of \`cell\` pixels per
 * row, tile n at column n % columns and row n / columns, \`tiles\` the asset
 * path each holds. */
export const SHEET = {
  key: "${sheet.key}",
  bytes: ${sheet.bytes},
  cell: ${sheet.cell},
  columns: ${sheet.columns},
  tiles: [
${sheet.tiles.map((t) => `    "${t}",`).join("\n")}
  ],
} as const;
`;
}

/** A number as a Rust f64 literal: JavaScript prints an integral double
 * without a point, which Rust reads as an integer. */
function f64_literal(x: number): string {
  const text = String(x);
  return /[.eE]/.test(text) ? text : `${text}.0`;
}

/** An asset path as the name of its member in the Rust's `Asset`. */
export function asset_ident(path: string): string {
  return path.replace(/[^A-Za-z0-9_]/g, "_");
}

/** Which cube type a texture-pack tile is, from the name the pack gives the
 * file: `block_<type>` a block's top, `<channel>_<type>` a ground type's top,
 * `side_<type>` the side of every channel's type of that name. */
function tile_cubes(path: string, channels: Readonly<Record<string, Readonly<Record<string, number>>>>): { cube: string; face: "Top" | "Side" }[] {
  const name = path.replace(/^.*\//, "").replace(/\.png$/, "");
  const [head, ...rest] = name.split("_");
  const type = rest.join("_");
  const cube = (channel: string) => `PlaceableCube::${channel[0].toUpperCase()}${channel.slice(1)}(cube_types::${channel[0].toUpperCase()}${channel.slice(1)}::${type})`;
  if (head === "side") {
    return Object.keys(channels).filter((ch) => ch !== "common" && type in channels[ch]).map((ch) => ({ cube: cube(ch), face: "Side" as const }));
  }
  return head in channels && head !== "common" && type in channels[head] ? [{ cube: cube(head), face: "Top" }] : [];
}

/** The same table for the kernel, which holds no text: every asset a member
 * of `Asset`, its size and extent a row at that member's number, and the
 * sheet's tiles the cube faces they are. The bucket keys are the shell's. */
export function render_rust_table(rows: readonly TableRow[], sheet: Sheet, channels: Readonly<Record<string, Readonly<Record<string, number>>>>): string {
  const members = rows.map((r, i) => `    ${asset_ident(r.path)} = ${i},`);
  const all = rows.map((r) => `        Asset::${asset_ident(r.path)},`);
  const lines = rows.map((r) => {
    const extent = r.extent ? `Some([${r.extent.map(f64_literal).join(", ")}])` : "None";
    return `    IngestedAsset { bytes: ${r.bytes}, extent: ${extent} },`;
  });
  const tiles = sheet.tiles.flatMap((t, n) => tile_cubes(t, channels).map((c) => `        (${c.cube}, CubeFace::${c.face}, ${n}),`));
  return `// pxl_shared/asset/ingested.rs
//
// GENERATED by apps/api/src/bake/asset/tool/ingest_asset.ts — do not edit.
// Every shipped asset as a member of \`Asset\`, in the ingest's sorted order:
// its size, and for a model its extent in ENU world units, measured from the
// glb. A catalog names an asset by its member; its path and its bucket key are
// the shell's (ingested.ts), and the bytes themselves are in the bucket.

#![allow(non_camel_case_types)]

use crate::spec::cell::{cube_types, PlaceableCube};

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[repr(u16)]
pub enum Asset {
${members.join("\n")}
}

impl Asset {
    /// Every asset, in the table's order.
    pub const ALL: [Asset; ${rows.length}] = [
${all.join("\n")}
    ];

    /// The asset a number names, or none for a number the table does not
    /// give out.
    pub fn of(value: u16) -> Option<Asset> {
        Asset::ALL.into_iter().find(|a| *a as u16 == value)
    }

    /// What the ingest measured of it.
    pub fn ingested(self) -> IngestedAsset {
        INGESTED[self as usize]
    }
}

#[derive(Clone, Copy, Debug, PartialEq)]
pub struct IngestedAsset {
    pub bytes: u64,
    /// ENU (x, y, z-up); None for an image.
    pub extent: Option<[f64; 3]>,
}

/// Each asset's row, at its member's number.
pub const INGESTED: [IngestedAsset; ${rows.length}] = [
${lines.join("\n")}
];

/// Which of a box's images a tile is. The split is the renderer's own: a face
/// is lateral at \`abs(normal.z) < 0.5\`, so a bottom face wears the top image
/// just as the top face does.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum CubeFace {
    Top,
    Side,
}

/// The texture pack as one sheet: \`columns\` tiles of \`cell\` pixels per
/// row, tile n at column n % columns and row n / columns, and \`tiles\` the
/// cube face each tile is.
pub struct Sheet {
    pub bytes: u64,
    pub cell: u32,
    pub columns: u32,
    pub tiles: &'static [(PlaceableCube, CubeFace, u32)],
}

pub const SHEET: Sheet = Sheet {
    bytes: ${sheet.bytes},
    cell: ${sheet.cell},
    columns: ${sheet.columns},
    tiles: &[
${tiles.join("\n")}
    ],
};

#[cfg(test)]
#[path = "ingested.test.rs"]
mod test;
`;
}
