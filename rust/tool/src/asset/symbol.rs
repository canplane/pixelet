// pxl-tool/asset/symbol.rs

//! Carto's place symbols, each SVG under `asset/raw/place/symbol/` named by the
//! path Carto gives it (`symbols/…`), which is how the places' theme names
//! it: for the marker sheet, the masks it tints, each rasterized once to
//! its coverage, a byte a pixel, in a square of `SYMBOL_PX`, laid end to end
//! in one file the spec crate includes; for the shell, its outlines.

use std::path::Path;

/// Carto's symbols are 14 pixels, drawn at the sheet's two device pixels a
/// pixel (pxl-render gpu/sheet.rs `SHEET_SCALE`).
pub const SYMBOL_PX: u32 = 28;

pub struct Symbol {
    /// As Carto gives it.
    pub path: String,
    pub mask: Vec<u8>,
    /// Its own box, and each shape in it as SVG path data and whether it
    /// fills even-odd.
    pub size: [f32; 2],
    pub shapes: Vec<(String, bool)>,
}

/// Each symbol, sorted by path.
pub fn symbols(dir: &Path) -> Result<Vec<Symbol>, String> {
    let mut paths = Vec::new();
    walk(dir, dir, &mut paths)?;
    paths.sort();
    paths
        .into_iter()
        .map(|rel| {
            let svg = std::fs::read(dir.join(&rel)).map_err(|e| format!("{rel}: {e}"))?;
            let tree = resvg::usvg::Tree::from_data(&svg, &resvg::usvg::Options::default()).map_err(|e| format!("{rel}: {e}"))?;
            let mut shapes = Vec::new();
            outline(tree.root(), &mut shapes);
            Ok(Symbol {
                path: format!("symbols/{rel}"),
                mask: mask(&tree).map_err(|e| format!("{rel}: {e}"))?,
                size: [tree.size().width(), tree.size().height()],
                shapes,
            })
        })
        .collect()
}

/// Every filled path under `group`, placed where it is drawn.
fn outline(group: &resvg::usvg::Group, out: &mut Vec<(String, bool)>) {
    use resvg::tiny_skia::PathSegment;
    for node in group.children() {
        match node {
            resvg::usvg::Node::Group(g) => outline(g, out),
            resvg::usvg::Node::Path(p) => {
                let Some(fill) = p.fill() else { continue };
                let Some(data) = p.data().clone().transform(p.abs_transform()) else { continue };
                let n = |v: f32| format!("{}", (v * 1000.0).round_ties_even() / 1000.0);
                let d: Vec<String> = data
                    .segments()
                    .map(|s| match s {
                        PathSegment::MoveTo(a) => format!("M{} {}", n(a.x), n(a.y)),
                        PathSegment::LineTo(a) => format!("L{} {}", n(a.x), n(a.y)),
                        PathSegment::QuadTo(a, b) => format!("Q{} {} {} {}", n(a.x), n(a.y), n(b.x), n(b.y)),
                        PathSegment::CubicTo(a, b, c) => format!("C{} {} {} {} {} {}", n(a.x), n(a.y), n(b.x), n(b.y), n(c.x), n(c.y)),
                        PathSegment::Close => "Z".into(),
                    })
                    .collect();
                out.push((d.join(""), fill.rule() == resvg::usvg::FillRule::EvenOdd));
            }
            _ => {}
        }
    }
}

fn walk(dir: &Path, base: &Path, out: &mut Vec<String>) -> Result<(), String> {
    for entry in std::fs::read_dir(dir).map_err(|e| format!("{}: {e}", dir.display()))?.flatten() {
        let path = entry.path();
        if path.is_dir() {
            walk(&path, base, out)?;
        } else if path.extension().is_some_and(|e| e == "svg") {
            out.push(path.strip_prefix(base).map_err(|e| e.to_string())?.to_string_lossy().replace('\\', "/"));
        }
    }
    Ok(())
}

/// The symbol's coverage, scaled from its own box to fill the square.
fn mask(tree: &resvg::usvg::Tree) -> Result<Vec<u8>, String> {
    let size = tree.size();
    let mut pixmap = resvg::tiny_skia::Pixmap::new(SYMBOL_PX, SYMBOL_PX).ok_or("an empty square")?;
    let scale = SYMBOL_PX as f32 / size.width().max(size.height());
    let transform = resvg::tiny_skia::Transform::from_scale(scale, scale).post_translate((SYMBOL_PX as f32 - size.width() * scale) / 2.0, (SYMBOL_PX as f32 - size.height() * scale) / 2.0);
    resvg::render(tree, transform, &mut pixmap.as_mut());
    Ok(pixmap.pixels().iter().map(|p| p.alpha()).collect())
}

/// The table the spec crate compiles: the paths, and the masks it includes.
pub fn render_rs(symbols: &[Symbol]) -> String {
    let mut rs = String::from(
        "// pxl-spec/asset/symbol.spec.rs\n//\n// GENERATED by pxl-tool/bin/ingest_asset.rs from asset/raw/place/symbol/ — do not edit.\n//\n// Carto's place symbols (openstreetmap-carto `symbols/`, CC0), each a mask\n// of its coverage, a byte a pixel, `SYMBOL_PX` a side, row by row, in\n// `symbol.mask` in the order of `SYMBOLS`.\n\n",
    );
    rs.push_str(&format!(
        "pub const SYMBOL_PX: u32 = {SYMBOL_PX};\n\n/// Each symbol's path as Carto gives it, sorted.\npub const SYMBOLS: [&str; {}] = [\n",
        symbols.len()
    ));
    for s in symbols {
        rs.push_str(&format!("    {:?},\n", s.path));
    }
    rs.push_str("];\n\npub static SYMBOL_MASKS: &[u8] = include_bytes!(\"symbol.mask\");\n");
    rs
}

/// The shell's module: each symbol's box and shapes, by its Carto path.
pub fn render_ts(symbols: &[Symbol]) -> String {
    let mut ts = String::from(
        "// @pxl/client/shell/search/place-symbol.ts\n//\n// Written by `./script/tool.ts ingest asset` from asset/raw/place/symbol/ — do not edit.\n//\n// Carto's place symbols (openstreetmap-carto `symbols/`, CC0) as outlines,\n// by the path Carto gives each: its box, and each shape's path data and\n// whether it fills even-odd.\n\nexport interface PlaceSymbol {\n  box: readonly [number, number];\n  shapes: readonly (readonly [string, boolean])[];\n}\n\nexport const PLACE_SYMBOLS: Record<string, PlaceSymbol> = {\n",
    );
    for s in symbols {
        let shapes: Vec<String> = s.shapes.iter().map(|(d, even)| format!("[{d:?}, {even}]")).collect();
        ts.push_str(&format!("  {:?}: {{ box: [{}, {}], shapes: [{}] }},\n", s.path, s.size[0], s.size[1], shapes.join(", ")));
    }
    ts.push_str("};\n");
    ts
}
