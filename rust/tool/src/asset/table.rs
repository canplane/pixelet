//! The ingested-asset table, written as the JSON the spec renders from.

use std::fmt::Write;

use crate::asset::pack::Slot;

pub struct Row {
    pub path: String,
    pub key: String,
    pub bytes: u64,
    pub extent: Option<[f64; 3]>,
}

pub struct Pack {
    /// The path its image ships at, a row of the table (`cube.json` `pack`).
    pub image: String,
    pub cell: u32,
    pub columns: u32,
    pub tiles: Vec<String>,
    pub means: Vec<[u8; 3]>,
    pub faces: Vec<TileFace>,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Face {
    Top,
    Side,
    Bottom,
}

impl Face {
    fn name(self) -> &'static str {
        match self {
            Face::Top => "top",
            Face::Side => "side",
            Face::Bottom => "bottom",
        }
    }
}

pub struct TileFace {
    /// The catalog's group, `ground` or `object`.
    pub group: String,
    pub ty: String,
    pub face: Face,
    pub tile: u32,
}

/// Each slot and the tile it wears; one tile may be several slots'. A slot
/// naming no catalog type is an error: a renamed type once left its blocks
/// untextured silently.
pub fn faces(slots: &[(u32, Slot)], groups: &[(String, Vec<String>)]) -> Result<Vec<TileFace>, String> {
    let mut out = Vec::new();
    for (n, slot) in slots {
        let (face, ty, wanted) = match slot {
            Slot::Top { group, ty } => (Face::Top, ty, Some(group.as_str())),
            Slot::Side { ty } => (Face::Side, ty, None),
            Slot::Bottom { ty } => (Face::Bottom, ty, None),
        };
        let before = out.len();
        for (group, types) in groups.iter().filter(|(g, _)| wanted.is_none_or(|w| w == *g)) {
            if types.contains(ty) {
                out.push(TileFace {
                    group: group.clone(),
                    ty: ty.clone(),
                    face,
                    tile: *n,
                });
            }
        }
        if out.len() == before {
            return Err(format!("the manifest's {slot:?} is no cube in spec/spec/asset/cube.json"));
        }
    }
    Ok(out)
}

/// The table as `spec/spec/asset/ingested.json`, which `cargo spec`
/// renders into the host's table, the pack's layout and the catalog
/// (pxl-tool spec/ingested.rs, spec/catalog.rs).
pub fn render_json(rows: &[Row], pack: &Pack) -> String {
    let string = |s: &str| format!("{s:?}");
    let mut out = String::with_capacity(rows.len() * 160);
    out.push_str(
        r#"{
  "$doc": [
    "GENERATED by pxl-tool/bin/ingest_asset.rs — do not edit.",
    "Every shipped file by its path under asset/content/, in the ingest's sorted",
    "order, which numbers it below the asset root from 1: its bucket key (the",
    "SHA-256 of its bytes, which where it lies does not change), its size, and for",
    "a model its extent in ENU world units, measured from the glb. Then the",
    "texture pack, a file of the table: `columns` tiles of `cell` pixels per row,",
    "tile n at column n % columns and row n / columns, `tiles` the path each",
    "holds, `means` each one's mean color in linear light, and `faces` the cube",
    "face — group, type, face — each tile is."
  ],
  "files": [
"#,
    );
    let files: Vec<String> = rows
        .iter()
        .map(|r| {
            let extent = r.extent.map_or(String::new(), |e| format!(", \"extent\": [{}, {}, {}]", e[0], e[1], e[2]));
            format!("    {{ \"path\": {}, \"key\": {}, \"bytes\": {}{extent} }}", string(&r.path), string(&r.key), r.bytes)
        })
        .collect();
    out.push_str(&files.join(",\n"));
    out.push_str("\n  ],\n  \"pack\": {\n");
    let _ = writeln!(out, "    \"image\": {},", string(&pack.image));
    let _ = writeln!(out, "    \"cell\": {},", pack.cell);
    let _ = writeln!(out, "    \"columns\": {},", pack.columns);
    let tiles: Vec<String> = pack.tiles.iter().map(|t| format!("      {}", string(t))).collect();
    let _ = writeln!(out, "    \"tiles\": [\n{}\n    ],", tiles.join(",\n"));
    let means: Vec<String> = pack.means.iter().map(|m| format!("      [{}, {}, {}]", m[0], m[1], m[2])).collect();
    let _ = writeln!(out, "    \"means\": [\n{}\n    ],", means.join(",\n"));
    let faces: Vec<String> = pack
        .faces
        .iter()
        .map(|f| format!("      [{}, {}, {}, {}]", string(&f.group), string(&f.ty), string(f.face.name()), f.tile))
        .collect();
    let _ = writeln!(out, "    \"faces\": [\n{}\n    ]", faces.join(",\n"));
    out.push_str("  }\n}\n");
    out
}
