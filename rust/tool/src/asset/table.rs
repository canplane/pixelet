// pxl-tool/asset/table.rs

//! The ingested-asset table, rendered into TypeScript and Rust from the same rows.

use std::fmt::Write;

use crate::asset::pack::Slot;

pub struct Row {
    pub path: String,
    pub key: String,
    pub bytes: u64,
    pub extent: Option<[f64; 3]>,
}

pub struct Pack {
    /// The path its image ships at, a row of the table (`cube.json` `pack`).
    pub image: String,
    pub cell: u32,
    pub columns: u32,
    pub tiles: Vec<String>,
    pub means: Vec<[u8; 3]>,
    pub faces: Vec<TileFace>,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Face {
    Top,
    Side,
    Bottom,
}

impl Face {
    fn member(self) -> &'static str {
        match self {
            Face::Top => "Top",
            Face::Side => "Side",
            Face::Bottom => "Bottom",
        }
    }

    fn name(self) -> &'static str {
        match self {
            Face::Top => "top",
            Face::Side => "side",
            Face::Bottom => "bottom",
        }
    }
}

pub struct TileFace {
    /// The catalog's group, `ground` or `object`.
    pub group: String,
    pub ty: String,
    pub face: Face,
    pub tile: u32,
}

/// Each slot and the tile it wears; one tile may be several slots'. A slot
/// naming no catalog type is an error: a renamed type once left its blocks
/// untextured silently.
pub fn faces(slots: &[(u32, Slot)], groups: &[(String, Vec<String>)]) -> Result<Vec<TileFace>, String> {
    let mut out = Vec::new();
    for (n, slot) in slots {
        let (face, ty, wanted) = match slot {
            Slot::Top { group, ty } => (Face::Top, ty, Some(group.as_str())),
            Slot::Side { ty } => (Face::Side, ty, None),
            Slot::Bottom { ty } => (Face::Bottom, ty, None),
        };
        let before = out.len();
        for (group, types) in groups.iter().filter(|(g, _)| wanted.is_none_or(|w| w == *g)) {
            if types.contains(ty) {
                out.push(TileFace {
                    group: group.clone(),
                    ty: ty.clone(),
                    face,
                    tile: *n,
                });
            }
        }
        if out.len() == before {
            return Err(format!("the manifest's {slot:?} is no cube in spec/spec/asset/cube.json"));
        }
    }
    Ok(out)
}

/// An integral double needs a `.0`, or Rust reads it as an integer.
fn f64_literal(x: f64) -> String {
    let text = format!("{x}");
    if text.contains(['.', 'e', 'E']) {
        text
    } else {
        format!("{text}.0")
    }
}

pub fn ident(path: &str) -> String {
    path.chars().map(|c| if c.is_ascii_alphanumeric() || c == '_' { c } else { '_' }).collect()
}

pub fn render_ts(rows: &[Row], pack: &Pack) -> String {
    let mut out = String::with_capacity(rows.len() * 160);
    out.push_str(
        r#"// @pxl/client/catalog/asset/ingested.spec.ts
//
// GENERATED by pxl-tool/bin/ingest_asset.rs — do not edit.
// Every shipped asset by its path under asset/content/: the bucket key (the
// SHA-256 of its bytes, which where it lies does not change), its size, and for a
// model its extent in ENU world units, measured from the glb. A catalog names an
// asset by its path and reads its key here; the bytes themselves are in the bucket.

export interface IngestedAsset {
  key: string;
  bytes: number;
  /** ENU (x, y, z-up); absent for an image. */
  extent?: readonly [number, number, number];
}

export const INGESTED: Readonly<Record<string, IngestedAsset>> = {
"#,
    );
    for r in rows {
        let extent = match r.extent {
            Some(e) => format!(", extent: [{}, {}, {}]", e[0], e[1], e[2]),
            None => String::new(),
        };
        let _ = writeln!(out, "  \"{}\": {{ key: \"{}\", bytes: {}{} }},", r.path, r.key, r.bytes, extent);
    }
    out.push_str(
        r#"};

/** The texture pack as one image, the asset at `image`: `columns` tiles of
 * `cell` pixels per row, tile n at column n % columns and row n / columns,
 * `tiles` the asset path each holds, and `faces` the cube face — group,
 * type, face — each tile is. */
export const PACK = {
"#,
    );
    let _ = writeln!(out, "  image: \"{}\",", pack.image);
    let _ = writeln!(out, "  cell: {},", pack.cell);
    let _ = writeln!(out, "  columns: {},", pack.columns);
    out.push_str("  tiles: [\n");
    for t in &pack.tiles {
        let _ = writeln!(out, "    \"{t}\",");
    }
    out.push_str("  ],\n  faces: [\n");
    for f in &pack.faces {
        let _ = writeln!(out, "    [\"{}\", \"{}\", \"{}\", {}],", f.group, f.ty, f.face.name(), f.tile);
    }
    out.push_str("  ],\n} as const;\n");
    out
}

pub fn render_rs(rows: &[Row], pack: &Pack) -> String {
    let mut out = String::with_capacity(rows.len() * 160);
    out.push_str(
        r##"// pxl-spec/asset/ingested.spec.rs
//
// GENERATED by pxl-tool/bin/ingest_asset.rs — do not edit.
// Every shipped asset as a member of `Asset`, in the ingest's sorted order:
// its size, and for a model its extent in ENU world units, measured from the
// glb. A catalog names an asset by its member; its path and its bucket key are
// the shell's (ingested.spec.ts), and the bytes themselves are in the bucket.

#![allow(non_camel_case_types)]

use crate::asset::cube::{self, Cube};

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[repr(u16)]
pub enum Asset {
"##,
    );
    for (i, r) in rows.iter().enumerate() {
        let _ = writeln!(out, "    {} = {i},", ident(&r.path));
    }
    out.push_str("}\n\nimpl Asset {\n    /// Every asset, in the table's order.\n");
    let _ = writeln!(out, "    pub const ALL: [Asset; {}] = [", rows.len());
    for r in rows {
        let _ = writeln!(out, "        Asset::{},", ident(&r.path));
    }
    out.push_str(
        r##"    ];

    /// The asset a number names, or none for a number the table does not
    /// give out.
    pub fn of(value: u16) -> Option<Asset> {
        Asset::ALL.into_iter().find(|a| *a as u16 == value)
    }

    /// What the ingest measured of it.
    pub fn ingested(self) -> IngestedAsset {
        INGESTED[self as usize]
    }
}

#[derive(Clone, Copy, Debug, PartialEq)]
pub struct IngestedAsset {
    pub bytes: u64,
    /// ENU (x, y, z-up); None for an image.
    pub extent: Option<[f64; 3]>,
}

/// Each asset's row, at its member's number.
"##,
    );
    let _ = writeln!(out, "pub const INGESTED: [IngestedAsset; {}] = [", rows.len());
    for r in rows {
        let extent = match r.extent {
            Some(e) => format!("Some([{}, {}, {}])", f64_literal(e[0]), f64_literal(e[1]), f64_literal(e[2])),
            None => "None".to_string(),
        };
        let _ = writeln!(out, "    IngestedAsset {{ bytes: {}, extent: {extent} }},", r.bytes);
    }
    out.push_str(
        r##"];

/// Which of a box's images a tile is, as Minecraft's `cube_bottom_top`
/// names them. Which face of a box wears which is the renderer's
/// (paint.wgsl): a cell below the surface wears its bottom on every side.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum CubeFace {
    Top,
    Side,
    Bottom,
}

/// The texture pack as one image, the asset `image`, the file the cube
/// kind's definition references (`cube.json` `pack`): `columns` tiles of
/// `cell` pixels per row, tile n at column n % columns and row n / columns,
/// and `tiles` the cube face each tile is.
pub struct Pack {
    pub image: Asset,
    pub cell: u32,
    pub columns: u32,
    pub tiles: &'static [(Cube, CubeFace, u32)],
    /// What each tile reads as from far enough away that the tile itself is
    /// gone: its own mean color, taken in linear light. A mesh that
    /// summarizes a patch of ground takes its color from here rather than
    /// from the catalog's swatch, which is the color a type is filed under
    /// and not the color its material shows.
    pub means: &'static [[u8; 3]],
}

pub const PACK: Pack = Pack {
"##,
    );
    let _ = writeln!(out, "    image: Asset::{},", ident(&pack.image));
    let _ = writeln!(out, "    cell: {},", pack.cell);
    let _ = writeln!(out, "    columns: {},", pack.columns);
    out.push_str("    tiles: &[\n");
    for f in &pack.faces {
        let variant = if f.group == "object" { "Object" } else { "Ground" };
        let face = f.face.member();
        let _ = writeln!(out, "        (Cube::{variant}(cube::{variant}::{}), CubeFace::{face}, {}),", f.ty, f.tile);
    }
    out.push_str("    ],\n    means: &[\n");
    for m in &pack.means {
        let _ = writeln!(out, "        [{}, {}, {}],", m[0], m[1], m[2]);
    }
    out.push_str("    ],\n};\n");
    out
}
