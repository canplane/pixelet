// pxl-tool/spec/setting.rs

//! The settings, each by the number schema.json gives it, and a choice's
//! options by theirs; a number is given out once in its table. The kernel's
//! table carries the numbers and no names, which are the shell's, for its
//! rows and the locale. The shell gets a separate production table without
//! the `dev` settings so the bundler drops them.
//! A setting whose `kept` is false the kernel's store neither keeps nor reads.

use super::data::ts_literal;
use super::{
    casing_note, enum_name, file, js_num, line_comments, pascal, read, rs_doc, rs_ident, Node,
    Output,
};

const JSON: &str = "spec/client/kernel/domain/view/setting/schema.json";

struct Setting<'a> {
    key: &'a str,
    spec: &'a Node,
}

impl Setting<'_> {
    fn kind(&self) -> &str {
        self.spec.str_at("kind").unwrap_or_default()
    }
    fn options(&self) -> Option<&str> {
        self.spec.str_at("options")
    }
    fn flag(&self, name: &str) -> bool {
        self.spec.get(name) == Some(&Node::Bool(true))
    }
    /// Kept unless marked `"kept": false`; anything else there is refused.
    fn kept(&self) -> Result<bool, String> {
        match self.spec.get("kept") {
            None | Some(Node::Bool(true)) => Ok(true),
            Some(Node::Bool(false)) => Ok(false),
            Some(_) => Err(format!("{JSON}: {}'s kept is not a bool", self.key)),
        }
    }
    fn default(&self) -> &Node {
        self.spec
            .get("default")
            .map(Node::value)
            .unwrap_or(&Node::Null)
    }
}

struct List<'a> {
    name: &'a str,
    /// Each option and its number, in the JSON's order.
    values: Vec<(String, u32)>,
    doc: Option<Vec<String>>,
}

/// A number as schema.json gives one: a whole u32.
fn number(n: &Node, what: &str) -> Result<u32, String> {
    n.num()
        .filter(|v| v.fract() == 0.0 && *v >= 0.0 && *v <= u32::MAX as f64)
        .map(|v| v as u32)
        .ok_or(format!("{JSON}: {what}'s number is not a whole u32"))
}

/// A table's numbers are each given out once.
fn check_numbers(table: &str, numbered: &[(&str, u32)]) -> Result<(), String> {
    for (i, (name, n)) in numbered.iter().enumerate() {
        if let Some((other, _)) = numbered[..i].iter().find(|(_, m)| m == n) {
            return Err(format!("{JSON}: {table}'s {name} and {other} are both {n}"));
        }
    }
    Ok(())
}

pub fn outputs() -> Result<Vec<Output>, String> {
    let spec = read(JSON)?;
    let every = spec.get("SETTINGS").ok_or(format!("{JSON}: no SETTINGS"))?;
    let settings: Vec<Setting> = every
        .named()
        .map(|(key, spec)| Setting { key, spec })
        .collect();
    let numbers = settings
        .iter()
        .map(|s| {
            Ok((
                s.key,
                number(s.spec.get("number").unwrap_or(&Node::Null), s.key)?,
            ))
        })
        .collect::<Result<Vec<_>, String>>()?;
    check_numbers("SETTINGS", &numbers)?;
    let number_of = |s: &Setting| {
        numbers
            .iter()
            .find(|(k, _)| *k == s.key)
            .map(|(_, n)| *n)
            .unwrap_or_default()
    };
    let mut lists: Vec<List> = Vec::new();
    for (name, n) in spec.named() {
        if name == "SETTINGS" {
            continue;
        }
        let values = n
            .is_wrapper()
            .then(|| n.value())
            .filter(|v| v.is_obj())
            .ok_or(format!(
                "{JSON}: {name} is not a table of options by number"
            ))?;
        let values = values
            .named()
            .map(|(o, v)| Ok((o.to_string(), number(v, &format!("{name}'s {o}"))?)))
            .collect::<Result<Vec<_>, String>>()?;
        check_numbers(
            name,
            &values
                .iter()
                .map(|(o, v)| (o.as_str(), *v))
                .collect::<Vec<_>>(),
        )?;
        lists.push(List {
            name,
            values,
            doc: n.lines_at("$doc"),
        });
    }
    let list = |name: &str| lists.iter().find(|l| l.name == name);
    let options_of = |s: &Setting| {
        s.options()
            .and_then(list)
            .map(|l| l.values.clone())
            .ok_or(format!("{JSON}: {}'s options name no list", s.key))
    };
    let mut choices: Vec<&str> = Vec::new();
    for s in settings.iter().filter(|s| s.kind() == "choice") {
        let o = s.options().unwrap_or_default();
        if !choices.contains(&o) {
            choices.push(o);
        }
    }

    let mut rs = vec![
        "// pxl-kernel/domain/view/setting/schema.spec.rs".to_string(),
        "//".into(),
        "// GENERATED by pxl-tool/bin/spec.rs from schema.json — do not edit.".into(),
        "//".into(),
    ];
    rs.extend(line_comments(
        &spec.lines_at("$doc").unwrap_or_default(),
        "",
    ));
    rs.push(String::new());
    rs.extend(casing_note());
    rs.push("#![allow(non_camel_case_types)]".into());
    for name in &choices {
        let List { values, doc, .. } = list(name).ok_or(format!("{JSON}: no list {name}"))?;
        let e = enum_name(name);
        rs.push(String::new());
        rs.extend(rs_doc(doc.as_deref().unwrap_or_default(), "", "///"));
        rs.extend([
            "#[derive(Clone, Copy, Debug, PartialEq, Eq)]".to_string(),
            "#[repr(u32)]".into(),
            format!("pub enum {e} {{"),
        ]);
        rs.extend(
            values
                .iter()
                .map(|(v, n)| format!("    {} = {n},", rs_ident(v))),
        );
        rs.extend(["}".to_string(), String::new()]);
        rs.extend([
            format!("impl {e} {{"),
            format!(
                "    pub const ALL: [{e}; {}] = [{}];",
                values.len(),
                values
                    .iter()
                    .map(|(v, _)| format!("{e}::{}", rs_ident(v)))
                    .collect::<Vec<_>>()
                    .join(", ")
            ),
            String::new(),
            "    /// The option a number names, or none for a number the list does not give out."
                .into(),
            format!("    pub fn of(number: u32) -> Option<{e}> {{"),
            format!("        {e}::ALL.into_iter().find(|o| *o as u32 == number)"),
            "    }".into(),
            "}".into(),
        ]);
    }
    rs.extend(
        [
            "",
            "/// How a setting is held.",
            "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
            "pub enum SettingKind {",
            "    Toggle,",
            "    Choice,",
            "    Index,",
            "}",
        ]
        .map(String::from),
    );
    rs.extend(
        [
            "",
            "/// Every setting, by its number in schema.json's SETTINGS.",
            "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
            "#[repr(u32)]",
            "pub enum SettingKey {",
        ]
        .map(String::from),
    );
    for s in &settings {
        rs.extend(rs_doc(
            &s.spec.lines_at("$doc").unwrap_or_default(),
            "    ",
            "///",
        ));
        rs.push(format!("    {} = {},", s.key, number_of(s)));
    }
    rs.extend(["}".to_string(), String::new()]);
    let keys_where = |test: &dyn Fn(&Setting) -> bool| {
        let keys: Vec<String> = settings
            .iter()
            .filter(|s| test(s))
            .map(|s| format!("SettingKey::{}", s.key))
            .collect();
        if keys.is_empty() {
            "false".to_string()
        } else {
            format!("matches!(self, {})", keys.join(" | "))
        }
    };
    rs.extend([
        "impl SettingKey {".to_string(),
        format!(
            "    pub const ALL: [SettingKey; {}] = [{}];",
            settings.len(),
            settings
                .iter()
                .map(|s| format!("SettingKey::{}", s.key))
                .collect::<Vec<_>>()
                .join(", ")
        ),
        String::new(),
        "    /// One past the highest number: the length of a list of every".into(),
        "    /// setting's value at its number, where a number not given out stays 0.".into(),
        format!(
            "    pub const SLOTS: usize = {};",
            numbers
                .iter()
                .map(|(_, n)| *n as usize + 1)
                .max()
                .unwrap_or(0)
        ),
        String::new(),
        "    /// The setting a number names, or none for a number the table does not give out."
            .into(),
        "    pub fn of(number: u32) -> Option<SettingKey> {".into(),
        "        SettingKey::ALL.into_iter().find(|key| *key as u32 == number)".into(),
        "    }".into(),
        String::new(),
        "    pub fn kind(self) -> SettingKind {".into(),
        "        match self {".into(),
    ]);
    rs.extend(settings.iter().map(|s| {
        format!(
            "            SettingKey::{} => SettingKind::{},",
            s.key,
            pascal(s.kind())
        )
    }));
    let mut session = Vec::new();
    for s in &settings {
        if !s.kept()? {
            session.push(format!("SettingKey::{}", s.key));
        }
    }
    rs.extend([
        "        }".to_string(),
        "    }".into(),
        String::new(),
        "    /// Written to the settings' kept slot and read from it; one schema.json".into(),
        "    /// marks `kept` false is held for the session alone.".into(),
        "    pub fn is_kept(self) -> bool {".into(),
        if session.is_empty() {
            "        true".to_string()
        } else {
            format!("        !matches!(self, {})", session.join(" | "))
        },
        "    }".into(),
        String::new(),
        "    /// Offered by a development build only.".into(),
        "    pub fn dev(self) -> bool {".into(),
        format!("        {}", keys_where(&|s| s.flag("dev"))),
        "    }".into(),
        String::new(),
        "    /// A choice's option a development build only offers.".into(),
        "    pub fn dev_option(self, value: u32) -> bool {".into(),
        "        match self {".into(),
    ]);
    for s in settings
        .iter()
        .filter(|s| s.spec.get("dev_options").is_some())
    {
        let names = options_of(s)?;
        let dev: Vec<String> = s
            .spec
            .get("dev_options")
            .and_then(Node::arr)
            .unwrap_or_default()
            .iter()
            .filter_map(|n| n.str())
            .map(|n| {
                names
                    .iter()
                    .find(|(o, _)| o == n)
                    .map(|(_, number)| number.to_string())
                    .ok_or(format!(
                        "{JSON}: {}'s dev option {n} is not one of its options",
                        s.key
                    ))
            })
            .collect::<Result<_, _>>()?;
        rs.push(format!(
            "            SettingKey::{} => matches!(value, {}),",
            s.key,
            dev.join(" | ")
        ));
    }
    rs.extend([
        "            _ => false,".to_string(),
        "        }".into(),
        "    }".into(),
        "}".into(),
    ]);
    let field_type = |s: &Setting| -> Result<String, String> {
        match s.kind() {
            "toggle" => Ok("bool".to_string()),
            "choice" => Ok(enum_name(s.options().unwrap_or_default())),
            "index" => {
                let d = s
                    .spec
                    .get("default")
                    .ok_or(format!("{JSON}: {} has no default", s.key))?;
                match d.is_wrapper().then(|| d.str_at("$type")).flatten() {
                    Some(t @ ("u8" | "u16" | "u32")) => Ok(t.to_string()),
                    _ => Err(format!("{JSON}: {} is an index with no width", s.key)),
                }
            }
            kind => Err(format!(
                "{JSON}: {} is a setting of no kind there is: {kind}",
                s.key
            )),
        }
    };
    let default_lit = |s: &Setting| -> Result<String, String> {
        let d = s.default();
        if s.kind() == "choice" {
            let name = d.str().unwrap_or_default();
            if !options_of(s)?.iter().any(|(o, _)| o == name) {
                return Err(format!(
                    "{JSON}: {}'s default is not one of its options",
                    s.key
                ));
            }
            return Ok(format!(
                "{}::{}",
                enum_name(s.options().unwrap_or_default()),
                rs_ident(name)
            ));
        }
        Ok(match d {
            Node::Bool(b) => b.to_string(),
            Node::Num(n) => js_num(*n),
            Node::Str(s) => s.clone(),
            other => format!("{other:?}"),
        })
    };
    rs.extend(
        [
            "",
            "/// Every setting's value: what the store holds, and what the app reads.",
            "#[derive(Clone, Debug, PartialEq)]",
            "pub struct Settings {",
        ]
        .map(String::from),
    );
    for s in &settings {
        rs.push(format!("    pub {}: {},", s.key, field_type(s)?));
    }
    rs.extend(
        [
            "}",
            "",
            "impl Settings {",
            "    /// Every setting at schema.json's default.",
            "    pub const DEFAULT: Settings = Settings {",
        ]
        .map(String::from),
    );
    for s in &settings {
        rs.push(format!("        {}: {},", s.key, default_lit(s)?));
    }
    rs.extend(["    };".to_string(), String::new()]);
    rs.extend(
        [
            "    /// A setting's value as it crosses and is kept: a toggle's 0 or 1, a",
            "    /// choice's option by its number, an index as itself.",
            "    pub fn get(&self, key: SettingKey) -> u32 {",
            "        match key {",
        ]
        .map(String::from),
    );
    rs.extend(
        settings
            .iter()
            .map(|s| format!("            SettingKey::{0} => self.{0} as u32,", s.key)),
    );
    rs.extend(
        [
            "        }",
            "    }",
            "",
            "    /// Sets a setting from its value as it crosses; false, and nothing set,",
            "    /// for a value the setting cannot hold.",
            "    pub fn set(&mut self, key: SettingKey, value: u32) -> bool {",
            "        match key {",
        ]
        .map(String::from),
    );
    for s in &settings {
        let k = s.key;
        rs.push(match s.kind() {
            "toggle" => format!("            SettingKey::{k} if value <= 1 => self.{k} = value == 1,"),
            "choice" => format!(
                "            SettingKey::{k} => match {}::of(value) {{ Some(o) => self.{k} = o, None => return false }},",
                enum_name(s.options().unwrap_or_default())
            ),
            _ => format!(
                "            SettingKey::{k} => match {}::try_from(value) {{ Ok(n) => self.{k} = n, Err(_) => return false }},",
                field_type(s)?
            ),
        });
    }
    rs.extend(
        [
            "            _ => return false,",
            "        }",
            "        true",
            "    }",
            "}",
        ]
        .map(String::from),
    );

    let row = |s: &Setting| -> Result<Node, String> {
        let mut out: Vec<(String, Node)> = vec![(
            "key".to_string(),
            Node::Obj(vec![
                ("$value".to_string(), Node::Num(number_of(s) as f64)),
                ("$type".to_string(), Node::Str("u32".to_string())),
            ]),
        )];
        if let Some(doc) = s.spec.get("$doc") {
            out.push(("$doc".to_string(), doc.clone()));
        }
        for (f, v) in s.spec.entries() {
            if f == "$doc" || f == "number" {
                continue;
            }
            let value = match f.as_str() {
                "options" => Node::Obj(
                    options_of(s)?
                        .into_iter()
                        .map(|(o, n)| (o, Node::Num(n as f64)))
                        .collect(),
                ),
                "default" => v.value().clone(),
                _ => v.clone(),
            };
            match out.iter_mut().find(|(k, _)| k == f) {
                Some(slot) => slot.1 = value,
                None => out.push((f.clone(), value)),
            }
        }
        Ok(Node::Obj(out))
    };
    let table = |keep: &dyn Fn(&Setting) -> bool| -> Result<Node, String> {
        let mut out = Vec::new();
        for s in settings.iter().filter(|s| keep(s)) {
            out.push((s.key.to_string(), row(s)?));
        }
        Ok(Node::Obj(out))
    };
    let mut ts = vec![
        "// @pxl/client/abi/schema.spec.ts".to_string(),
        "//".into(),
        format!("// GENERATED by pxl-tool/bin/spec.rs from {JSON} — do not edit."),
        "//".into(),
    ];
    ts.extend(line_comments(
        &spec.lines_at("$doc").unwrap_or_default(),
        "",
    ));
    ts.extend([
        String::new(),
        format!(
            "export const SETTINGS = {} as const;",
            ts_literal(&table(&|_| true)?, "f64", "")?
        ),
    ]);
    ts.extend([
        String::new(),
        "/** SETTINGS without its `dev` entries: what a production bundle carries in its place. */"
            .into(),
        format!(
            "export const SETTINGS_SHIPPED = {} as const;",
            ts_literal(&table(&|s| !s.flag("dev"))?, "f64", "")?
        ),
    ]);

    Ok(vec![
        Output::new(
            "rust/client/kernel/src/domain/view/setting/schema.spec.rs",
            file(&rs),
        ),
        Output::new("ts/client/src/abi/schema.spec.ts", file(&ts)),
    ])
}
