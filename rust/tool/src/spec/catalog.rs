// pxl-tool/spec/catalog.rs

//! The catalog: every file reference the asset specs make, a slot each,
//! numbered in the kinds' order (id.json `KIND`). First the cube kind's pack,
//! then each decor variant's model and skin, then each `file` leaf of
//! actor.json and of sky.json in its document order. The Rust names each
//! slot; the catalog fills them with the file each names, by its number below
//! the asset root, and its extent (pxl-spec asset/catalog.rs reads the
//! layout). The host serves it, as hex in TypeScript.

use super::ingested::{files, INGESTED_JSON};
use super::{file, read, Node, Output};

/// A data spec's `$type` for a file reference: in Rust its slot, in
/// TypeScript its path.
pub const FILE: &str = "file";

pub const CUBE_JSON: &str = "spec/spec/asset/cube.json";
pub const DECOR_JSON: &str = "spec/spec/asset/decor.json";
const ACTOR_JSON: &str = "spec/spec/asset/actor.json";
const SKY_JSON: &str = "spec/spec/asset/sky.json";

/// Every slot's path, each spec's run of them in the kinds' order.
fn runs() -> Result<Vec<(&'static str, Vec<String>)>, String> {
    let pack = read(CUBE_JSON)?
        .get("pack")
        .map(Node::value)
        .and_then(Node::str)
        .map(str::to_string)
        .ok_or(format!("{CUBE_JSON}: no pack"))?;
    let mut decor = Vec::new();
    for (name, d) in read(DECOR_JSON)?.get("decors").ok_or(format!("{DECOR_JSON}: no decors"))?.entries() {
        for v in d.get("variants").and_then(Node::arr).ok_or(format!("{DECOR_JSON}: {name}.variants"))? {
            for field in ["model", "skin"] {
                decor.push(v.str_at(field).ok_or(format!("{DECOR_JSON}: {name}'s variant has no {field}"))?.to_string());
            }
        }
    }
    let mut out = vec![(CUBE_JSON, vec![pack]), (DECOR_JSON, decor)];
    for json in [ACTOR_JSON, SKY_JSON] {
        let mut paths = Vec::new();
        leaves(&read(json)?, None, &mut paths);
        out.push((json, paths));
    }
    Ok(out)
}

/// The `file` leaves under `n`, in document order, as data.rs renders them.
fn leaves(n: &Node, ty: Option<&str>, out: &mut Vec<String>) {
    let ty = n.str_at("$type").or(ty);
    match n {
        _ if n.is_wrapper() => leaves(n.value(), ty, out),
        Node::Str(s) if ty == Some(FILE) => out.push(s.clone()),
        Node::Arr(a) => a.iter().for_each(|e| leaves(e, ty, out)),
        Node::Obj(_) => n.named().for_each(|(_, v)| leaves(v, ty, out)),
        _ => {}
    }
}

/// The first slot of `json`'s references, and how many it makes.
pub fn run_of(json: &str) -> Result<(u16, u16), String> {
    let mut first = 0;
    for (j, paths) in runs()? {
        let n = u16::try_from(paths.len()).map_err(|e| e.to_string())?;
        if j == json {
            return Ok((first, n));
        }
        first += n;
    }
    Ok((first, 0))
}

pub fn outputs() -> Result<Vec<Output>, String> {
    let slots: Vec<String> = runs()?.into_iter().flat_map(|(_, p)| p).collect();
    let files = files()?;
    let mut bytes = (slots.len() as u32).to_le_bytes().to_vec();
    let mut extents = Vec::with_capacity(slots.len() * 24);
    for path in &slots {
        let row = files
            .iter()
            .position(|f| f.path == *path)
            .ok_or(format!("{path}, a slot's file, is no file of {INGESTED_JSON}: run the asset ingest"))?;
        bytes.extend((row as u32 + 1).to_le_bytes());
        for e in files[row].extent.unwrap_or([0.0; 3]) {
            extents.extend(e.to_le_bytes());
        }
    }
    bytes.extend(extents);
    let hex: String = bytes.iter().map(|b| format!("{b:02x}")).collect();
    let ts = [
        "// @pxl/client/namespace/catalog.spec.ts",
        "//",
        "// GENERATED by pxl-tool/bin/spec.rs from the asset specs and ingested.json — do not edit.",
        "//",
        "// The catalog the host plugs in, served below the asset root at `CATALOG`",
        "// (host/io/asset.ts): the file each of the kernel's slots names and its",
        "// extent, laid out as pxl-spec asset/catalog.rs reads it, in hex.",
        "",
    ]
    .map(String::from)
    .into_iter()
    .chain([format!("export const CATALOG_HEX = \"{hex}\";")])
    .collect::<Vec<_>>();
    let rs = [
        "// pxl-spec/asset/catalog.spec.rs",
        "//",
        "// GENERATED by pxl-tool/bin/spec.rs from the asset specs — do not edit.",
        "",
        "use super::Slot;",
        "",
        "/// Every file reference the asset specs make, a slot each.",
    ]
    .map(String::from)
    .into_iter()
    .chain([
        format!("pub const SLOTS: usize = {};", slots.len()),
        String::new(),
        "/// The cube kind's texture pack (cube.json `pack`).".to_string(),
        "pub const pack: Slot = Slot(0);".to_string(),
    ])
    .collect::<Vec<_>>();
    Ok(vec![
        Output::new("ts/client/src/namespace/catalog.spec.ts", file(&ts)),
        Output::new("rust/spec/src/asset/catalog.spec.rs", file(&rs)),
    ])
}
