use super::{file, json_str, line_comments, packed, read, rs_doc, Output};

pub fn published_outputs() -> Result<Vec<Output>, String> {
    let spec = read("spec/spec/bake/published.json")?;
    let format = spec.get("FORMAT").ok_or("published.json: no FORMAT")?;
    let format_doc = format.lines_at("$doc").unwrap_or_default();
    let mut formats: Vec<(&str, u32)> = Vec::new();
    for (k, n) in format.entries().iter().filter(|(k, _)| !k.starts_with('$')) {
        let n = n
            .num()
            .ok_or(format!("published.json: FORMAT.{k} is no number"))?;
        if n < 1.0 || n.fract() != 0.0 {
            return Err(format!(
                "published.json: FORMAT.{k} {n} is not a format number"
            ));
        }
        formats.push((k, n as u32));
    }
    let version_bytes = spec
        .get("VERSION_BYTES")
        .and_then(|n| n.num())
        .filter(|n| *n >= 1.0 && n.fract() == 0.0)
        .ok_or("published.json: VERSION_BYTES is no count")? as u32;
    let version_doc = spec.lines_at("$VERSION_BYTES").unwrap_or_default();
    let head = [
        "//".to_string(),
        "// GENERATED by pxl-tool/bin/spec.rs from published.json — do not edit.".into(),
        "".into(),
    ];
    let list = |f: &dyn Fn(&str) -> String| {
        formats
            .iter()
            .map(|(k, _)| f(k))
            .collect::<Vec<_>>()
            .join(", ")
    };

    let mut ts = vec!["// @pxl/client/namespace/published.spec.ts".to_string()];
    ts.extend(head.iter().cloned());
    ts.push("/** The base layers by the number the kernel names one by: the root a bake's objects are opened below (xpute's OPENAT). */".into());
    ts.push(format!(
        "export const BASE_LAYERS = [{}] as const;",
        list(&|k| json_str(k))
    ));
    ts.extend([
        "".to_string(),
        "export type BaseLayer = typeof BASE_LAYERS[number];".into(),
        "".into(),
        format!("/** {} */", version_doc.join(" ")),
        format!("export const VERSION_BYTES = {version_bytes};"),
    ]);

    // The Worker's own: it is bundled for the Workers runtime, apart from the
    // client, so it reads a copy beside it written from the same JSON.
    let mut edge = vec!["// @pxl/edge/published.spec.ts".to_string()];
    edge.extend(head.iter().cloned());
    edge.push("/** The base layers, each a kind a baked page is published under. */".into());
    edge.push(format!(
        "export const BASE_LAYERS = [{}] as const;",
        list(&|k| json_str(k))
    ));

    let mut rs = vec!["// pxl-spec/bake/published.spec.rs".to_string()];
    rs.extend(head);
    rs.extend(rs_doc(&format_doc, "", "///"));
    rs.push("pub struct Format {".into());
    rs.extend(formats.iter().map(|(k, _)| format!("    pub {k}: u32,")));
    rs.extend([
        "}".to_string(),
        String::new(),
        "pub const FORMAT: Format = Format {".into(),
    ]);
    rs.extend(formats.iter().map(|(k, n)| format!("    {k}: {n},")));
    rs.extend(["};", ""].map(String::from));
    rs.extend(rs_doc(&version_doc, "", "///"));
    rs.push(format!("pub const VERSION_BYTES: usize = {version_bytes};"));
    rs.push(String::new());
    rs.extend(
        [
            "/// The base layers a version is published for: the kinds of `FORMAT`,",
            "/// numbered in their order.",
            "#[expect(non_camel_case_types, reason = \"generated from the spec\")]",
            "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
            "#[repr(u32)]",
            "pub enum BaseLayer {",
        ]
        .map(String::from),
    );
    rs.extend(formats.iter().map(|(k, _)| format!("    {k},")));
    rs.extend([
        "}".to_string(),
        String::new(),
        "impl BaseLayer {".into(),
        format!(
            "    pub const ALL: [BaseLayer; {}] = [{}];",
            formats.len(),
            list(&|k| format!("BaseLayer::{k}"))
        ),
        String::new(),
        "    /// The layer a number names, or none for a number nobody gave out.".into(),
        "    pub fn of(number: u32) -> Option<BaseLayer> {".into(),
        "        BaseLayer::ALL.into_iter().find(|k| *k as u32 == number)".into(),
        "    }".into(),
        String::new(),
        "    pub fn name(self) -> &'static str {".into(),
        "        match self {".into(),
    ]);
    rs.extend(
        formats
            .iter()
            .map(|(k, _)| format!("            BaseLayer::{k} => {},", json_str(k))),
    );
    rs.extend(
        [
            "        }",
            "    }",
            "}",
            "",
            "impl Format {",
            "    /// `FORMAT[layer]`.",
            "    pub fn of(&self, layer: BaseLayer) -> u32 {",
            "        match layer {",
        ]
        .map(String::from),
    );
    rs.extend(
        formats
            .iter()
            .map(|(k, _)| format!("            BaseLayer::{k} => self.{k},")),
    );
    rs.extend(["        }", "    }", "}"].map(String::from));
    Ok(vec![
        Output::new("ts/client/src/namespace/published.spec.ts", file(&ts)),
        Output::new("ts/server/edge/published.spec.ts", file(&edge)),
        Output::new("rust/spec/src/bake/published.spec.rs", file(&rs)),
    ])
}

pub fn object_outputs() -> Result<Vec<Output>, String> {
    let json = "spec/spec/bake/object.json";
    let spec = read(json)?;
    let doc = spec.lines_at("$doc").unwrap_or_default();
    let tiers = spec
        .get("OBJECT_TIERS")
        .and_then(|n| n.num())
        .ok_or(format!("{json}: no OBJECT_TIERS"))?;
    if tiers < 1.0 || tiers.fract() != 0.0 {
        return Err(format!("{json}: OBJECT_TIERS {tiers} is not a count"));
    }
    let tiers = tiers as u32;
    let head = [
        "//".to_string(),
        "// GENERATED by pxl-tool/bin/spec.rs from object.json — do not edit.".into(),
        "".into(),
    ];

    let mut ts = vec!["// @pxl/client/shell/world/object.spec.ts".to_string()];
    ts.extend(head.iter().cloned());
    ts.push("/**".into());
    ts.extend(doc.iter().map(|l| {
        if l.is_empty() {
            " *".to_string()
        } else {
            format!(" * {l}")
        }
    }));
    ts.extend([
        " */".to_string(),
        format!("export const OBJECT_TIERS = {tiers};"),
    ]);

    let mut rs = vec!["// pxl-spec/bake/object.spec.rs".to_string()];
    rs.extend(head);
    rs.extend(rs_doc(&doc, "", "///"));
    rs.push(format!("pub const OBJECT_TIERS: usize = {tiers};"));
    Ok(vec![
        Output::new("ts/client/src/shell/world/object.spec.ts", file(&ts)),
        Output::new("rust/spec/src/bake/object.spec.rs", file(&rs)),
    ])
}

// The Rust reads a place's look by its category number: per category, in lists the
// kernel indexes, what Carto draws for it, with 0 for a zoom it never shows at.

pub fn place_theme_outputs() -> Result<Vec<Output>, String> {
    let (cat_json, theme_json) = (
        "spec/spec/bake/place_category.json",
        "spec/spec/bake/place_theme.json",
    );
    let (cat, theme) = (read(cat_json)?, read(theme_json)?);
    let categories: Vec<&str> = cat
        .get("CATEGORIES")
        .and_then(|c| c.arr())
        .ok_or(format!("{cat_json}: no CATEGORIES"))?
        .iter()
        .filter_map(|k| k.str())
        .collect();
    // A category is a half-word on the wire, and 0 is none.
    if categories.len() >= u16::MAX as usize {
        return Err(format!(
            "{cat_json}: {} categories do not fit a half-word beside none",
            categories.len()
        ));
    }
    let rows = theme
        .get("THEME")
        .ok_or(format!("{theme_json}: no THEME"))?;
    if let Some((k, _)) = rows.named().find(|(k, _)| !categories.contains(k)) {
        return Err(format!("{theme_json}: {k} is no category of {cat_json}"));
    }
    let zoom = |k: &str, f: &str| -> Result<String, String> {
        match rows.get(k).and_then(|r| r.get(f)) {
            None => Ok("0".into()),
            Some(z) => z
                .num()
                .filter(|z| (1.0..=31.0).contains(z) && z.fract() == 0.0)
                .map(|z| format!("{z}"))
                .ok_or(format!("{theme_json}: {k}.{f} is not a zoom")),
        }
    };
    let color = |k: &str, f: &str| -> Result<String, String> {
        match rows.get(k).and_then(|r| r.str_at(f)) {
            None => Ok("0".into()),
            Some(c) => packed(c).map(|n| format!("0x{n:06x}ff")),
        }
    };
    let mut rs = vec![
        "// pxl-spec/bake/place_theme.spec.rs".to_string(),
        "//".into(),
        "// GENERATED by pxl-tool/bin/spec.rs from place_category.json and place_theme.json — do not edit.".into(),
        "//".into(),
    ];
    rs.extend(line_comments(&cat.lines_at("$doc").unwrap_or_default(), ""));
    rs.push("//".into());
    rs.extend(line_comments(
        &theme.lines_at("$doc").unwrap_or_default(),
        "",
    ));
    let mut list = |doc: &str,
                    ty: &str,
                    name: &str,
                    each: &dyn Fn(&str) -> Result<String, String>|
     -> Result<(), String> {
        rs.extend([
            String::new(),
            format!("/// {doc}, category k at `{name}[k - 1]`."),
            format!("pub const {name}: [{ty}; {}] = [", categories.len()),
        ]);
        for k in &categories {
            rs.push(format!("    {},", each(k)?));
        }
        rs.push("];".into());
        Ok(())
    };
    list(
        "Each category's Overture name",
        "&str",
        "CATEGORIES",
        &|k| Ok(json_str(k)),
    )?;
    list(
        "The zoom from which Carto draws a category as a dot, 0 for never",
        "u8",
        "DOT_ZOOM",
        &|k| zoom(k, "dot"),
    )?;
    list(
        "The zoom from which Carto draws a category's icon, 0 for never",
        "u8",
        "ICON_ZOOM",
        &|k| zoom(k, "icon"),
    )?;
    list(
        "The zoom from which Carto names a category, 0 for never",
        "u8",
        "LABEL_ZOOM",
        &|k| zoom(k, "label"),
    )?;
    list(
        "A category's icon or dot fill as `0xRRGGBBAA`",
        "u32",
        "FILL",
        &|k| color(k, "fill"),
    )?;
    list(
        "A category's label fill, its ink, as `0xRRGGBBAA`",
        "u32",
        "INK",
        &|k| color(k, "text"),
    )?;
    list(
        "A category's icon under Carto's `symbols/`, \"\" for none",
        "&str",
        "SYMBOL",
        &|k| {
            Ok(json_str(
                rows.get(k)
                    .and_then(|r| r.str_at("symbol"))
                    .unwrap_or_default(),
            ))
        },
    )?;
    Ok(vec![Output::new(
        "rust/spec/src/bake/place_theme.spec.rs",
        file(&rs),
    )])
}
