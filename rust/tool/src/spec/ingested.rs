// pxl-tool/spec/ingested.rs

//! What the asset ingest wrote (`spec/spec/asset/ingested.json`), rendered:
//! the host's table, which binds a file's number to its bucket key, and the
//! texture pack's layout, which the renderer reads.

use std::fmt::Write;

use super::{file, read, Node, Output};

pub const INGESTED_JSON: &str = "spec/spec/asset/ingested.json";

pub struct File {
    pub path: String,
    key: String,
    bytes: u64,
    /// ENU (x, y, z-up); None for an image.
    pub extent: Option<[f64; 3]>,
}

/// Every file, in the order that numbers it below the asset root from 1.
pub fn files() -> Result<Vec<File>, String> {
    let spec = read(INGESTED_JSON)?;
    let rows = spec
        .get("files")
        .and_then(Node::arr)
        .ok_or(format!("{INGESTED_JSON}: no files"))?;
    rows.iter()
        .map(|r| {
            let at = |field: &str| format!("{INGESTED_JSON}: a file's {field}");
            let extent = match r.get("extent").and_then(Node::arr) {
                None => None,
                Some(e) => Some(
                    e.iter()
                        .map(Node::num)
                        .collect::<Option<Vec<_>>>()
                        .and_then(|e| e.try_into().ok())
                        .ok_or(at("extent"))?,
                ),
            };
            Ok(File {
                path: r.str_at("path").ok_or(at("path"))?.to_string(),
                key: r.str_at("key").ok_or(at("key"))?.to_string(),
                bytes: r.get("bytes").and_then(Node::num).ok_or(at("bytes"))? as u64,
                extent,
            })
        })
        .collect()
}

struct Pack {
    image: String,
    cell: u32,
    columns: u32,
    tiles: Vec<String>,
    means: Vec<[u32; 3]>,
    /// Group, type, face, tile.
    faces: Vec<(String, String, String, u32)>,
}

fn pack() -> Result<Pack, String> {
    let spec = read(INGESTED_JSON)?;
    let p = spec
        .get("pack")
        .ok_or(format!("{INGESTED_JSON}: no pack"))?;
    let at = |field: &str| format!("{INGESTED_JSON}: pack.{field}");
    let whole = |n: &Node| {
        n.num()
            .filter(|n| n.fract() == 0.0 && *n >= 0.0)
            .map(|n| n as u32)
    };
    let list = |field: &str| p.get(field).and_then(Node::arr).ok_or(at(field));
    let means = list("means")?
        .iter()
        .map(|m| {
            m.arr()
                .and_then(|m| m.iter().map(whole).collect::<Option<Vec<_>>>())
                .and_then(|m| m.try_into().ok())
        })
        .collect::<Option<Vec<_>>>()
        .ok_or(at("means"))?;
    let faces = list("faces")?
        .iter()
        .map(|f| match f.arr()? {
            [g, t, face, n] => Some((
                g.str()?.to_string(),
                t.str()?.to_string(),
                face.str()?.to_string(),
                whole(n)?,
            )),
            _ => None,
        })
        .collect::<Option<Vec<_>>>()
        .ok_or(at("faces"))?;
    Ok(Pack {
        image: p.str_at("image").ok_or(at("image"))?.to_string(),
        cell: p.get("cell").and_then(whole).ok_or(at("cell"))?,
        columns: p.get("columns").and_then(whole).ok_or(at("columns"))?,
        tiles: list("tiles")?
            .iter()
            .map(|t| t.str().map(str::to_string))
            .collect::<Option<Vec<_>>>()
            .ok_or(at("tiles"))?,
        means,
        faces,
    })
}

pub fn outputs() -> Result<Vec<Output>, String> {
    let (rows, pack) = (files()?, pack()?);
    Ok(vec![
        Output::new(
            "ts/client/src/namespace/ingested.spec.ts",
            render_ts(&rows, &pack),
        ),
        Output::new("rust/spec/src/asset/ingested.spec.rs", render_rs(&pack)?),
    ])
}

fn render_ts(rows: &[File], pack: &Pack) -> String {
    let mut out = String::with_capacity(rows.len() * 160);
    out.push_str(
        r#"// @pxl/client/namespace/ingested.spec.ts
//
// GENERATED by pxl-tool/bin/spec.rs from ingested.json — do not edit.
// Every shipped asset by its path under asset/content/: the bucket key (the
// SHA-256 of its bytes, which where it lies does not change), its size, and for a
// model its extent in ENU world units, measured from the glb. A catalog names an
// asset by its path and reads its key here; the bytes themselves are in the bucket.
// Its order numbers each file below the asset root, from 1 (host/io/asset.ts).

export interface IngestedFile {
  key: string;
  bytes: number;
  /** ENU (x, y, z-up); absent for an image. */
  extent?: readonly [number, number, number];
}

export const INGESTED: Readonly<Record<string, IngestedFile>> = {
"#,
    );
    for r in rows {
        let extent = match r.extent {
            Some(e) => format!(", extent: [{}, {}, {}]", e[0], e[1], e[2]),
            None => String::new(),
        };
        let _ = writeln!(
            out,
            "  \"{}\": {{ key: \"{}\", bytes: {}{} }},",
            r.path, r.key, r.bytes, extent
        );
    }
    out.push_str(
        r#"};

/** The texture pack as one image, the asset at `image`: `columns` tiles of
 * `cell` pixels per row, tile n at column n % columns and row n / columns,
 * `tiles` the asset path each holds, and `faces` the cube face — group,
 * type, face — each tile is. */
export const PACK = {
"#,
    );
    let _ = writeln!(out, "  image: \"{}\",", pack.image);
    let _ = writeln!(out, "  cell: {},", pack.cell);
    let _ = writeln!(out, "  columns: {},", pack.columns);
    out.push_str("  tiles: [\n");
    for t in &pack.tiles {
        let _ = writeln!(out, "    \"{t}\",");
    }
    out.push_str("  ],\n  faces: [\n");
    for (group, ty, face, tile) in &pack.faces {
        let _ = writeln!(out, "    [\"{group}\", \"{ty}\", \"{face}\", {tile}],");
    }
    out.push_str("  ],\n} as const;\n");
    out
}

fn render_rs(pack: &Pack) -> Result<String, String> {
    let mut out = vec![
        r##"// pxl-spec/asset/ingested.spec.rs
//
// GENERATED by pxl-tool/bin/spec.rs from ingested.json — do not edit.
// The texture pack as the asset ingest composed it: which of its tiles each
// cube wears on which face, and what each reads as from afar. Its image is
// the file the catalog names for the cube kind's pack (catalog.spec.rs
// `pack`).

use crate::asset::cube::{self, Cube};

/// Which of a box's images a tile is, as Minecraft's `cube_bottom_top`
/// names them. Which face of a box wears which is the renderer's
/// (paint.wgsl): a cell below the surface wears its bottom on every side.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum CubeFace {
    Top,
    Side,
    Bottom,
}

/// The texture pack as one image: `columns` tiles of `cell` pixels per row,
/// tile n at column n % columns and row n / columns, `tiles` the cube face
/// each tile is, and `sentinels` the tile a sentinel the world draws wears.
pub struct Pack {
    pub cell: u32,
    pub columns: u32,
    pub tiles: &'static [(Cube, CubeFace, u32)],
    pub sentinels: &'static [(u8, u32)],
    /// What each tile reads as from far enough away that the tile itself is
    /// gone: its own mean color, taken in linear light. A mesh that
    /// summarizes a patch of ground takes its color from here rather than
    /// from the catalog's swatch, which is the color a type is filed under
    /// and not the color its material shows.
    pub means: &'static [[u8; 3]],
}

pub const PACK: Pack = Pack {"##
            .to_string(),
        format!("    cell: {},", pack.cell),
        format!("    columns: {},", pack.columns),
        "    tiles: &[".to_string(),
    ];
    for (group, ty, face, tile) in pack.faces.iter().filter(|f| f.0 != "sentinel") {
        let variant = if group == "object" {
            "Object"
        } else {
            "Ground"
        };
        let face = match face.as_str() {
            "top" => "Top",
            "side" => "Side",
            "bottom" => "Bottom",
            _ => return Err(format!("{INGESTED_JSON}: pack.faces: {face} is no face")),
        };
        out.push(format!(
            "        (Cube::{variant}(cube::{variant}::{ty}), CubeFace::{face}, {tile}),"
        ));
    }
    out.push("    ],".to_string());
    out.push("    sentinels: &[".to_string());
    out.extend(
        pack.faces
            .iter()
            .filter(|f| f.0 == "sentinel")
            .map(|(_, ty, _, tile)| format!("        (cube::sentinel::{ty}, {tile}),")),
    );
    out.push("    ],".to_string());
    out.push("    means: &[".to_string());
    out.extend(
        pack.means
            .iter()
            .map(|m| format!("        [{}, {}, {}],", m[0], m[1], m[2])),
    );
    out.extend(["    ],".to_string(), "};".to_string()]);
    Ok(file(&out))
}
