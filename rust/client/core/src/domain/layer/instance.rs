// pxl-core/domain/layer/instance.rs

//! A thing drawn as one instance of its model, whichever layer it comes from.
//! Its `id` is its asset's id, and `meta` is what its decor carries. The
//! ground generates its own instances; a placed object's instance comes from
//! its placement.

use pxl_spec::asset::decor::DecorMeta;
use pxl_spec::asset::AssetId;
use pxl_spec::space::coord::aabb::Aabb;
use pxl_spec::space::coord::v3::V3;
use pxl_spec::space::coord::world::cube;
use pxl_spec::space::layer::lattice::GROUND;

use pxl_spec::space::layer::octant::Octant;

#[derive(Clone, Copy, Debug, PartialEq)]
pub(crate) struct Instance {
    pub id: AssetId,
    /// Where it stands: the middle of its footprint, at the height of its
    /// base.
    pub at: V3,
    pub src: Source,
    pub meta: DecorMeta,
}

/// The layer an instance comes from, and where in that layer it is held.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum Source {
    /// Generated by the ground, in the leaf cell it stands on.
    Ground([i32; 3]),
    /// Placed as an object, at its entry in the object layer.
    Object(Octant),
}

impl Instance {
    /// The leaf cell the ground generated it in; none for a placed one.
    pub(crate) fn generated_in(&self) -> Option<[i32; 3]> {
        match self.src {
            Source::Ground(cell) => Some(cell),
            Source::Object(_) => None,
        }
    }

    /// The cell it stands in: the leaf cell the ground generated it in, or
    /// the cell of its entry for a placed one.
    pub(crate) fn octant(&self) -> Octant {
        match self.src {
            Source::Ground(cell) => Octant::new(GROUND.leaf_cell_zoom(), cell),
            Source::Object(e) => e,
        }
    }

    /// The cube of the cell it stands in.
    pub(crate) fn cell(&self) -> Aabb {
        match self.src {
            Source::Ground(cell) => cube(GROUND.leaf_cell_zoom(), cell),
            Source::Object(e) => cube(e.zoom(), e.at()),
        }
    }
}
