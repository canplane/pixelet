// pxl-kernel/domain/layer/instance.rs

//! A thing drawn as one instance of its shape, whichever layer answers it:
//! its id is its kind over its shape (the asset catalog's), and `meta` is what
//! its decor carries. The ground generates its own; an object's is the placement's.

use pxl_spec::asset::decor::DecorMeta;
use pxl_spec::space::coord::aabb::Aabb;
use pxl_spec::space::coord::v3::V3;
use pxl_spec::space::coord::zoom::cube;
use pxl_spec::space::layer::lattice::GROUND;

use pxl_spec::bake::constant::EntryAt;

#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Instance {
    pub id: u16,
    /// Where it stands: its footprint's middle, at the height of its base.
    pub at: V3,
    pub src: Source,
    pub meta: DecorMeta,
}

/// Which layer's record it is.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Source {
    /// Generated by the ground, in the leaf cell it stands on.
    Ground([i32; 3]),
    /// Placed, at its entry.
    Object(EntryAt),
}

impl Instance {
    /// The leaf cell the ground generated it in; none for a placed one.
    pub fn generated_in(&self) -> Option<[i32; 3]> {
        match self.src {
            Source::Ground(cell) => Some(cell),
            Source::Object(_) => None,
        }
    }

    /// The cell it stands in: the leaf the ground generated it in, or its entry's.
    pub fn cell(&self) -> Aabb {
        match self.src {
            Source::Ground(cell) => cube(GROUND.cell(), cell),
            Source::Object(e) => cube(e.zoom(), e.at()),
        }
    }
}
