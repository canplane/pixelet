use regex::Regex;

use super::{align_star, casing_note, file, js_num, json_str, pascal, pretty, read, rgb_literal, rs_doc, rs_ident, ts_doc, Node, Output};

const CUBE_TYPE_JSON: &str = "spec/spec/cell/cube_type.json";
const DECOR_JSON: &str = "spec/spec/cell/decor.json";

/// How the renderer draws a ground look, numbered as pxl-render's material classes.
const KINDS: [&str; 4] = ["land", "water", "transport", "structure"];

struct Entry<'a> {
    name: &'a str,
    value: u32,
    kind: Option<&'a str>,
    shift: Option<f64>,
    doc: Option<Vec<String>>,
}

/// A list's entries in order, a section heading as `Err(title)`.
fn entries<'a>(list: &'a Node, what: &str) -> Result<Vec<Result<Entry<'a>, &'a str>>, String> {
    let list = list
        .get("entries")
        .and_then(Node::arr)
        .or_else(|| list.arr())
        .ok_or(format!("{CUBE_TYPE_JSON}: {what} has no entries"))?;
    list.iter()
        .map(|e| {
            if let Some(section) = e.str_at("section") {
                return Ok(Err(section));
            }
            let name = e.str_at("name").ok_or(format!("{CUBE_TYPE_JSON}: {what}: an entry with no name"))?;
            let value = e.get("value").and_then(Node::num).ok_or(format!("{CUBE_TYPE_JSON}: {name} has no value"))? as u32;
            Ok(Ok(Entry {
                name,
                value,
                kind: e.str_at("kind"),
                shift: e.get("shift").and_then(Node::num),
                doc: e.lines_at("doc"),
            }))
        })
        .collect()
}

fn named<'l, 'a>(list: &'l [Result<Entry<'a>, &'a str>]) -> impl Iterator<Item = &'l Entry<'a>> {
    list.iter().filter_map(|e| e.as_ref().ok())
}

/// The ground's looks by kind and the object's colors as `block`: the groups a
/// texture's file name is prefixed by.
pub fn catalog() -> Result<Vec<(String, Vec<String>)>, String> {
    let spec = read(CUBE_TYPE_JSON)?;
    let ground = entries(spec.get("ground").ok_or("no ground")?, "ground")?;
    let object = entries(spec.get("object").ok_or("no object")?, "object")?;
    let mut groups: Vec<(String, Vec<String>)> = KINDS
        .iter()
        .map(|k| (k.to_string(), named(&ground).filter(|e| e.kind == Some(*k)).map(|e| e.name.to_string()).collect()))
        .collect();
    groups.push(("block".into(), named(&object).filter(|e| e.value > 256).map(|e| e.name.to_string()).collect()));
    Ok(groups)
}

pub fn color_outputs() -> Result<Vec<Output>, String> {
    let spec = read("spec/spec/cell/color.json")?;
    let head: Vec<String> = [
        "//",
        "// GENERATED by pxl-tool/bin/spec.rs from color.json — do not edit.",
        "//",
        "// The color of every look and every placed color: what a cube *is* to",
        "// the eye when no texture is drawn over it — everything drawn with the",
        "// pack off reads this, the coarse tiers included, which summarize it",
        "// the way they summarize the tiles with the pack on",
        "// (pxl-render mesh/chunk.rs). A texture pack decorates these; it",
        "// does not replace them.",
    ]
    .map(String::from)
    .to_vec();

    let mut with_rgb = Vec::new();
    for (group, entries) in spec.entries() {
        if group == "_meta" {
            with_rgb.push((group.clone(), entries.clone()));
            continue;
        }
        let mut packed_entries = Vec::new();
        for (n, e) in entries.entries() {
            let hex = e.str_at("hex").ok_or(format!("color.json: {group}.{n} has no hex"))?;
            let mut fields: Vec<(String, Node)> = e.entries().to_vec();
            fields.push(("rgb".to_string(), Node::Num(super::packed(hex)? as f64)));
            packed_entries.push((n.clone(), Node::Obj(fields)));
        }
        with_rgb.push((group.clone(), Node::Obj(packed_entries)));
    }
    let mut json = String::new();
    pretty(&Node::Obj(with_rgb), "", &mut json);
    let bare_keys = Regex::new(r#""([A-Za-z_][A-Za-z0-9_]*)":"#).map_err(|e| e.to_string())?;
    let close_brace = Regex::new(r"\n(\s*)\}").map_err(|e| e.to_string())?;
    let close_bracket = Regex::new(r"\n(\s*)\]").map_err(|e| e.to_string())?;
    let json = bare_keys.replace_all(&json, "$1:");
    let json = close_brace.replace_all(&json, ",\n$1}");
    let json = close_bracket.replace_all(&json, ",\n$1]");
    let mut ts = vec!["// @pxl/web/catalog/cell/color.spec.ts".to_string()];
    ts.extend(head.iter().cloned());
    ts.extend([String::new(), format!("export default {json};")]);

    let types = read(CUBE_TYPE_JSON)?;
    let mut rs = vec!["// pxl-spec/cell/color.spec.rs".to_string()];
    rs.extend(head);
    rs.push(String::new());
    rs.extend(casing_note());
    rs.extend(["", "use super::cube_type::cube_types;", "use super::Swatch;"].map(String::from));
    let groups = [("sentinel", "sentinel", "u8"), ("ground", "ground", "u8"), ("object", "object", "u16")];
    for (group, module, width) in groups {
        let list = entries(
            if group == "sentinel" {
                types.get("sentinel").ok_or("no sentinel")?
            } else {
                types.get(group).ok_or(format!("no {group}"))?
            },
            group,
        )?;
        let colors = spec.get(group).ok_or(format!("color.json has no {group}"))?;
        rs.extend([
            String::new(),
            format!("/// `{group}`'s color for a value."),
            format!("pub const fn {group}(t: {width}) -> Option<Swatch> {{"),
            "    match t {".to_string(),
        ]);
        for (name, entry) in colors.entries() {
            if !named(&list).any(|e| e.name == name.as_str()) {
                return Err(format!("color.json: {group}.{name} is nothing cube_type.json names"));
            }
            if let Some(note) = entry.str_at("note") {
                rs.push(format!("        // {note}"));
            }
            let hex = entry.str_at("hex").ok_or(format!("color.json: {group}.{name} has no hex"))?;
            rs.push(format!("        cube_types::{module}::{} => Some(Swatch::new({})),", rs_ident(name), rgb_literal(hex)?));
        }
        if group == "ground" {
            for e in named(&list) {
                if colors.get(e.name).is_none() {
                    return Err(format!("color.json: ground.{} has no color", e.name));
                }
            }
            rs.push("        // A sentinel a baked cell can hold.".to_string());
            rs.push("        _ => sentinel(t),".to_string());
        } else {
            rs.push("        _ => None,".to_string());
        }
        rs.extend(["    }", "}"].map(String::from));
    }
    Ok(vec![
        Output::new("apps/web/src/catalog/cell/color.spec.ts", file(&ts)),
        Output::new("crates/spec/src/cell/color.spec.rs", file(&rs)),
    ])
}

pub fn cube_type_outputs() -> Result<Vec<Output>, String> {
    let spec = read(CUBE_TYPE_JSON)?;
    let sentinel = entries(spec.get("sentinel").ok_or("no sentinel")?, "sentinel")?;
    let ground_node = spec.get("ground").ok_or("no ground")?;
    let ground = entries(ground_node, "ground")?;
    let object_node = spec.get("object").ok_or("no object")?;
    let object = entries(object_node, "object")?;
    let base = spec.get("base").ok_or(format!("{CUBE_TYPE_JSON}: no base"))?;
    let base_type = base.str_at("type").ok_or("base has no type")?;

    // One value space: the sentinels and the looks within a byte, the object's own and decor past it.
    let decor = read(DECOR_JSON)?;
    let decor: Vec<(&str, u32)> = decor
        .get("decor_types")
        .ok_or(format!("{DECOR_JSON}: no decor_types"))?
        .entries()
        .iter()
        .map(|(k, v)| v.get("value").and_then(Node::num).map(|n| (k.as_str(), n as u32)).ok_or(format!("{DECOR_JSON}: {k} has no value")))
        .collect::<Result<_, _>>()?;
    let mut seen = std::collections::BTreeMap::new();
    for (name, value) in named(&sentinel).chain(named(&ground)).chain(named(&object)).map(|e| (e.name, e.value)).chain(decor.iter().copied()) {
        if let Some(other) = seen.insert(value, name) {
            return Err(format!("{CUBE_TYPE_JSON}, {DECOR_JSON}: {name} and {other} are both {value}"));
        }
    }
    for (name, value) in &decor {
        if *value <= 255 || *value > u32::from(u16::MAX) {
            return Err(format!("{DECOR_JSON}: {name} is {value}, not past a byte within a u16"));
        }
    }
    for e in named(&ground) {
        if e.value == 0 || e.value >= 255 {
            return Err(format!("{CUBE_TYPE_JSON}: ground.{} is {}, not within 1-254", e.name, e.value));
        }
        if !e.kind.is_some_and(|k| KINDS.contains(&k)) {
            return Err(format!("{CUBE_TYPE_JSON}: ground.{} has no kind of {KINDS:?}", e.name));
        }
    }
    for e in named(&object) {
        if e.value <= 255 || e.value > u16::MAX as u32 {
            return Err(format!("{CUBE_TYPE_JSON}: object.{} is {}, not past a byte within a u16", e.name, e.value));
        }
    }
    for (group, values) in [("ground", &ground), ("object", &object)] {
        let values: Vec<u32> = named(values).map(|e| e.value).collect();
        if values.windows(2).any(|w| w[0] >= w[1]) {
            return Err(format!("{CUBE_TYPE_JSON}: {group} is numbered ascending, as its order is read"));
        }
    }

    let head: Vec<String> = [
        "//",
        "// GENERATED by pxl-tool/bin/spec.rs from cube_type.json — do not edit.",
        "//",
        "// One value space: a ground cell is a byte, a Carto look numbered in the",
        "// order Carto paints, and an object's value a u16 whose byte range is",
        "// that palette and whose range past it is what only an object can be.",
    ]
    .map(String::from)
    .to_vec();
    let note = |n: &Node, indent: &str| {
        n.lines_at("note")
            .unwrap_or_default()
            .iter()
            .map(|l| if l.is_empty() { format!("{indent}//") } else { format!("{indent}// {l}") })
            .collect::<Vec<_>>()
    };

    // TS
    let mut ts = vec!["// @pxl/web/catalog/cell/cube_type.spec.ts".to_string()];
    ts.extend(head.iter().cloned());
    ts.extend([
        String::new(),
        "/** How the renderer draws a ground look, and the texture pack's prefix for it. */".to_string(),
        format!("export type Kind = {};", KINDS.iter().map(|k| format!("\"{k}\"")).collect::<Vec<_>>().join(" | ")),
    ]);
    ts.extend([String::new(), "export const cube_types = {".into(), "  sentinel: {".into()]);
    for e in named(&sentinel) {
        if let Some(doc) = &e.doc {
            ts.extend(ts_doc(doc, "    ").into_iter().enumerate().map(|(i, l)| if i == 0 { l } else { align_star(l, "    ") }));
        }
        ts.push(format!("    {}: 0x{:02x},", e.name, e.value));
    }
    ts.push("  },".into());
    ts.extend(note(ground_node, "  "));
    ts.push("  ground: {".into());
    for item in &ground {
        match item {
            Err(section) => ts.extend([String::new(), format!("    // ---- {section} ----"), String::new()]),
            Ok(e) => {
                if let Some(doc) = &e.doc {
                    ts.extend(ts_doc(doc, "    ").into_iter().enumerate().map(|(i, l)| if i == 0 { l } else { align_star(l, "    ") }));
                }
                ts.push(format!("    {}: {},", e.name, e.value));
            }
        }
    }
    ts.push("  },".into());
    ts.extend(note(object_node, "  "));
    ts.push("  object: {".into());
    for item in &object {
        match item {
            Err(section) => ts.extend([String::new(), format!("    // ---- {section} ----"), String::new()]),
            Ok(e) => ts.push(format!("    {}: {},", e.name, e.value)),
        }
    }
    ts.extend(["  },".to_string(), "} as const satisfies Record<string, Record<string, number>>;".into(), String::new()]);
    ts.push("/** Each look's kind, by its number. */".into());
    ts.push("export const ground_kind: Readonly<Record<number, Kind>> = {".into());
    ts.extend(named(&ground).map(|e| format!("  {}: \"{}\",", e.value, e.kind.unwrap_or("land"))));
    ts.extend([
        "};".to_string(),
        String::new(),
        "/** What a cell nothing painted shows. */".into(),
        format!("export const BASE = cube_types.ground.{base_type};"),
    ]);

    // Rust
    let mut rs = vec!["// pxl-spec/cell/cube_type.spec.rs".to_string()];
    rs.extend(head);
    rs.push(String::new());
    rs.extend(casing_note());
    rs.extend(["#![allow(non_camel_case_types, non_upper_case_globals)]", ""].map(String::from));
    rs.extend([
        "/// How the renderer draws a ground look: pxl-render's material class.".to_string(),
        "#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]".into(),
        "#[repr(u8)]".into(),
        "pub enum Kind {".into(),
    ]);
    rs.extend(KINDS.iter().enumerate().map(|(i, k)| format!("    {} = {},", pascal(k), i + 1)));
    rs.extend([
        "}".to_string(),
        String::new(),
        "pub mod cube_types {".into(),
        "    use super::Kind;".into(),
        String::new(),
        "    pub mod sentinel {".into(),
    ]);
    for e in named(&sentinel) {
        if let Some(doc) = &e.doc {
            rs.extend(rs_doc(doc, "        ", "///"));
        }
        rs.push(format!("        pub const {}: u8 = 0x{:02x};", e.name, e.value));
    }
    rs.extend(["    }".to_string(), String::new()]);
    rs.extend(note(ground_node, "    "));
    rs.push("    pub mod ground {".into());
    for item in &ground {
        match item {
            Err(section) => rs.extend([String::new(), format!("        // ---- {section} ----"), String::new()]),
            Ok(e) => {
                if let Some(doc) = &e.doc {
                    rs.extend(rs_doc(doc, "        ", "///"));
                }
                rs.push(format!("        pub const {}: u8 = {};", e.name, e.value));
            }
        }
    }
    rs.extend([String::new(), "        pub const ENTRIES: &[(&str, u8)] = &[".to_string()]);
    rs.extend(named(&ground).map(|e| format!("            ({}, {}),", json_str(e.name), e.name)));
    rs.extend([
        "        ];".to_string(),
        String::new(),
        "        /// What a cell nothing painted shows.".into(),
        format!("        pub const BASE: u8 = {base_type};"),
        "    }".into(),
        String::new(),
    ]);
    rs.extend(note(object_node, "    "));
    rs.push("    pub mod object {".into());
    for item in &object {
        match item {
            Err(section) => rs.extend([String::new(), format!("        // ---- {section} ----"), String::new()]),
            Ok(e) => {
                if let Some(doc) = &e.doc {
                    rs.extend(rs_doc(doc, "        ", "///"));
                }
                rs.push(format!("        pub const {}: u16 = {};", e.name, e.value));
            }
        }
    }
    rs.extend(["    }".to_string(), String::new()]);
    // The looks as an enum.
    rs.extend([
        "    /// A look, by its number.".to_string(),
        "    #[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]".into(),
        "    #[repr(u8)]".into(),
        "    pub enum Ground {".into(),
    ]);
    rs.extend(named(&ground).map(|e| format!("        {} = {},", e.name, e.value)));
    rs.extend([
        "    }".to_string(),
        String::new(),
        "    impl Ground {".into(),
        "        /// Every look, in paint order.".into(),
        format!("        pub const ALL: [Ground; {}] = [", named(&ground).count()),
    ]);
    rs.extend(named(&ground).map(|e| format!("            Ground::{},", e.name)));
    rs.extend([
        "        ];".to_string(),
        String::new(),
        "        /// The look a byte names; none for a sentinel or a number the palette does not give out.".into(),
        "        pub const fn of(value: u8) -> Option<Ground> {".into(),
        "            match value {".into(),
    ]);
    rs.extend(named(&ground).map(|e| format!("                {} => Some(Ground::{}),", e.value, e.name)));
    rs.extend([
        "                _ => None,".to_string(),
        "            }".into(),
        "        }".into(),
        String::new(),
        "        pub const fn kind(self) -> Kind {".into(),
        "            match self {".into(),
    ]);
    rs.extend(named(&ground).map(|e| format!("                Ground::{} => Kind::{},", e.name, pascal(e.kind.unwrap_or("land")))));
    rs.extend([
        "            }".to_string(),
        "        }".into(),
        String::new(),
        "        /// How far off its sampled height a cell showing the look stands, in units, up positive.".into(),
        "        pub const fn shift(self) -> i16 {".into(),
        "            match self {".into(),
    ]);
    for e in named(&ground).filter(|e| e.shift.is_some()) {
        rs.push(format!("                Ground::{} => {},", e.name, js_num(e.shift.unwrap_or(0.0))));
    }
    rs.extend(["                _ => 0,".to_string(), "            }".into(), "        }".into(), "    }".into(), String::new()]);
    // The object's colors.
    let colors: Vec<&Entry> = named(&object).filter(|e| e.value > 256).collect();
    rs.extend([
        "    /// A placed color, by its number.".to_string(),
        "    #[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]".into(),
        "    #[repr(u16)]".into(),
        "    pub enum Block {".into(),
    ]);
    rs.extend(colors.iter().map(|e| format!("        {} = {},", e.name, e.value)));
    rs.extend([
        "    }".to_string(),
        String::new(),
        "    impl Block {".into(),
        format!("        pub const ALL: [Block; {}] = [", colors.len()),
    ]);
    rs.extend(colors.iter().map(|e| format!("            Block::{},", e.name)));
    rs.extend([
        "        ];".to_string(),
        String::new(),
        "        pub const fn of(value: u16) -> Option<Block> {".into(),
        "            match value {".into(),
    ]);
    rs.extend(colors.iter().map(|e| format!("                {} => Some(Block::{}),", e.value, e.name)));
    rs.extend(["                _ => None,".to_string(), "            }".into(), "        }".into(), "    }".into(), "}".into()]);
    Ok(vec![
        Output::new("apps/web/src/catalog/cell/cube_type.spec.ts", file(&ts)),
        Output::new("crates/spec/src/cell/cube_type.spec.rs", file(&rs)),
    ])
}

pub fn decor_outputs() -> Result<Vec<Output>, String> {
    let spec = read(DECOR_JSON)?;
    let doc = spec.lines_at("doc").unwrap_or_default();
    let head: Vec<String> = [
        "//",
        "// GENERATED by pxl-tool/bin/spec.rs from decor.json — do not edit.",
        "//",
        "// The decor kinds, the cube catalog's sibling: drawn as a model, not a meshed box.",
        "//",
    ]
    .map(String::from)
    .to_vec();
    let entries: Vec<(&str, String)> = spec
        .get("decor_types")
        .map(|d| d.entries().iter().map(|(k, v)| (k.as_str(), v.get("value").and_then(Node::num).map(js_num).unwrap_or_default())).collect())
        .unwrap_or_default();
    let kinds = decor_kinds(&spec, &ground_names()?)?;

    let mut ts = vec!["// @pxl/web/catalog/cell/decor.spec.ts".to_string()];
    ts.extend(head.iter().cloned());
    ts.extend(doc.iter().map(|l| format!("// {l}")));
    ts.push("export const decor_types = {".into());
    ts.extend(entries.iter().map(|(k, v)| format!("  {k}: {v},")));
    ts.extend(["} as const satisfies Record<string, number>;", "", "export type DecorId = keyof typeof decor_types;"].map(String::from));

    let mut rs = vec!["// pxl-spec/cell/decor.spec.rs".to_string()];
    rs.extend(head);
    rs.extend(doc.iter().map(|l| format!("// {l}")));
    rs.push("//".into());
    rs.extend(casing_note());
    rs.extend(["#[allow(non_upper_case_globals, non_camel_case_types)]", "pub mod decor_types {"].map(String::from));
    rs.extend(entries.iter().map(|(k, v)| format!("    pub const {k}: u16 = {v};")));
    rs.push(String::new());
    rs.extend(["    #[derive(Clone, Copy, Debug, PartialEq, Eq)]", "    #[repr(u16)]", "    pub enum Decor {"].map(String::from));
    rs.extend(entries.iter().map(|(k, v)| format!("        {k} = {v},")));
    rs.extend(["    }".to_string(), String::new()]);
    rs.extend([
        "    impl Decor {".to_string(),
        "        /// Every kind the catalog gives out, in the JSON's own order.".into(),
        format!(
            "        pub const ALL: [Decor; {}] = [{}];",
            entries.len(),
            entries.iter().map(|(k, _)| format!("Decor::{k}")).collect::<Vec<_>>().join(", ")
        ),
        String::new(),
    ]);
    rs.extend(
        [
            "        /// The kind a number names, or none for a number the catalog does not",
            "        /// give out.",
            "        pub fn of(value: u16) -> Option<Decor> {",
            "            Decor::ALL.into_iter().find(|t| *t as u16 == value)",
            "        }",
            "    }",
            "}",
            "",
            "pub type DecorId = decor_types::Decor;",
        ]
        .map(String::from),
    );
    rs.extend(kinds);
    Ok(vec![
        Output::new("apps/web/src/catalog/cell/decor.spec.ts", file(&ts)),
        Output::new("crates/spec/src/cell/decor.spec.rs", file(&rs)),
    ])
}

/// The ground's looks by name, what a kind may stand on.
fn ground_names() -> Result<Vec<String>, String> {
    let spec = read(CUBE_TYPE_JSON)?;
    Ok(named(&entries(spec.get("ground").ok_or("no ground")?, "ground")?).map(|e| e.name.to_string()).collect())
}

/// The kinds' table: each kind's models and how the ground grows it, in the
/// catalog's order, which is the order its variants are numbered in.
fn decor_kinds(spec: &Node, looks: &[String]) -> Result<Vec<String>, String> {
    const ASSET: &str = "crate::asset::ingested::Asset";
    let mut rs: Vec<String> = [
        "",
        "/// How a kind the ground grows faces: any way, or along the road or rail its",
        "/// cell lies on.",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
        "#[allow(non_camel_case_types)]",
        "pub enum Orientation {",
        "    random,",
        "    along_transport,",
        "}",
        "",
        "/// A model and its pack's colormap.",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
        "pub struct Variant {",
        "    pub model: crate::asset::ingested::Asset,",
        "    pub skin: crate::asset::ingested::Asset,",
        "}",
        "",
        "/// A kind: its number, its models, and how the ground grows it.",
        "#[derive(Clone, Copy, Debug, PartialEq)]",
        "pub struct DecorKind {",
        "    pub decor: decor_types::Decor,",
        "    pub seed: u64,",
        "    pub density: f64,",
        "    pub orientation: Orientation,",
        "    pub on: &'static [crate::bake::format::GroundCell],",
        "    pub variants: &'static [Variant],",
        "}",
        "",
    ]
    .map(String::from)
    .to_vec();
    let meta = spec.get("meta").ok_or(format!("{DECOR_JSON}: no meta"))?.entries();
    rs.extend(["/// What a decor thing carries beside where it stands.".to_string(), "#[derive(Clone, Copy, Debug, PartialEq)]".into(), "pub struct DecorMeta {".into()]);
    for (field, ty) in meta {
        let ty = ty.str().filter(|t| matches!(*t, "u32" | "f64")).ok_or(format!("{DECOR_JSON}: meta.{field} is no u32 or f64"))?;
        rs.push(format!("    pub {field}: {ty},"));
    }
    rs.extend(["}".to_string(), String::new()]);
    let kinds = spec.get("decor_types").ok_or(format!("{DECOR_JSON}: no decor_types"))?.entries();
    rs.push(format!("pub const KINDS: [DecorKind; {}] = [", kinds.len()));
    for (name, k) in kinds {
        let at = |field: &str| format!("{DECOR_JSON}: {name}.{field}");
        if let Some(doc) = k.lines_at("doc") {
            rs.extend(doc.iter().map(|l| format!("    // {l}").trim_end().to_string()));
        }
        let seed = k.str_at("seed").ok_or(at("seed"))?;
        u64::from_str_radix(seed.trim_start_matches("0x"), 16).map_err(|e| format!("{}: {e}", at("seed")))?;
        let density = k.get("density").and_then(Node::num).ok_or(at("density"))?;
        let orientation = k.str_at("orientation").filter(|o| matches!(*o, "random" | "along_transport")).ok_or(at("orientation"))?;
        let on = k.get("on").and_then(Node::arr).ok_or(at("on"))?;
        let on = on
            .iter()
            .map(|l| l.str().filter(|l| looks.iter().any(|g| g == l)).map(|l| format!("crate::cell::cube_types::ground::{l}")).ok_or(format!("{}: {l:?} is no ground look", at("on"))))
            .collect::<Result<Vec<_>, _>>()?;
        let variants = k.get("variants").and_then(Node::arr).ok_or(at("variants"))?;
        let variants = variants
            .iter()
            .map(|v| match (v.str_at("model"), v.str_at("skin")) {
                (Some(m), Some(s)) => Ok(format!("Variant {{ model: {ASSET}::{}, skin: {ASSET}::{} }}", rs_ident(m), rs_ident(s))),
                _ => Err(at("variants")),
            })
            .collect::<Result<Vec<_>, _>>()?;
        rs.extend([
            "    DecorKind {".to_string(),
            format!("        decor: decor_types::Decor::{name},"),
            format!("        seed: {seed},"),
            format!("        density: {},", if density.fract() == 0.0 { format!("{}.0", js_num(density)) } else { js_num(density) }),
            format!("        orientation: Orientation::{orientation},"),
            format!("        on: &[{}],", on.join(", ")),
            "        variants: &[".to_string(),
        ]);
        rs.extend(variants.iter().map(|v| format!("            {v},")));
        rs.extend(["        ],".to_string(), "    },".to_string()]);
    }
    rs.push("];".into());
    Ok(rs)
}
