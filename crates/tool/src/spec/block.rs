use regex::Regex;

use super::{align_star, casing_note, file, js_num, json_str, pretty, read, rgb_literal, rs_doc, rs_ident, ts_doc, Node, Output};

const CUBE_JSON: &str = "spec/spec/block/cube.json";
const DECOR_JSON: &str = "spec/spec/block/decor.json";
const ID_JSON: &str = "spec/spec/block/id.json";

struct Entry<'a> {
    name: &'a str,
    value: u32,
    transport: bool,
    doc: Option<Vec<String>>,
}

/// A list's entries in order, a section heading as `Err(id)`.
fn entries<'a>(list: &'a Node, what: &str) -> Result<Vec<Result<Entry<'a>, &'a str>>, String> {
    let list = list.get("entries").and_then(Node::arr).or_else(|| list.arr()).ok_or(format!("{CUBE_JSON}: {what} has no entries"))?;
    list.iter()
        .map(|e| {
            if let Some(section) = e.str_at("section") {
                return Ok(Err(section));
            }
            let name = e.str_at("name").ok_or(format!("{CUBE_JSON}: {what}: an entry with no name"))?;
            let value = e.get("value").and_then(Node::num).ok_or(format!("{CUBE_JSON}: {name} has no value"))? as u32;
            Ok(Ok(Entry {
                name,
                value,
                transport: matches!(e.get("transport"), Some(Node::Bool(true))),
                doc: e.lines_at("$doc"),
            }))
        })
        .collect()
}

fn named<'l, 'a>(list: &'l [Result<Entry<'a>, &'a str>]) -> impl Iterator<Item = &'l Entry<'a>> {
    list.iter().filter_map(|e| e.as_ref().ok())
}

/// The catalog's two groups of placeable cubes, the ground's looks and the
/// object's colors, which a texture is filed under.
pub fn catalog() -> Result<Vec<(String, Vec<String>)>, String> {
    let spec = read(CUBE_JSON)?;
    let ground = entries(spec.get("ground").ok_or("no ground")?, "ground")?;
    let object = entries(spec.get("object").ok_or("no object")?, "object")?;
    Ok(vec![
        ("ground".into(), named(&ground).map(|e| e.name.to_string()).collect()),
        ("object".into(), named(&object).filter(|e| is_color(e)).map(|e| e.name.to_string()).collect()),
    ])
}

/// One of the object's colors: what past a ground byte it gives out to be placed.
fn is_color(e: &Entry) -> bool {
    e.value > 256
}

/// Each placeable cube with the section heading it is listed under.
fn sectioned<'l, 'a>(list: &'l [Result<Entry<'a>, &'a str>]) -> impl Iterator<Item = (&'a str, &'l Entry<'a>)> {
    list.iter()
        .scan("", |section, item| {
            Some(match item {
                Err(s) => {
                    *section = s;
                    None
                }
                Ok(e) => Some((*section, e)),
            })
        })
        .flatten()
}

/// Each ground look's color by name, packed `0xRRGGBB`, as color.json gives it.
pub fn ground_colors() -> Result<std::collections::BTreeMap<String, u32>, String> {
    let spec = read("spec/spec/block/color.json")?;
    let ground = spec.get("ground").ok_or("color.json has no ground")?;
    ground
        .entries()
        .iter()
        .map(|(n, e)| Ok((n.clone(), super::packed(e.str_at("hex").ok_or(format!("color.json: ground.{n} has no hex"))?)?)))
        .collect()
}

pub fn color_outputs() -> Result<Vec<Output>, String> {
    let spec = read("spec/spec/block/color.json")?;
    let head: Vec<String> = [
        "//",
        "// GENERATED by pxl-tool/bin/spec.rs from color.json — do not edit.",
        "//",
        "// The color of every look and every placed color: what a cube *is* to",
        "// the eye when no texture is drawn over it — everything drawn with the",
        "// pack off reads this, the coarse tiers included, which summarize it",
        "// the way they summarize the tiles with the pack on",
        "// (pxl-render mesh/chunk.rs). A texture pack decorates these; it",
        "// does not replace them.",
    ]
    .map(String::from)
    .to_vec();

    let mut with_rgb = Vec::new();
    for (group, entries) in spec.entries() {
        if group == "$doc" {
            with_rgb.push((group.clone(), entries.clone()));
            continue;
        }
        let mut packed_entries = Vec::new();
        for (n, e) in entries.entries() {
            let hex = e.str_at("hex").ok_or(format!("color.json: {group}.{n} has no hex"))?;
            let mut fields: Vec<(String, Node)> = e.entries().to_vec();
            fields.push(("rgb".to_string(), Node::Num(super::packed(hex)? as f64)));
            packed_entries.push((n.clone(), Node::Obj(fields)));
        }
        with_rgb.push((group.clone(), Node::Obj(packed_entries)));
    }
    let mut json = String::new();
    pretty(&Node::Obj(with_rgb), "", &mut json);
    let bare_keys = Regex::new(r#""([A-Za-z_][A-Za-z0-9_]*)":"#).map_err(|e| e.to_string())?;
    let close_brace = Regex::new(r"\n(\s*)\}").map_err(|e| e.to_string())?;
    let close_bracket = Regex::new(r"\n(\s*)\]").map_err(|e| e.to_string())?;
    let json = bare_keys.replace_all(&json, "$1:");
    let json = close_brace.replace_all(&json, ",\n$1}");
    let json = close_bracket.replace_all(&json, ",\n$1]");
    let mut ts = vec!["// @pxl/web/catalog/block/color.spec.ts".to_string()];
    ts.extend(head.iter().cloned());
    ts.extend([String::new(), format!("export default {json};")]);

    let types = read(CUBE_JSON)?;
    let mut rs = vec!["// pxl-spec/block/color.spec.rs".to_string()];
    rs.extend(head);
    rs.push(String::new());
    rs.extend(casing_note());
    rs.extend(["", "use super::cube;", "use super::Swatch;"].map(String::from));
    let groups = [("sentinel", "sentinel", "u8"), ("ground", "ground", "u8"), ("object", "object", "u16")];
    for (group, module, width) in groups {
        let list = entries(
            if group == "sentinel" {
                types.get("sentinel").ok_or("no sentinel")?
            } else {
                types.get(group).ok_or(format!("no {group}"))?
            },
            group,
        )?;
        let colors = spec.get(group).ok_or(format!("color.json has no {group}"))?;
        rs.extend([
            String::new(),
            format!("/// `{group}`'s color for a value."),
            format!("pub const fn {group}(t: {width}) -> Option<Swatch> {{"),
            "    match t {".to_string(),
        ]);
        for (name, entry) in colors.entries() {
            if !named(&list).any(|e| e.name == name.as_str()) {
                return Err(format!("color.json: {group}.{name} is nothing cube.json names"));
            }
            if let Some(doc) = entry.str_at("$doc") {
                rs.push(format!("        // {doc}"));
            }
            let hex = entry.str_at("hex").ok_or(format!("color.json: {group}.{name} has no hex"))?;
            rs.push(format!("        cube::{module}::{} => Some(Swatch::new({})),", rs_ident(name), rgb_literal(hex)?));
        }
        if group == "ground" {
            for e in named(&list) {
                if colors.get(e.name).is_none() {
                    return Err(format!("color.json: ground.{} has no color", e.name));
                }
            }
            rs.push("        // A sentinel a baked cell can hold.".to_string());
            rs.push("        _ => sentinel(t),".to_string());
        } else {
            rs.push("        _ => None,".to_string());
        }
        rs.extend(["    }", "}"].map(String::from));
    }
    Ok(vec![
        Output::new("apps/web/src/catalog/block/color.spec.ts", file(&ts)),
        Output::new("crates/spec/src/block/color.spec.rs", file(&rs)),
    ])
}

pub fn cube_outputs() -> Result<Vec<Output>, String> {
    let spec = read(CUBE_JSON)?;
    let sentinel = entries(spec.get("sentinel").ok_or("no sentinel")?, "sentinel")?;
    let ground_node = spec.get("ground").ok_or("no ground")?;
    let ground = entries(ground_node, "ground")?;
    let object_node = spec.get("object").ok_or("no object")?;
    let object = entries(object_node, "object")?;
    let base = spec.get("base").ok_or(format!("{CUBE_JSON}: no base"))?;
    let base_type = base.str_at("type").ok_or("base has no type")?;

    // One value space: the sentinels and the looks within a byte, the object's own and decor past it.
    let decor = read(DECOR_JSON)?;
    let decor: Vec<(&str, u32)> = decor
        .get("decors")
        .ok_or(format!("{DECOR_JSON}: no decors"))?
        .entries()
        .iter()
        .map(|(k, v)| v.get("value").and_then(Node::num).map(|n| (k.as_str(), n as u32)).ok_or(format!("{DECOR_JSON}: {k} has no value")))
        .collect::<Result<_, _>>()?;
    let mut seen = std::collections::BTreeMap::new();
    for (name, value) in named(&sentinel).chain(named(&ground)).chain(named(&object)).map(|e| (e.name, e.value)).chain(decor.iter().copied()) {
        if let Some(other) = seen.insert(value, name) {
            return Err(format!("{CUBE_JSON}, {DECOR_JSON}: {name} and {other} are both {value}"));
        }
    }
    // An id is its kind over its shape (id.json).
    let id = read(ID_JSON)?;
    let shape_bits = id.get("SHAPE_BITS").map(Node::value).and_then(Node::num).ok_or(format!("{ID_JSON}: no SHAPE_BITS"))? as u32;
    let kind = |name: &str| {
        id.get("KIND")
            .and_then(|c| c.get(name))
            .and_then(Node::num)
            .map(|n| n as u32)
            .ok_or(format!("{ID_JSON}: no kind {name}"))
    };
    let (cube_kind, decor_kind) = (kind("cube")?, kind("decor")?);
    for (name, value) in &decor {
        if *value > u32::from(u16::MAX) || value >> shape_bits != decor_kind {
            return Err(format!("{DECOR_JSON}: {name} is {value}, not of the decor kind within a u16"));
        }
    }
    for e in named(&ground) {
        if e.value == 0 || e.value >= 255 {
            return Err(format!("{CUBE_JSON}: ground.{} is {}, not within 1-254", e.name, e.value));
        }
    }
    for e in named(&object) {
        if e.value <= 255 || e.value >> shape_bits != cube_kind {
            return Err(format!("{CUBE_JSON}: object.{} is {}, not past a byte of the cube kind", e.name, e.value));
        }
    }
    for (group, values) in [("ground", &ground), ("object", &object)] {
        let values: Vec<u32> = named(values).map(|e| e.value).collect();
        if values.windows(2).any(|w| w[0] >= w[1]) {
            return Err(format!("{CUBE_JSON}: {group} is numbered ascending, as its order is read"));
        }
    }

    let head: Vec<String> = [
        "//",
        "// GENERATED by pxl-tool/bin/spec.rs from cube.json — do not edit.",
        "//",
        "// One value space: a ground cell is a byte, a Carto look numbered in the",
        "// order Carto paints, and an object's value a u16 whose byte range is",
        "// that palette and whose range past it is what only an object can be.",
    ]
    .map(String::from)
    .to_vec();
    let note = |n: &Node, indent: &str| {
        n.lines_at("$doc")
            .unwrap_or_default()
            .iter()
            .map(|l| if l.is_empty() { format!("{indent}//") } else { format!("{indent}// {l}") })
            .collect::<Vec<_>>()
    };

    // TS
    let mut ts = vec!["// @pxl/web/catalog/block/cube.spec.ts".to_string()];
    ts.extend(head.iter().cloned());
    // Every placeable cube under its heading: the ground's looks, and the colors past a ground byte.
    let cube_sections: Vec<(&str, &Entry)> = sectioned(&ground).chain(sectioned(&object).filter(|(_, e)| is_color(e))).collect();
    let mut section_ids: Vec<&str> = Vec::new();
    for (s, _) in &cube_sections {
        if !section_ids.contains(s) {
            section_ids.push(s);
        }
    }
    ts.extend([
        String::new(),
        "/** The catalog's section a placeable cube is listed under, as Carto groups the looks. */".to_string(),
        format!("export type CubeSection = {};", section_ids.iter().map(|s| format!("\"{s}\"")).collect::<Vec<_>>().join(" | ")),
    ]);
    ts.extend([String::new(), "export const cube = {".into(), "  sentinel: {".into()]);
    for e in named(&sentinel) {
        if let Some(doc) = &e.doc {
            ts.extend(ts_doc(doc, "    ").into_iter().enumerate().map(|(i, l)| if i == 0 { l } else { align_star(l, "    ") }));
        }
        ts.push(format!("    {}: 0x{:02x},", e.name, e.value));
    }
    ts.push("  },".into());
    ts.extend(note(ground_node, "  "));
    ts.push("  ground: {".into());
    for item in &ground {
        match item {
            Err(section) => ts.extend([String::new(), format!("    // ---- {section} ----"), String::new()]),
            Ok(e) => {
                if let Some(doc) = &e.doc {
                    ts.extend(ts_doc(doc, "    ").into_iter().enumerate().map(|(i, l)| if i == 0 { l } else { align_star(l, "    ") }));
                }
                ts.push(format!("    {}: {},", e.name, e.value));
            }
        }
    }
    ts.push("  },".into());
    ts.extend(note(object_node, "  "));
    ts.push("  object: {".into());
    for item in &object {
        match item {
            Err(section) => ts.extend([String::new(), format!("    // ---- {section} ----"), String::new()]),
            Ok(e) => ts.push(format!("    {}: {},", e.name, e.value)),
        }
    }
    ts.extend(["  },".to_string(), "} as const satisfies Record<string, Record<string, number>>;".into(), String::new()]);
    ts.push("/** Each placeable cube's section, by its number. */".into());
    ts.push("export const cube_section: Readonly<Record<number, CubeSection>> = {".into());
    ts.extend(cube_sections.iter().map(|(s, e)| format!("  {}: \"{s}\",", e.value)));
    ts.extend([
        "};".to_string(),
        String::new(),
        "/** What a cell nothing painted shows. */".into(),
        format!("export const BASE = cube.ground.{base_type};"),
    ]);

    // Rust
    let mut rs = vec!["// pxl-spec/block/cube.spec.rs".to_string()];
    rs.extend(head);
    rs.push(String::new());
    rs.extend(casing_note());
    rs.extend(["#![allow(non_camel_case_types, non_upper_case_globals)]", ""].map(String::from));
    rs.extend(["pub mod cubes {".to_string(), "    pub mod sentinel {".into()]);
    for e in named(&sentinel) {
        if let Some(doc) = &e.doc {
            rs.extend(rs_doc(doc, "        ", "///"));
        }
        rs.push(format!("        pub const {}: u8 = 0x{:02x};", e.name, e.value));
    }
    rs.extend(["    }".to_string(), String::new()]);
    rs.extend(note(ground_node, "    "));
    rs.push("    pub mod ground {".into());
    for item in &ground {
        match item {
            Err(section) => rs.extend([String::new(), format!("        // ---- {section} ----"), String::new()]),
            Ok(e) => {
                if let Some(doc) = &e.doc {
                    rs.extend(rs_doc(doc, "        ", "///"));
                }
                rs.push(format!("        pub const {}: u8 = {};", e.name, e.value));
            }
        }
    }
    rs.extend([String::new(), "        pub const ENTRIES: &[(&str, u8)] = &[".to_string()]);
    rs.extend(named(&ground).map(|e| format!("            ({}, {}),", json_str(e.name), e.name)));
    rs.extend([
        "        ];".to_string(),
        String::new(),
        "        /// What a cell nothing painted shows.".into(),
        format!("        pub const BASE: u8 = {base_type};"),
        "    }".into(),
        String::new(),
    ]);
    rs.extend(note(object_node, "    "));
    rs.push("    pub mod object {".into());
    for item in &object {
        match item {
            Err(section) => rs.extend([String::new(), format!("        // ---- {section} ----"), String::new()]),
            Ok(e) => {
                if let Some(doc) = &e.doc {
                    rs.extend(rs_doc(doc, "        ", "///"));
                }
                rs.push(format!("        pub const {}: u16 = {};", e.name, e.value));
            }
        }
    }
    rs.extend(["    }".to_string(), String::new()]);
    // The looks as an enum.
    rs.extend([
        "    /// A look, by its number.".to_string(),
        "    #[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]".into(),
        "    #[repr(u8)]".into(),
        "    pub enum Ground {".into(),
    ]);
    rs.extend(named(&ground).map(|e| format!("        {} = {},", e.name, e.value)));
    rs.extend([
        "    }".to_string(),
        String::new(),
        "    impl Ground {".into(),
        "        /// Every look, in paint order.".into(),
        format!("        pub const ALL: [Ground; {}] = [", named(&ground).count()),
    ]);
    rs.extend(named(&ground).map(|e| format!("            Ground::{},", e.name)));
    rs.extend([
        "        ];".to_string(),
        String::new(),
        "        /// The look a byte names; none for a sentinel or a number the palette does not give out.".into(),
        "        pub const fn of(value: u8) -> Option<Ground> {".into(),
        "            match value {".into(),
    ]);
    rs.extend(named(&ground).map(|e| format!("                {} => Some(Ground::{}),", e.value, e.name)));
    rs.extend([
        "                _ => None,".to_string(),
        "            }".into(),
        "        }".into(),
        String::new(),
        "        /// A way: decor faces along it and no pier stands on it.".into(),
        format!(
            "        pub const fn transport(self) -> bool {{ matches!(self, {}) }}",
            named(&ground).filter(|e| e.transport).map(|e| format!("Ground::{}", e.name)).collect::<Vec<_>>().join(" | ")
        ),
    ]);
    rs.extend(["    }".to_string(), String::new()]);
    // The object's colors.
    let colors: Vec<&Entry> = named(&object).filter(|e| is_color(e)).collect();
    rs.extend([
        "    /// One of the object's colors, by its number.".to_string(),
        "    #[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]".into(),
        "    #[repr(u16)]".into(),
        "    pub enum Object {".into(),
    ]);
    rs.extend(colors.iter().map(|e| format!("        {} = {},", e.name, e.value)));
    rs.extend([
        "    }".to_string(),
        String::new(),
        "    impl Object {".into(),
        format!("        pub const ALL: [Object; {}] = [", colors.len()),
    ]);
    rs.extend(colors.iter().map(|e| format!("            Object::{},", e.name)));
    rs.extend([
        "        ];".to_string(),
        String::new(),
        "        pub const fn of(value: u16) -> Option<Object> {".into(),
        "            match value {".into(),
    ]);
    rs.extend(colors.iter().map(|e| format!("                {} => Some(Object::{}),", e.value, e.name)));
    rs.extend(["                _ => None,".to_string(), "            }".into(), "        }".into(), "    }".into(), "}".into()]);
    Ok(vec![
        Output::new("apps/web/src/catalog/block/cube.spec.ts", file(&ts)),
        Output::new("crates/spec/src/block/cube.spec.rs", file(&unwrapped(rs, "pub mod cubes {"))),
    ])
}

pub fn decor_outputs() -> Result<Vec<Output>, String> {
    let spec = read(DECOR_JSON)?;
    let doc = spec.lines_at("$doc").unwrap_or_default();
    let head: Vec<String> = [
        "//",
        "// GENERATED by pxl-tool/bin/spec.rs from decor.json — do not edit.",
        "//",
        "// The decors, the cube catalog's sibling: drawn as a model, not a meshed box.",
        "//",
    ]
    .map(String::from)
    .to_vec();
    let entries: Vec<(&str, String)> = spec
        .get("decors")
        .map(|d| {
            d.entries()
                .iter()
                .map(|(k, v)| (k.as_str(), v.get("value").and_then(Node::num).map(js_num).unwrap_or_default()))
                .collect()
        })
        .unwrap_or_default();
    let table = decor_table(&spec, &ground_names()?)?;

    let mut ts = vec!["// @pxl/web/catalog/block/decor.spec.ts".to_string()];
    ts.extend(head.iter().cloned());
    ts.extend(doc.iter().map(|l| format!("// {l}")));
    ts.push("export const decor = {".into());
    ts.extend(entries.iter().map(|(k, v)| format!("  {k}: {v},")));
    ts.extend(["} as const satisfies Record<string, number>;", "", "export type DecorId = keyof typeof decor;"].map(String::from));

    let mut rs = vec!["// pxl-spec/block/decor.spec.rs".to_string()];
    rs.extend(head);
    rs.extend(doc.iter().map(|l| format!("// {l}")));
    rs.push("//".into());
    rs.extend(casing_note());
    rs.extend(["#![allow(non_upper_case_globals, non_camel_case_types)]", "pub mod decors {"].map(String::from));
    rs.extend(entries.iter().map(|(k, v)| format!("    pub const {k}: u16 = {v};")));
    rs.push(String::new());
    rs.extend(["    #[derive(Clone, Copy, Debug, PartialEq, Eq)]", "    #[repr(u16)]", "    pub enum DecorId {"].map(String::from));
    rs.extend(entries.iter().map(|(k, v)| format!("        {k} = {v},")));
    rs.extend(["    }".to_string(), String::new()]);
    rs.extend([
        "    impl DecorId {".to_string(),
        "        /// Every decor the catalog gives out, in the JSON's own order.".into(),
        format!(
            "        pub const ALL: [DecorId; {}] = [{}];",
            entries.len(),
            entries.iter().map(|(k, _)| format!("DecorId::{k}")).collect::<Vec<_>>().join(", ")
        ),
        String::new(),
    ]);
    rs.extend(
        [
            "        /// The decor a number names, or none for a number the catalog does not",
            "        /// give out.",
            "        pub fn of(value: u16) -> Option<DecorId> {",
            "            DecorId::ALL.into_iter().find(|t| *t as u16 == value)",
            "        }",
            "    }",
            "}",
            "",
            "",
        ]
        .map(String::from),
    );
    rs.extend(table);
    Ok(vec![
        Output::new("apps/web/src/catalog/block/decor.spec.ts", file(&ts)),
        Output::new("crates/spec/src/block/decor.spec.rs", file(&unwrapped(rs, "pub mod decors {"))),
    ])
}

/// The ground's looks by name, what a decor may stand on.
fn ground_names() -> Result<Vec<String>, String> {
    let spec = read(CUBE_JSON)?;
    Ok(named(&entries(spec.get("ground").ok_or("no ground")?, "ground")?).map(|e| e.name.to_string()).collect())
}

/// The decors' table: each one's models and how the ground grows it, in the
/// catalog's order, which is the order its variants are numbered in.
fn decor_table(spec: &Node, looks: &[String]) -> Result<Vec<String>, String> {
    const ASSET: &str = "crate::asset::ingested::Asset";
    let mut rs: Vec<String> = [
        "",
        "/// How a decor the ground grows faces: any way, or along the road or rail its",
        "/// cell lies on.",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
        "#[allow(non_camel_case_types)]",
        "pub enum Orientation {",
        "    random,",
        "    along_transport,",
        "}",
        "",
        "/// A model, its pack's colormap, and the box it claims in its kind's cells.",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
        "pub struct Variant {",
        "    pub model: crate::asset::ingested::Asset,",
        "    pub skin: crate::asset::ingested::Asset,",
        "    pub size: [u32; 3],",
        "}",
        "",
        "/// A decor: its id, its models, and how the ground grows it.",
        "#[derive(Clone, Copy, Debug, PartialEq)]",
        "pub struct Decor {",
        "    pub id: DecorId,",
        "    pub seed: u64,",
        "    pub density: f64,",
        "    pub orientation: Orientation,",
        "    pub on: &'static [crate::bake::tile::terrain::GroundId],",
        "    /// Its cell: a unit's zoom, this many coarser.",
        "    pub scale_steps: i8,",
        "    pub variants: &'static [Variant],",
        "}",
        "",
    ]
    .map(String::from)
    .to_vec();
    let meta = spec.get("meta").ok_or(format!("{DECOR_JSON}: no meta"))?.entries();
    rs.extend([
        "/// What a decor thing carries beside where it stands.".to_string(),
        "#[derive(Clone, Copy, Debug, PartialEq)]".into(),
        "pub struct DecorMeta {".into(),
    ]);
    for (field, ty) in meta {
        let ty = ty.str().filter(|t| matches!(*t, "u32" | "f64")).ok_or(format!("{DECOR_JSON}: meta.{field} is no u32 or f64"))?;
        rs.push(format!("    pub {field}: {ty},"));
    }
    rs.extend(["}".to_string(), String::new()]);
    let decors = spec.get("decors").ok_or(format!("{DECOR_JSON}: no decors"))?.entries();
    rs.push(format!("pub const DECORS: [Decor; {}] = [", decors.len()));
    for (name, k) in decors {
        let at = |field: &str| format!("{DECOR_JSON}: {name}.{field}");
        if let Some(doc) = k.lines_at("$doc") {
            rs.extend(doc.iter().map(|l| format!("    // {l}").trim_end().to_string()));
        }
        let seed = k.str_at("seed").ok_or(at("seed"))?;
        u64::from_str_radix(seed.trim_start_matches("0x"), 16).map_err(|e| format!("{}: {e}", at("seed")))?;
        let density = k.get("density").and_then(Node::num).ok_or(at("density"))?;
        let orientation = k.str_at("orientation").filter(|o| matches!(*o, "random" | "along_transport")).ok_or(at("orientation"))?;
        let on = k.get("on").and_then(Node::arr).ok_or(at("on"))?;
        let on = on
            .iter()
            .map(|l| {
                l.str()
                    .filter(|l| looks.iter().any(|g| g == l))
                    .map(|l| format!("crate::block::cube::ground::{l}"))
                    .ok_or(format!("{}: {l:?} is no ground look", at("on")))
            })
            .collect::<Result<Vec<_>, _>>()?;
        let scale_steps = match k.get("scale_steps") {
            None => 0.0,
            Some(n) => n.num().filter(|n| n.fract() == 0.0 && (f64::from(i8::MIN)..=f64::from(i8::MAX)).contains(n)).ok_or(at("scale_steps"))?,
        };
        let variants = k.get("variants").and_then(Node::arr).ok_or(at("variants"))?;
        let variants = variants
            .iter()
            .map(|v| {
                let size = v.get("size").and_then(Node::arr).filter(|s| s.len() == 3).map(|s| s.iter().map(Node::num).collect::<Option<Vec<_>>>());
                match (v.str_at("model"), v.str_at("skin"), size.flatten()) {
                    (Some(m), Some(s), Some(size)) if size.iter().all(|&n| n >= 1.0 && n.fract() == 0.0 && n <= f64::from(u32::MAX)) => Ok(format!(
                        "Variant {{ model: {ASSET}::{}, skin: {ASSET}::{}, size: [{}] }}",
                        rs_ident(m),
                        rs_ident(s),
                        size.iter().map(|&n| js_num(n)).collect::<Vec<_>>().join(", ")
                    )),
                    _ => Err(at("variants")),
                }
            })
            .collect::<Result<Vec<_>, _>>()?;
        rs.extend([
            "    Decor {".to_string(),
            format!("        id: DecorId::{name},"),
            format!("        seed: {seed},"),
            format!("        density: {},", if density.fract() == 0.0 { format!("{}.0", js_num(density)) } else { js_num(density) }),
            format!("        orientation: Orientation::{orientation},"),
            format!("        on: &[{}],", on.join(", ")),
            format!("        scale_steps: {},", js_num(scale_steps)),
            "        variants: &[".to_string(),
        ]);
        rs.extend(variants.iter().map(|v| format!("            {v},")));
        rs.extend(["        ],".to_string(), "    },".to_string()]);
    }
    rs.push("];".into());
    Ok(rs)
}

/// The lines of `rs` with the module `open` opens taken off, its body one
/// indent out: the generated file is the module itself.
fn unwrapped(rs: Vec<String>, open: &str) -> Vec<String> {
    let Some(at) = rs.iter().position(|l| l == open) else { return rs };
    let mut depth = 0i32;
    let mut close = at;
    for (i, l) in rs.iter().enumerate().skip(at) {
        depth += l.matches('{').count() as i32 - l.matches('}').count() as i32;
        if depth == 0 {
            close = i;
            break;
        }
    }
    let body = rs[at + 1..close].iter().map(|l| l.strip_prefix("    ").unwrap_or(l).to_string());
    rs[..at].iter().cloned().chain(body).chain(rs[close + 1..].iter().cloned()).collect()
}
