// pxl-tool/spec/bake.rs

use super::{file, json_str, line_comments, packed, read, rs_doc, Output};

pub fn published_outputs() -> Result<Vec<Output>, String> {
    let spec = read("spec/spec/bake/published.json")?;
    let doc = spec.lines_at("doc").unwrap_or_default();
    let kinds: Vec<(&str, &str)> = spec
        .get("PUBLISHED_VERSION")
        .map(|p| p.entries().iter().map(|(k, v)| (k.as_str(), v.str().unwrap_or_default())).collect())
        .unwrap_or_default();
    let format = spec.get("FORMAT").ok_or("published.json: no FORMAT")?;
    let format_doc = format.lines_at("$doc").unwrap_or_default();
    let mut formats: Vec<(&str, u32)> = Vec::new();
    for (k, _) in &kinds {
        let n = format.get(k).and_then(|n| n.num()).ok_or(format!("published.json: FORMAT has no {k}"))?;
        if n < 1.0 || n.fract() != 0.0 {
            return Err(format!("published.json: FORMAT.{k} {n} is not a format number"));
        }
        formats.push((k, n as u32));
    }
    // `v<format>.<YYYY-MM-DD>.<n>`, or a name the client would request and no bake writes.
    for (k, v) in &kinds {
        let parts: Vec<&str> = v.strip_prefix('v').map(|r| r.split('.').collect()).unwrap_or_default();
        let day = |d: &str| d.len() == 10 && d.split('-').map(str::len).eq([4, 2, 2]) && d.split('-').all(|p| p.parse::<u32>().is_ok());
        let named = matches!(parts.as_slice(), [format, d, n] if format.parse::<u32>().is_ok() && day(d) && n.parse::<u32>().is_ok_and(|n| n >= 1));
        if !named {
            return Err(format!("published.json: PUBLISHED_VERSION.{k} {v:?} is not v<format>.<YYYY-MM-DD>.<n>"));
        }
    }
    let source = spec.get("SOURCE").ok_or("published.json: no SOURCE")?;
    let source_doc = source.lines_at("$doc").unwrap_or_default();
    let top_z = source.get("top_z").and_then(|n| n.num()).ok_or("published.json: SOURCE has no top_z")?;
    if top_z < 0.0 || top_z.fract() != 0.0 {
        return Err(format!("published.json: SOURCE.top_z {top_z} is not a zoom"));
    }
    let top_z = top_z as u32;
    let head = ["//".to_string(), "// GENERATED by pxl-tool/bin/spec.rs from published.json — do not edit.".into(), "".into()];
    let list = |f: &dyn Fn(&str) -> String| kinds.iter().map(|(k, _)| f(k)).collect::<Vec<_>>().join(", ");

    let mut ts = vec!["// @pxl/web/config/published.spec.ts".to_string()];
    ts.extend(head.iter().cloned());
    ts.push("/**".into());
    ts.extend(doc.iter().map(|l| if l.is_empty() { " *".to_string() } else { format!(" * {l}") }));
    ts.extend([" */".to_string(), "export const PUBLISHED_VERSION = {".into()]);
    ts.extend(kinds.iter().map(|(k, v)| format!("  {k}: {},", json_str(v))));
    ts.extend(
        [
            "} as const;",
            "",
            "export type BakeKind = keyof typeof PUBLISHED_VERSION;",
            "",
            "/** The kinds by the number the kernel names one by: the root a bake's objects are opened below (xpute's OPENAT). */",
        ]
        .map(String::from),
    );
    ts.push(format!("export const BAKE_KINDS: readonly BakeKind[] = [{}];", list(&|k| json_str(k))));
    ts.extend([
        "".to_string(),
        "/** What a tile source declares of itself: SOURCE's shape, which the dev tile".into(),
        " * server answers too. */".into(),
    ]);
    ts.extend(["export interface TileSource {".to_string(), "  readonly top_z: number;".into(), "}".into(), "".into(), "/**".into()]);
    ts.extend(source_doc.iter().map(|l| if l.is_empty() { " *".to_string() } else { format!(" * {l}") }));
    ts.extend([" */".to_string(), format!("export const PUBLISHED_SOURCE: TileSource = {{ top_z: {top_z} }};")]);

    let mut rs = vec!["// pxl-spec/bake/published.spec.rs".to_string()];
    rs.extend(head);
    rs.extend(rs_doc(&doc, "", "///"));
    rs.push("pub struct PublishedVersion {".into());
    rs.extend(kinds.iter().map(|(k, _)| format!("    pub {k}: &'static str,")));
    rs.extend(["}".to_string(), String::new(), "pub const PUBLISHED_VERSION: PublishedVersion = PublishedVersion {".into()]);
    rs.extend(kinds.iter().map(|(k, v)| format!("    {k}: {},", json_str(v))));
    rs.extend(["};".to_string(), String::new()]);
    rs.extend(rs_doc(&format_doc, "", "///"));
    rs.push("pub struct Format {".into());
    rs.extend(kinds.iter().map(|(k, _)| format!("    pub {k}: u32,")));
    rs.extend(["}".to_string(), String::new(), "pub const FORMAT: Format = Format {".into()]);
    rs.extend(formats.iter().map(|(k, n)| format!("    {k}: {n},")));
    rs.extend(
        [
            "};",
            "",
            "/// A bake's folder and published name: its format, the day it was baked",
            "/// (`YYYY-MM-DD`, UTC) and that day's count of bakes of its kind, from 1.",
            "pub fn version_name(format: u32, day: &str, n: u32) -> String {",
            "    format!(\"v{format}.{day}.{n}\")",
            "}",
            "",
        ]
        .map(String::from),
    );
    rs.extend(
        [
            "/// The kinds a version is published for: the fields of `PUBLISHED_VERSION`,",
            "/// numbered in their order.",
            "#[allow(non_camel_case_types)]",
            "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
            "#[repr(u32)]",
            "pub enum BakeKind {",
        ]
        .map(String::from),
    );
    rs.extend(kinds.iter().map(|(k, _)| format!("    {k},")));
    rs.extend([
        "}".to_string(),
        String::new(),
        "impl BakeKind {".into(),
        format!("    pub const ALL: [BakeKind; {}] = [{}];", kinds.len(), list(&|k| format!("BakeKind::{k}"))),
        String::new(),
        "    /// The kind a number names, or none for a number nobody gave out.".into(),
        "    pub fn of(number: u32) -> Option<BakeKind> {".into(),
        "        BakeKind::ALL.into_iter().find(|k| *k as u32 == number)".into(),
        "    }".into(),
        "}".into(),
        String::new(),
        "impl PublishedVersion {".into(),
        "    /// `PUBLISHED_VERSION[kind]`.".into(),
        "    pub fn of(&self, kind: BakeKind) -> &'static str {".into(),
        "        match kind {".into(),
    ]);
    rs.extend(kinds.iter().map(|(k, _)| format!("            BakeKind::{k} => self.{k},")));
    rs.extend(["        }", "    }", "}"].map(String::from));
    rs.push(String::new());
    rs.extend(rs_doc(&source_doc, "", "///"));
    rs.push(format!("pub const PUBLISHED_TOP_ZOOM: crate::space::coord::zoom::Zoom = {top_z};"));
    rs.extend([
        String::new(),
        "const _: () = assert!(PUBLISHED_TOP_ZOOM >= crate::space::layer::lattice::GROUND.top(), \"a published zoom past the pyramid's top\");".to_string(),
    ]);
    Ok(vec![
        Output::new("apps/web/src/config/published.spec.ts", file(&ts)),
        Output::new("crates/spec/src/bake/published.spec.rs", file(&rs)),
    ])
}

pub fn object_outputs() -> Result<Vec<Output>, String> {
    let json = "spec/spec/bake/object.json";
    let spec = read(json)?;
    let doc = spec.lines_at("$doc").unwrap_or_default();
    let tiers = spec.get("OBJECT_TIERS").and_then(|n| n.num()).ok_or(format!("{json}: no OBJECT_TIERS"))?;
    if tiers < 1.0 || tiers.fract() != 0.0 {
        return Err(format!("{json}: OBJECT_TIERS {tiers} is not a count"));
    }
    let tiers = tiers as u32;
    let head = ["//".to_string(), "// GENERATED by pxl-tool/bin/spec.rs from object.json — do not edit.".into(), "".into()];

    let mut ts = vec!["// @pxl/web/config/object.spec.ts".to_string()];
    ts.extend(head.iter().cloned());
    ts.push("/**".into());
    ts.extend(doc.iter().map(|l| if l.is_empty() { " *".to_string() } else { format!(" * {l}") }));
    ts.extend([" */".to_string(), format!("export const OBJECT_TIERS = {tiers};")]);

    let mut rs = vec!["// pxl-spec/bake/object.spec.rs".to_string()];
    rs.extend(head);
    rs.extend(rs_doc(&doc, "", "///"));
    rs.push(format!("pub const OBJECT_TIERS: usize = {tiers};"));
    Ok(vec![
        Output::new("apps/web/src/config/object.spec.ts", file(&ts)),
        Output::new("crates/spec/src/bake/object.spec.rs", file(&rs)),
    ])
}

// The Rust reads a place's look by its kind number: per kind, in lists the
// kernel indexes, what Carto draws for it, with 0 for a zoom it never shows at.

pub fn place_theme_outputs() -> Result<Vec<Output>, String> {
    let (cat_json, theme_json) = ("spec/spec/bake/place_category.json", "spec/spec/bake/place_theme.json");
    let (cat, theme) = (read(cat_json)?, read(theme_json)?);
    let kinds: Vec<&str> = cat
        .get("CATEGORIES")
        .and_then(|c| c.arr())
        .ok_or(format!("{cat_json}: no CATEGORIES"))?
        .iter()
        .filter_map(|k| k.str())
        .collect();
    // A kind is a half-word on the wire, and 0 is none.
    if kinds.len() >= u16::MAX as usize {
        return Err(format!("{cat_json}: {} kinds do not fit a half-word beside none", kinds.len()));
    }
    let rows = theme.get("THEME").ok_or(format!("{theme_json}: no THEME"))?;
    if let Some((k, _)) = rows.named().find(|(k, _)| !kinds.contains(k)) {
        return Err(format!("{theme_json}: {k} is no category of {cat_json}"));
    }
    let zoom = |k: &str, f: &str| -> Result<String, String> {
        match rows.get(k).and_then(|r| r.get(f)) {
            None => Ok("0".into()),
            Some(z) => z
                .num()
                .filter(|z| (1.0..=31.0).contains(z) && z.fract() == 0.0)
                .map(|z| format!("{z}"))
                .ok_or(format!("{theme_json}: {k}.{f} is not a zoom")),
        }
    };
    let color = |k: &str, f: &str| -> Result<String, String> {
        match rows.get(k).and_then(|r| r.str_at(f)) {
            None => Ok("0".into()),
            Some(c) => packed(c).map(|n| format!("0x{n:06x}ff")),
        }
    };
    let mut rs = vec![
        "// pxl-spec/bake/place_theme.spec.rs".to_string(),
        "//".into(),
        "// GENERATED by pxl-tool/bin/spec.rs from place_category.json and place_theme.json — do not edit.".into(),
        "//".into(),
    ];
    rs.extend(line_comments(&cat.lines_at("$doc").unwrap_or_default(), ""));
    rs.push("//".into());
    rs.extend(line_comments(&theme.lines_at("$doc").unwrap_or_default(), ""));
    let mut list = |doc: &str, ty: &str, name: &str, each: &dyn Fn(&str) -> Result<String, String>| -> Result<(), String> {
        rs.extend([
            String::new(),
            format!("/// {doc}, kind k at `{name}[k - 1]`."),
            format!("pub const {name}: [{ty}; {}] = [", kinds.len()),
        ]);
        for k in &kinds {
            rs.push(format!("    {},", each(k)?));
        }
        rs.push("];".into());
        Ok(())
    };
    list("Each kind's Overture category", "&str", "CATEGORIES", &|k| Ok(json_str(k)))?;
    list("The zoom from which Carto draws a kind as a dot, 0 for never", "u8", "DOT_ZOOM", &|k| zoom(k, "dot"))?;
    list("The zoom from which Carto draws a kind's icon, 0 for never", "u8", "ICON_ZOOM", &|k| zoom(k, "icon"))?;
    list("The zoom from which Carto names a kind, 0 for never", "u8", "LABEL_ZOOM", &|k| zoom(k, "label"))?;
    list("A kind's icon or dot fill as `0xRRGGBBAA`", "u32", "FILL", &|k| color(k, "fill"))?;
    list("A kind's label fill as `0xRRGGBBAA`", "u32", "TEXT", &|k| color(k, "text"))?;
    list("A kind's icon under Carto's `symbols/`, \"\" for none", "&str", "SYMBOL", &|k| {
        Ok(json_str(rows.get(k).and_then(|r| r.str_at("symbol")).unwrap_or_default()))
    })?;
    Ok(vec![Output::new("crates/spec/src/bake/place_theme.spec.rs", file(&rs))])
}
