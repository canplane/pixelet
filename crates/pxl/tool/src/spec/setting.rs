// pxl-tool/spec/setting.rs

//! The settings. A setting is numbered by its place in SETTINGS, and that
//! number is what crosses and what the kernel holds; its name is storage's
//! and the sheet's. The kernel gets the settings as one struct of typed
//! fields, with the number's reading and writing beside it, so nothing past
//! the store names a setting by text. A `dev` setting's name, and its
//! options' names, are under the kernel's `dev` feature: a module built
//! without it holds the setting at its default and carries none of its
//! words. The shell gets the rows the sheet draws, and the same rows without
//! the `dev` ones for a production bundle to carry in their place: a filter
//! on the whole table at run time leaves every name in the artifact, and a
//! literal the build does not read is one the bundler drops.

use super::data::ts_literal;
use super::{casing_note, enum_name, file, js_num, line_comments, pascal, read, rs_doc, rs_ident, ts_doc, Node, Output};

const JSON: &str = "spec/pxl/web/kernel/shell/setting/schema.json";

struct Setting<'a> {
    key: &'a str,
    spec: &'a Node,
}

impl Setting<'_> {
    fn kind(&self) -> &str {
        self.spec.str_at("kind").unwrap_or_default()
    }
    fn options(&self) -> Option<&str> {
        self.spec.str_at("options")
    }
    fn flag(&self, name: &str) -> bool {
        self.spec.get(name) == Some(&Node::Bool(true))
    }
    fn default(&self) -> &Node {
        self.spec.get("default").map(Node::value).unwrap_or(&Node::Null)
    }
}

/// A list the settings name, such as a choice's options.
struct List<'a> {
    name: &'a str,
    values: Vec<String>,
    doc: Option<Vec<String>>,
}

pub fn outputs() -> Result<Vec<Output>, String> {
    let spec = read(JSON)?;
    let settings: Vec<Setting> = spec.get("SETTINGS").map(|s| s.named().map(|(key, spec)| Setting { key, spec }).collect()).unwrap_or_default();
    let mut lists: Vec<List> = Vec::new();
    for (name, n) in spec.named() {
        if name == "SETTINGS" {
            continue;
        }
        let values = n.is_wrapper().then(|| n.value().arr()).flatten().ok_or(format!("{JSON}: {name} is not a list"))?;
        lists.push(List {
            name,
            values: values.iter().filter_map(|v| v.str().map(str::to_string)).collect(),
            doc: n.lines_at("$doc"),
        });
    }
    let list = |name: &str| lists.iter().find(|l| l.name == name);
    let options_of = |s: &Setting| s.options().and_then(list).map(|l| l.values.clone()).ok_or(format!("{JSON}: {}'s options name no list", s.key));
    let mut choices: Vec<&str> = Vec::new();
    for s in settings.iter().filter(|s| s.kind() == "choice") {
        let o = s.options().unwrap_or_default();
        if !choices.contains(&o) {
            choices.push(o);
        }
    }

    // ---- Rust ----
    let mut rs = vec![
        "// pxl-kernel/shell/setting/schema.spec.rs".to_string(),
        "//".into(),
        "// GENERATED by pxl-tool/bin/spec.rs from schema.json — do not edit.".into(),
        "//".into(),
    ];
    rs.extend(line_comments(&spec.lines_at("$doc").unwrap_or_default(), ""));
    rs.push(String::new());
    rs.extend(casing_note());
    rs.push("#![allow(non_camel_case_types)]".into());
    for name in &choices {
        let List { values, doc, .. } = list(name).ok_or(format!("{JSON}: no list {name}"))?;
        let e = enum_name(name);
        rs.push(String::new());
        rs.extend(rs_doc(doc.as_deref().unwrap_or_default(), "", "///"));
        rs.extend(["#[derive(Clone, Copy, Debug, PartialEq, Eq)]".to_string(), "#[repr(u32)]".into(), format!("pub enum {e} {{")]);
        rs.extend(values.iter().enumerate().map(|(i, v)| format!("    {} = {i},", rs_ident(v))));
        rs.extend(["}".to_string(), String::new()]);
        rs.extend([
            format!("impl {e} {{"),
            format!(
                "    pub const ALL: [{e}; {}] = [{}];",
                values.len(),
                values.iter().map(|v| format!("{e}::{}", rs_ident(v))).collect::<Vec<_>>().join(", ")
            ),
            String::new(),
            "    /// The option an index names, or none for an index past the list.".into(),
            format!("    pub fn of(index: u32) -> Option<{e}> {{"),
            format!("        {e}::ALL.get(index as usize).copied()"),
            "    }".into(),
            "}".into(),
        ]);
    }
    rs.extend(
        [
            "",
            "/// How a setting is held.",
            "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
            "pub enum SettingKind {",
            "    Toggle,",
            "    Choice,",
            "    Number,",
            "}",
        ]
        .map(String::from),
    );
    rs.extend(
        [
            "",
            "/// Every setting, by its place in schema.json's SETTINGS.",
            "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
            "#[repr(u32)]",
            "pub enum SettingKey {",
        ]
        .map(String::from),
    );
    for (i, s) in settings.iter().enumerate() {
        rs.extend(rs_doc(&s.spec.lines_at("$doc").unwrap_or_default(), "    ", "///"));
        rs.push(format!("    {} = {i},", s.key));
    }
    rs.extend(["}".to_string(), String::new()]);
    let keys_where = |test: &dyn Fn(&Setting) -> bool| {
        let keys: Vec<String> = settings.iter().filter(|s| test(s)).map(|s| format!("SettingKey::{}", s.key)).collect();
        if keys.is_empty() {
            "false".to_string()
        } else {
            format!("matches!(self, {})", keys.join(" | "))
        }
    };
    rs.extend([
        "impl SettingKey {".to_string(),
        format!(
            "    pub const ALL: [SettingKey; {}] = [{}];",
            settings.len(),
            settings.iter().map(|s| format!("SettingKey::{}", s.key)).collect::<Vec<_>>().join(", ")
        ),
        String::new(),
        "    /// The setting a number names, or none for a number past the table.".into(),
        "    pub fn of(number: u32) -> Option<SettingKey> {".into(),
        "        SettingKey::ALL.get(number as usize).copied()".into(),
        "    }".into(),
        String::new(),
        "    pub fn kind(self) -> SettingKind {".into(),
        "        match self {".into(),
    ]);
    rs.extend(settings.iter().map(|s| format!("            SettingKey::{} => SettingKind::{},", s.key, pascal(s.kind()))));
    rs.extend([
        "        }".to_string(),
        "    }".into(),
        String::new(),
        "    /// Offered by a development build only.".into(),
        "    pub fn dev(self) -> bool {".into(),
        format!("        {}", keys_where(&|s| s.flag("dev"))),
        "    }".into(),
        String::new(),
        "    /// Read by a chunk's build, so a change builds the chunks again.".into(),
        "    pub fn sources_chunks(self) -> bool {".into(),
        format!("        {}", keys_where(&|s| s.flag("sources_chunks"))),
        "    }".into(),
        "}".into(),
    ]);
    let field_type = |s: &Setting| -> Result<String, String> {
        match s.kind() {
            "toggle" => Ok("bool".to_string()),
            "choice" => Ok(enum_name(s.options().unwrap_or_default())),
            _ => {
                let d = s.spec.get("default").ok_or(format!("{JSON}: {} has no default", s.key))?;
                match d.is_wrapper().then(|| d.str_at("$type")).flatten() {
                    Some(t @ ("u8" | "u16" | "u32")) => Ok(t.to_string()),
                    _ => Err(format!("{JSON}: {} is a number with no width", s.key)),
                }
            }
        }
    };
    let default_lit = |s: &Setting| -> Result<String, String> {
        let d = s.default();
        if s.kind() == "choice" {
            let name = d.str().unwrap_or_default();
            if !options_of(s)?.iter().any(|o| o == name) {
                return Err(format!("{JSON}: {}'s default is not one of its options", s.key));
            }
            return Ok(format!("{}::{}", enum_name(s.options().unwrap_or_default()), rs_ident(name)));
        }
        Ok(match d {
            Node::Bool(b) => b.to_string(),
            Node::Num(n) => js_num(*n),
            Node::Str(s) => s.clone(),
            other => format!("{other:?}"),
        })
    };
    rs.extend(
        [
            "",
            "/// Every setting's value: what the store holds, and what the app reads.",
            "#[derive(Clone, Debug, PartialEq)]",
            "pub struct Settings {",
        ]
        .map(String::from),
    );
    for s in &settings {
        rs.push(format!("    pub {}: {},", s.key, field_type(s)?));
    }
    rs.extend(
        [
            "}",
            "",
            "impl Settings {",
            "    /// Every setting at schema.json's default.",
            "    pub const DEFAULT: Settings = Settings {",
        ]
        .map(String::from),
    );
    for s in &settings {
        rs.push(format!("        {}: {},", s.key, default_lit(s)?));
    }
    rs.extend(["    };".to_string(), String::new()]);
    rs.extend(
        [
            "    /// A setting's value as it crosses: a toggle's 0 or 1, a choice's option",
            "    /// by its index, a number.",
            "    pub fn get(&self, key: SettingKey) -> u32 {",
            "        match key {",
        ]
        .map(String::from),
    );
    rs.extend(settings.iter().map(|s| format!("            SettingKey::{0} => self.{0} as u32,", s.key)));
    rs.extend(
        [
            "        }",
            "    }",
            "",
            "    /// Sets a setting from its value as it crosses; false, and nothing set,",
            "    /// for a value the setting cannot hold.",
            "    pub fn set(&mut self, key: SettingKey, value: u32) -> bool {",
            "        match key {",
        ]
        .map(String::from),
    );
    for s in &settings {
        let k = s.key;
        rs.push(match s.kind() {
            "toggle" => format!("            SettingKey::{k} if value <= 1 => self.{k} = value == 1,"),
            "choice" => format!(
                "            SettingKey::{k} => match {}::of(value) {{ Some(o) => self.{k} = o, None => return false }},",
                enum_name(s.options().unwrap_or_default())
            ),
            _ => format!(
                "            SettingKey::{k} => match {}::try_from(value) {{ Ok(n) => self.{k} = n, Err(_) => return false }},",
                field_type(s)?
            ),
        });
    }
    rs.extend(["            _ => return false,", "        }", "        true", "    }", "}"].map(String::from));

    // ---- TypeScript ----
    let row = |s: &Setting, i: usize| -> Result<Node, String> {
        let mut out: Vec<(String, Node)> = vec![(
            "key".to_string(),
            Node::Obj(vec![("$value".to_string(), Node::Num(i as f64)), ("$type".to_string(), Node::Str("u32".to_string()))]),
        )];
        if let Some(doc) = s.spec.get("$doc") {
            out.push(("$doc".to_string(), doc.clone()));
        }
        for (f, v) in s.spec.entries() {
            if f == "$doc" || f == "sources_chunks" {
                continue;
            }
            let value = match f.as_str() {
                "options" => Node::Arr(options_of(s)?.into_iter().map(Node::Str).collect()),
                "default" => v.value().clone(),
                _ => v.clone(),
            };
            match out.iter_mut().find(|(k, _)| k == f) {
                Some(slot) => slot.1 = value,
                None => out.push((f.clone(), value)),
            }
        }
        Ok(Node::Obj(out))
    };
    let table = |keep: &dyn Fn(&Setting) -> bool| -> Result<Node, String> {
        let mut out = Vec::new();
        for (i, s) in settings.iter().enumerate() {
            if keep(s) {
                out.push((s.key.to_string(), row(s, i)?));
            }
        }
        Ok(Node::Obj(out))
    };
    let List {
        values: dev_sections, doc: dev_doc, ..
    } = list("DEV_SECTIONS").ok_or(format!("{JSON}: no DEV_SECTIONS"))?;
    let mut ts = vec![
        "// @pxl/web/feature/setting/schema.spec.ts".to_string(),
        "//".into(),
        format!("// GENERATED by pxl-tool/bin/spec.rs from {JSON} — do not edit."),
        "//".into(),
    ];
    ts.extend(line_comments(&spec.lines_at("$doc").unwrap_or_default(), ""));
    ts.push(String::new());
    ts.extend(ts_doc(dev_doc.as_deref().unwrap_or_default(), ""));
    ts.push(format!(
        "export const DEV_SECTIONS = {} as const;",
        ts_literal(&Node::Arr(dev_sections.iter().cloned().map(Node::Str).collect()), "f64", "")?
    ));
    ts.extend([String::new(), format!("export const SETTINGS = {} as const;", ts_literal(&table(&|_| true)?, "f64", "")?)]);
    ts.extend([
        String::new(),
        "/** SETTINGS without its `dev` entries: what a production bundle carries in its place. */".into(),
        format!("export const SETTINGS_SHIPPED = {} as const;", ts_literal(&table(&|s| !s.flag("dev"))?, "f64", "")?),
    ]);

    Ok(vec![
        Output::new("crates/pxl/web/kernel/src/shell/setting/schema.spec.rs", file(&rs)),
        Output::new("apps/web/src/feature/setting/schema.spec.ts", file(&ts)),
    ])
}
