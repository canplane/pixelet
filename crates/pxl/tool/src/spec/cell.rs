// pxl-tool/spec/cell.rs

//! The cell catalogs: the cube types each channel gives out, the color of
//! each, and the decor kinds beside them.

use regex::Regex;

use super::{align_star, casing_note, file, js_num, json_str, packed, pascal, pretty, read, rgb_literal, rs_doc, rs_ident, ts_doc, Node, Output};

/// The ground channels, numbered by their place here: that number is
/// `GroundChannelKey`'s, which is a channel's identity in what the object
/// store holds, and the field a packed cell holds it in. Appending one is
/// free; moving one renumbers stored placements.
const GROUND_CHANNELS: [&str; 4] = ["land", "water", "structure", "transport"];

const CUBE_TYPE_JSON: &str = "spec/pxl/spec/cell/cube_type.json";

/// A channel of cube_type.json: its name, its note, and its entries, each a
/// type or a section heading.
struct Channel<'a> {
    name: &'a str,
    note: Vec<String>,
    entries: &'a [Node],
}

impl<'a> Channel<'a> {
    fn types(&self) -> impl Iterator<Item = &'a Node> {
        self.entries.iter().filter(|e| e.get("name").is_some())
    }
}

fn channels(spec: &Node) -> Result<Vec<Channel<'_>>, String> {
    let list = spec.get("channels").and_then(Node::arr).ok_or(format!("{CUBE_TYPE_JSON}: no channels"))?;
    list.iter()
        .map(|c| {
            Ok(Channel {
                name: c.str_at("name").ok_or(format!("{CUBE_TYPE_JSON}: a channel with no name"))?,
                note: c.lines_at("note").unwrap_or_default(),
                entries: c.get("entries").and_then(Node::arr).ok_or(format!("{CUBE_TYPE_JSON}: a channel with no entries"))?,
            })
        })
        .collect()
}

/// Every channel's type names, in the JSON's order: the catalog as a tool
/// that reads it at run time sees it, rather than as pxl-spec compiles it.
pub fn catalog() -> Result<Vec<(String, Vec<String>)>, String> {
    let spec = read(CUBE_TYPE_JSON)?;
    Ok(channels(&spec)?
        .iter()
        .map(|c| (c.name.to_string(), c.types().filter_map(|e| e.str_at("name")).map(str::to_string).collect()))
        .collect())
}

fn type_value(e: &Node) -> Result<u32, String> {
    e.get("value")
        .and_then(Node::num)
        .map(|v| v as u32)
        .ok_or(format!("{CUBE_TYPE_JSON}: {:?} has no value", e.str_at("name")))
}

// ---- color.json ----

pub fn color_outputs() -> Result<Vec<Output>, String> {
    let spec = read("spec/pxl/spec/cell/color.json")?;
    let head: Vec<String> = [
        "//",
        "// GENERATED by pxl-tool/bin/spec.rs from color.json — do not edit.",
        "//",
        "// The color of every cube type: what a cube *is* to the eye when no",
        "// texture is drawn over it — everything drawn with the pack off reads",
        "// this, the coarse tiers included, which summarize it the way they",
        "// summarize the tiles with the pack on",
        "// (pxl-render mesh/chunk_mesher.rs). The shipped palette carries it as",
        "// each row's `color`. A texture pack decorates these; it does not",
        "// replace them, which is why this table lives with the type numbering in",
        "// spec/cell rather than beside the pack's images.",
    ]
    .map(String::from)
    .to_vec();

    // The shell's copy is the JSON itself, each entry with its color packed
    // beside the hex it is written in.
    let mut with_rgb = Vec::new();
    for (ch, entries) in spec.entries() {
        if ch == "_meta" {
            with_rgb.push((ch.clone(), entries.clone()));
            continue;
        }
        let mut packed_entries = Vec::new();
        for (n, e) in entries.entries() {
            let hex = e.str_at("hex").ok_or(format!("color.json: {ch}.{n} has no hex"))?;
            let mut fields: Vec<(String, Node)> = e.entries().iter().filter(|(k, _)| k != "rgb").cloned().collect();
            let rgb = Node::Num(packed(hex)? as f64);
            match e.entries().iter().position(|(k, _)| k == "rgb") {
                Some(at) => fields.insert(at, ("rgb".to_string(), rgb)),
                None => fields.push(("rgb".to_string(), rgb)),
            }
            packed_entries.push((n.clone(), Node::Obj(fields)));
        }
        with_rgb.push((ch.clone(), Node::Obj(packed_entries)));
    }
    let mut json = String::new();
    pretty(&Node::Obj(with_rgb), "", &mut json);
    let bare_keys = Regex::new(r#""([A-Za-z_][A-Za-z0-9_]*)":"#).map_err(|e| e.to_string())?;
    let close_brace = Regex::new(r"\n(\s*)\}").map_err(|e| e.to_string())?;
    let close_bracket = Regex::new(r"\n(\s*)\]").map_err(|e| e.to_string())?;
    let json = bare_keys.replace_all(&json, "$1:");
    let json = close_brace.replace_all(&json, ",\n$1}");
    let json = close_bracket.replace_all(&json, ",\n$1]");
    let mut ts = vec!["// @pxl/web/catalog/cell/color.spec.ts".to_string()];
    ts.extend(head.iter().cloned());
    ts.extend([String::new(), format!("export default {json};")]);

    // What the Rust holds is each channel's color as a function of its type's
    // number, matched on the catalog's own constants, so nothing there finds
    // a channel or a type by its name. A ground channel falls back to
    // `common`'s, which is what a sentinel a baked cell can hold (VOID,
    // UNKNOWN) shows as.
    let types = read(CUBE_TYPE_JSON)?;
    let catalog = channels(&types)?;
    let mut rs = vec!["// pxl-spec/cell/color.spec.rs".to_string()];
    rs.extend(head);
    rs.push(String::new());
    rs.extend(casing_note());
    rs.extend(["", "use super::cube_type::{cube_types, GroundChannelKey};", "use super::r#type::Swatch;"].map(String::from));
    for (ch, entries) in spec.entries() {
        if ch == "_meta" {
            continue;
        }
        let channel = catalog.iter().find(|c| c.name == ch).ok_or(format!("color.json: {ch} is no channel cube_type.json has"))?;
        rs.extend([
            String::new(),
            format!("/// `{ch}`'s color for a type, by its number."),
            format!("pub const fn {ch}(t: u8) -> Option<Swatch> {{"),
            "    match t {".to_string(),
        ]);
        for (name, entry) in entries.entries() {
            if !channel.types().any(|e| e.str_at("name") == Some(name.as_str())) {
                return Err(format!("color.json: {ch}.{name} is no type cube_type.json has"));
            }
            if let Some(note) = entry.str_at("note") {
                rs.push(format!("        // {note}"));
            }
            let hex = entry.str_at("hex").ok_or(format!("color.json: {ch}.{name} has no hex"))?;
            rs.push(format!("        cube_types::{ch}::{} => Some(Swatch::new({})),", rs_ident(name), rgb_literal(hex)?));
        }
        rs.extend(["        _ => None,", "    }", "}"].map(String::from));
    }
    rs.extend(
        [
            "",
            "/// A ground channel's color for a type: its own, or `common`'s for a",
            "/// sentinel a baked cell can hold.",
            "pub const fn ground(channel: GroundChannelKey, t: u8) -> Option<Swatch> {",
            "    let own = match channel {",
        ]
        .map(String::from),
    );
    rs.extend(GROUND_CHANNELS.iter().map(|name| format!("        GroundChannelKey::{} => {name}(t),", name.to_uppercase())));
    rs.extend(["    };", "    match own {", "        Some(swatch) => Some(swatch),", "        None => common(t),", "    }", "}"].map(String::from));
    Ok(vec![
        Output::new("apps/web/src/catalog/cell/color.spec.ts", file(&ts)),
        Output::new("crates/pxl/spec/src/cell/color.spec.rs", file(&rs)),
    ])
}

