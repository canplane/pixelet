/// A ground cell's four channels packed into one word, for Rust alone: the
/// client and the bake both compile it, and the shell never decodes a page.
///
/// A channel's field is a dense index into its own table, not the catalog's
/// number, because the catalog numbers an identity rather than a sequence —
/// `land::sea` is 129 — and a placed cube already names one of them where a
/// browser can see it. The table is what turns one back into the other, and
/// the field's width comes out of the table's length, so a new type widens
/// its own field and shifts the ones above it with nothing edited by hand
/// (issue/20260923-a-ground-cell-is-fourteen-bits.md).
fn ground_pack(catalog: &[Channel]) -> Result<(Vec<String>, Vec<String>), String> {
    let mut tables: Vec<(&str, Vec<String>)> = Vec::new();
    for name in GROUND_CHANNELS {
        let ch = catalog.iter().find(|c| c.name == name).ok_or(format!("cube_type.json has no {name} channel"))?;
        // VOID first, so a cell of nothing is a word of zero, and UNKNOWN
        // last, so it is where a byte the channel does not give out is sent.
        let mut values = vec!["common::void".to_string()];
        values.extend(ch.types().filter_map(|e| e.str_at("name")).map(|n| format!("{name}::{n}")));
        values.push("common::unknown".into());
        tables.push((name, values));
    }
    let bits: Vec<u32> = tables.iter().map(|(_, v)| (32 - (v.len() as u32 - 1).leading_zeros()).max(1)).collect();
    let shifts: Vec<u32> = bits.iter().scan(0, |at, b| Some(std::mem::replace(at, *at + b))).collect();
    let cell_bits: u32 = bits.iter().sum();

    let mut number_of: Vec<(String, u32)> = Vec::new();
    for ch in catalog {
        for e in ch.types() {
            number_of.push((format!("{}::{}", ch.name, e.str_at("name").unwrap_or_default()), type_value(e)?));
        }
    }
    let number = |v: &str| number_of.iter().rev().find(|(k, _)| k == v).map(|(_, n)| *n).ok_or(format!("no number for {v}"));
    let mut inverse: Vec<Vec<usize>> = Vec::new();
    for (_, values) in &tables {
        let mut row = vec![values.len() - 1; 256];
        for (i, v) in values.iter().enumerate() {
            row[number(v)? as usize] = i;
        }
        inverse.push(row);
    }
    let join = |xs: &[String]| xs.join(", ");
    let rows = |row: &[usize]| {
        row.chunks(32)
            .map(|c| format!("            {},", c.iter().map(usize::to_string).collect::<Vec<_>>().join(", ")))
            .collect::<Vec<_>>()
    };
    let names: Vec<String> = tables.iter().map(|(n, _)| json_str(n)).collect();
    let numbers: Vec<String> = tables
        .iter()
        .map(|(_, v)| Ok(format!("[{}]", v.iter().map(|x| number(x).map(|n| n.to_string())).collect::<Result<Vec<_>, String>>()?.join(", "))))
        .collect::<Result<_, String>>()?;
    let indices: Vec<String> = inverse.iter().map(|r| format!("[{}]", r.iter().map(usize::to_string).collect::<Vec<_>>().join(", "))).collect();
    let bits_list = bits.iter().map(u32::to_string).collect::<Vec<_>>().join(", ");
    let shift_list = shifts.iter().map(u32::to_string).collect::<Vec<_>>().join(", ");

    let ts = vec![
        "/** A ground cell's four channels in one word: each a dense index into its".to_string(),
        " * own table, whose entries are the catalog's own numbers. VOID is index 0".into(),
        " * and UNKNOWN the last. The widths are the tables' lengths and nothing".into(),
        " * else; pxl-spec's bake/pack.rs is the reader that knows a field has a".into(),
        " * place, and this is here for whoever writes a page the kernel will read. */".into(),
        "export const ground_pack = {".into(),
        format!("  channels: [{}],", join(&names)),
        format!("  number: [{}],", join(&numbers)),
        format!("  index: [{}],", join(&indices)),
        format!("  bits: [{bits_list}],"),
        format!("  shift: [{shift_list}],"),
        format!("  cell_bits: {cell_bits},"),
        "} as const;".into(),
    ];
    let mut rs: Vec<String> = [
        "/// A ground cell's four channels in one word: each a dense index into its",
        "/// own table, whose entries are the catalog's own numbers. VOID is index 0",
        "/// and UNKNOWN the last, so a cell nothing painted is a word of zero and a",
        "/// byte no channel gives out reads as UNKNOWN rather than as a type.",
        "///",
        "/// The widths are the tables' lengths and nothing else. Everything here is",
        "/// walked through `bake/ground.rs`'s pack and unpack, which are the only",
        "/// readers that know a field has a place.",
        "pub mod ground_pack {",
        "    use super::cube_types::*;",
        "",
        "    /// The channels a packed cell holds, in the order their fields sit in",
        "    /// the word, by name for a tool that prints one. A field is found by",
        "    /// `GroundChannelKey`'s number, which is this order.",
    ]
    .map(String::from)
    .to_vec();
    rs.push(format!("    pub const CHANNELS: [&str; {}] = [{}];", tables.len(), join(&names)));
    rs.extend([
        String::new(),
        "    /// The catalog number each dense index names, a channel a row.".into(),
        format!("    pub const NUMBER: [&[u8]; {}] = [", tables.len()),
    ]);
    rs.extend(tables.iter().map(|(_, v)| format!("        &[{}],", join(v))));
    rs.extend([
        "    ];".to_string(),
        String::new(),
        "    /// The dense index each catalog number takes, a channel a row: the".into(),
        "    /// reverse of NUMBER, and UNKNOWN's index where the channel gives the".into(),
        "    /// number out to nobody.".into(),
        format!("    pub const INDEX: [[u8; 256]; {}] = [", tables.len()),
    ]);
    for row in &inverse {
        rs.push("        [".into());
        rs.extend(rows(row));
        rs.push("        ],".into());
    }
    rs.extend([
        "    ];".to_string(),
        String::new(),
        "    /// What it takes to name one of a channel's entries, and where that".into(),
        "    /// field starts in the word.".into(),
        format!("    pub const BITS: [u32; {}] = [{bits_list}];", tables.len()),
        format!("    pub const SHIFT: [u32; {}] = [{shift_list}];", tables.len()),
        String::new(),
        "    /// The bits a ground cell takes, all four fields together.".into(),
        format!("    pub const CELL_BITS: u32 = {cell_bits};"),
        "}".into(),
    ]);
    Ok((rs, ts))
}

pub fn cube_type_outputs() -> Result<Vec<Output>, String> {
    let spec = read(CUBE_TYPE_JSON)?;
    let catalog = channels(&spec)?;
    let head: Vec<String> = [
        "//",
        "// GENERATED by pxl-tool/bin/spec.rs from cube_type.json — do not edit.",
        "//",
        "// The cube catalog's numbering, every channel a name per value;",
        "// color.json colors it by the same names, and pxl-spec cell/cube.rs says",
        "// what each channel is.",
    ]
    .map(String::from)
    .to_vec();
    let key_doc: Vec<String> = [
        "A ground channel: one of the four a baked cell is painted in. The number is",
        "its identity — the number a stored value names it by, such as a",
        "terrain-styled cube's — and the field a packed cell holds it in",
        "(`ground_pack`), both written from one list; it is not its place in the",
        "order a cell is painted in (bake/format.rs `GROUND_CH_KEYS`), which can move",
        "without renumbering anything the object store holds.",
    ]
    .map(String::from)
    .to_vec();
    let keys: Vec<(String, usize)> = GROUND_CHANNELS.iter().enumerate().map(|(i, n)| (n.to_uppercase(), i)).collect();

    let mut ts = vec!["// @pxl/web/catalog/cell/cube_type.spec.ts".to_string()];
    ts.extend(head.iter().cloned());
    ts.push(String::new());
    ts.extend(ts_doc(&key_doc, ""));
    ts.push("export const enum GroundChannelKey {".into());
    ts.extend(keys.iter().map(|(k, i)| format!("  {k} = {i},")));
    ts.extend(["}", "", "export const cube_types = {"].map(String::from));

    let mut rs = vec!["// pxl-spec/cell/cube_type.spec.rs".to_string()];
    rs.extend(head);
    rs.push(String::new());
    rs.extend(casing_note());
    rs.extend(["#![allow(non_camel_case_types, non_upper_case_globals)]", "", "use super::r#type::Channels;", ""].map(String::from));
    rs.extend(rs_doc(&key_doc, "", "///"));
    rs.extend(["#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]", "#[repr(u8)]", "pub enum GroundChannelKey {"].map(String::from));
    rs.extend(keys.iter().map(|(k, i)| format!("    {k} = {i},")));
    rs.extend(["}".to_string(), String::new()]);
    rs.extend([
        "impl GroundChannelKey {".to_string(),
        format!(
            "    pub const ALL: [GroundChannelKey; {}] = [{}];",
            keys.len(),
            keys.iter().map(|(k, _)| format!("GroundChannelKey::{k}")).collect::<Vec<_>>().join(", ")
        ),
        String::new(),
        "    /// The channel a stored identity names, the reverse of `self as u8`.".into(),
        "    pub const fn from_id(id: u32) -> Option<GroundChannelKey> {".into(),
        "        match id {".into(),
    ]);
    rs.extend(keys.iter().map(|(k, i)| format!("            {i} => Some(GroundChannelKey::{k}),")));
    rs.extend(
        [
            "            _ => None,",
            "        }",
            "    }",
            "",
            "    /// The same, from the byte a packet carries it as.",
            "    pub const fn of(id: u8) -> Option<GroundChannelKey> {",
            "        GroundChannelKey::from_id(id as u32)",
            "    }",
            "}",
            "",
            "/// The catalog: a module per channel, each type a constant, and `ENTRIES`",
            "/// the channel as the object's keys walk it. `CHANNELS` is `cube_types`",
            "/// itself, walked.",
            "pub mod cube_types {",
        ]
        .map(String::from),
    );
    let mut enums: Vec<String> = Vec::new();
    for (ci, ch) in catalog.iter().enumerate() {
        let note = |indent: &str| ch.note.iter().map(|l| if l.is_empty() { format!("{indent}//") } else { format!("{indent}// {l}") }).collect::<Vec<_>>();
        if ci > 0 {
            ts.extend([String::new(), format!("  // ---- {} ----", ch.name)]);
        }
        ts.extend(note("  "));
        if ci > 0 {
            ts.push(String::new());
            rs.push(String::new());
        }
        ts.push(format!("  {}: {{", ch.name));
        rs.extend(note("    "));
        rs.push(format!("    pub mod {} {{", ch.name));
        let mut names: Vec<&str> = Vec::new();
        let mut recessed: Vec<(&str, String)> = Vec::new();
        let mut types: Vec<(&str, String, Option<Vec<String>>)> = Vec::new();
        for (ei, e) in ch.entries.iter().enumerate() {
            if let Some(section) = e.str_at("section") {
                if ei > 0 {
                    ts.push(String::new());
                    rs.push(String::new());
                }
                ts.extend([format!("    // ---- {section} ----"), String::new()]);
                rs.extend([format!("        // ---- {section} ----"), String::new()]);
                continue;
            }
            let name = e.str_at("name").ok_or(format!("{CUBE_TYPE_JSON}: {}: an entry with no name", ch.name))?;
            let doc = e.lines_at("doc");
            if let Some(doc) = &doc {
                ts.extend(ts_doc(doc, "    ").into_iter().enumerate().map(|(i, l)| if i == 0 { l } else { align_star(l, "    ") }));
                rs.extend(rs_doc(doc, "        ", "///"));
            }
            let value = type_value(e)?;
            let lit = if ch.name == "common" { format!("0x{value:02x}") } else { value.to_string() };
            ts.push(format!("    {name}: {lit},"));
            rs.push(format!("        pub const {name}: u8 = {lit};"));
            names.push(name);
            if let Some(r) = e.get("recess").and_then(Node::num) {
                recessed.push((name, js_num(r)));
            }
            types.push((name, lit, doc));
        }
        ts.push("  },".into());
        rs.extend([String::new(), "        pub const ENTRIES: &[(&str, u8)] = &[".to_string()]);
        rs.extend(names.iter().map(|n| format!("            ({}, {n}),", json_str(n))));
        rs.push("        ];".into());
        // Rust alone: the recess is a height, and heights are the kernel's.
        rs.extend([
            String::new(),
            "        /// How far below its sampled height a cell showing the type sits, in".into(),
            "        /// units; a type not listed sits at it.".into(),
            format!(
                "        pub const RECESS: &[(u8, i16)] = &[{}];",
                recessed.iter().map(|(n, r)| format!("({n}, {r})")).collect::<Vec<_>>().join(", ")
            ),
            "    }".into(),
        ]);
        // The same channel as one type, for Rust, which names a member of a
        // closed set with an enum rather than with the text the JSON spells it
        // out under. TypeScript already has this: `cube_types.land` IS the
        // closed set there, its keys checked by `keyof typeof`.
        let e = pascal(ch.name);
        enums.push(String::new());
        enums.extend(note("    "));
        enums.extend(["    #[derive(Clone, Copy, Debug, PartialEq, Eq)]".to_string(), "    #[repr(u8)]".into(), format!("    pub enum {e} {{")]);
        for (name, lit, doc) in &types {
            if let Some(doc) = doc {
                enums.extend(rs_doc(doc, "        ", "///"));
            }
            enums.push(format!("        {name} = {lit},"));
        }
        enums.extend(["    }".to_string(), String::new()]);
        enums.extend([
            format!("    impl {e} {{"),
            "        /// Every type the channel gives out, in the JSON's own order.".into(),
            format!("        pub const ALL: [{e}; {}] = [", types.len()),
        ]);
        enums.extend(types.iter().map(|(name, _, _)| format!("            {e}::{name},")));
        enums.extend([
            "        ];".to_string(),
            String::new(),
            "        /// The type a number names, or none for a number the channel".into(),
            "        /// does not give out.".into(),
            format!("        pub fn of(value: u8) -> Option<{e}> {{"),
            format!("            {e}::ALL.into_iter().find(|t| *t as u8 == value)"),
            "        }".into(),
            "    }".into(),
        ]);
    }
    ts.push("} as const satisfies Record<string, Record<string, number>>;".into());
    rs.extend([String::new(), "    pub const CHANNELS: &super::Channels = &[".to_string()]);
    rs.extend(catalog.iter().map(|ch| format!("        ({}, {}::ENTRIES),", json_str(ch.name), ch.name)));
    rs.push("    ];".into());
    let base = spec.get("base").ok_or(format!("{CUBE_TYPE_JSON}: no base"))?;
    let (base_channel, base_type) = (base.str_at("channel").unwrap_or_default(), base.str_at("type").unwrap_or_default());
    rs.push(String::new());
    rs.extend(rs_doc(&base.lines_at("doc").unwrap_or_default(), "    ", "///"));
    rs.extend([
        "    pub mod base {".to_string(),
        format!(
            "        pub const CHANNEL: super::super::GroundChannelKey = super::super::GroundChannelKey::{};",
            base_channel.to_uppercase()
        ),
        format!("        pub const TYPE: u8 = super::{base_channel}::{base_type};"),
        "    }".into(),
    ]);
    rs.extend(enums);
    rs.push("}".into());
    let (pack_rs, pack_ts) = ground_pack(&catalog)?;
    rs.push(String::new());
    rs.extend(pack_rs);
    ts.push(String::new());
    ts.extend(pack_ts);
    Ok(vec![
        Output::new("apps/web/src/catalog/cell/cube_type.spec.ts", file(&ts)),
        Output::new("crates/pxl/spec/src/cell/cube_type.spec.rs", file(&rs)),
    ])
}

// ---- decor.json ----

pub fn decor_outputs() -> Result<Vec<Output>, String> {
    let spec = read("spec/pxl/spec/cell/decor.json")?;
    let doc = spec.lines_at("doc").unwrap_or_default();
    let head: Vec<String> = [
        "//",
        "// GENERATED by pxl-tool/bin/spec.rs from decor.json — do not edit.",
        "//",
        "// [Layer: objects] User-placed decor kind catalog — the cube catalog's own sibling, non-cube content (GLB instances, not a meshed box).",
        "//",
    ]
    .map(String::from)
    .to_vec();
    let entries: Vec<(&str, String)> = spec
        .get("decor_types")
        .map(|d| d.entries().iter().map(|(k, v)| (k.as_str(), v.num().map(js_num).unwrap_or_default())).collect())
        .unwrap_or_default();

    let mut ts = vec!["// @pxl/web/catalog/cell/decor.spec.ts".to_string()];
    ts.extend(head.iter().cloned());
    ts.extend(doc.iter().map(|l| format!("// {l}")));
    ts.push("export const decor_types = {".into());
    ts.extend(entries.iter().map(|(k, v)| format!("  {k}: {v},")));
    ts.extend(["} as const satisfies Record<string, number>;", "", "export type DecorId = keyof typeof decor_types;"].map(String::from));

    let mut rs = vec!["// pxl-spec/cell/decor.spec.rs".to_string()];
    rs.extend(head);
    rs.extend(doc.iter().map(|l| format!("// {l}")));
    rs.push("//".into());
    rs.extend(casing_note());
    rs.extend(["#[allow(non_upper_case_globals, non_camel_case_types)]", "pub mod decor_types {"].map(String::from));
    rs.extend(entries.iter().map(|(k, v)| format!("    pub const {k}: u8 = {v};")));
    rs.push(String::new());
    // The catalog as one type, as cube_type.json's channels are: the kernel
    // holds a decor kind as this, and its name is the shell's.
    rs.extend(["    #[derive(Clone, Copy, Debug, PartialEq, Eq)]", "    #[repr(u8)]", "    pub enum Decor {"].map(String::from));
    rs.extend(entries.iter().map(|(k, v)| format!("        {k} = {v},")));
    rs.extend(["    }".to_string(), String::new()]);
    rs.extend([
        "    impl Decor {".to_string(),
        "        /// Every kind the catalog gives out, in the JSON's own order.".into(),
        format!(
            "        pub const ALL: [Decor; {}] = [{}];",
            entries.len(),
            entries.iter().map(|(k, _)| format!("Decor::{k}")).collect::<Vec<_>>().join(", ")
        ),
        String::new(),
    ]);
    rs.extend(
        [
            "        /// The kind a number names, or none for a number the catalog does not",
            "        /// give out.",
            "        pub fn of(value: u8) -> Option<Decor> {",
            "            Decor::ALL.into_iter().find(|t| *t as u8 == value)",
            "        }",
            "    }",
            "}",
            "",
            "pub type DecorId = decor_types::Decor;",
        ]
        .map(String::from),
    );
    Ok(vec![
        Output::new("apps/web/src/catalog/cell/decor.spec.ts", file(&ts)),
        Output::new("crates/pxl/spec/src/cell/decor.spec.rs", file(&rs)),
    ])
}
