//! What the bake and the client agree on about what the bucket holds: the
//! version each kind of page is published at, the coarsest level it supplies
//! whole, and the POI badges a page's kinds are drawn with.

use super::{file, json_str, line_comments, packed, read, rs_doc, Output};

pub fn published_outputs() -> Result<Vec<Output>, String> {
    let spec = read("spec/pxl/spec/bake/published.json")?;
    let doc = spec.lines_at("doc").unwrap_or_default();
    let kinds: Vec<(&str, &str)> = spec
        .get("PUBLISHED_VERSION")
        .map(|p| p.entries().iter().map(|(k, v)| (k.as_str(), v.str().unwrap_or_default())).collect())
        .unwrap_or_default();
    let source = spec.get("SOURCE").ok_or("published.json: no SOURCE")?;
    let source_doc = source.lines_at("$doc").unwrap_or_default();
    let top_level = source.get("top_level").and_then(|n| n.num()).ok_or("published.json: SOURCE has no top_level")?;
    if top_level < 0.0 || top_level.fract() != 0.0 {
        return Err(format!("published.json: SOURCE.top_level {top_level} is not a level"));
    }
    let top_level = top_level as u32;
    let head = ["//".to_string(), "// GENERATED by pxl-tool/bin/spec.rs from published.json — do not edit.".into(), "".into()];
    let list = |f: &dyn Fn(&str) -> String| kinds.iter().map(|(k, _)| f(k)).collect::<Vec<_>>().join(", ");

    let mut ts = vec!["// @pxl/web/config/published.spec.ts".to_string()];
    ts.extend(head.iter().cloned());
    ts.push("/**".into());
    ts.extend(doc.iter().map(|l| if l.is_empty() { " *".to_string() } else { format!(" * {l}") }));
    ts.extend([" */".to_string(), "export const PUBLISHED_VERSION = {".into()]);
    ts.extend(kinds.iter().map(|(k, v)| format!("  {k}: {},", json_str(v))));
    ts.extend(
        [
            "} as const;",
            "",
            "export type BakeKind = keyof typeof PUBLISHED_VERSION;",
            "",
            "/** The kinds by the number the kernel names one by (FETCH_CREATE's `bake`). */",
        ]
        .map(String::from),
    );
    ts.push(format!("export const BAKE_KINDS: readonly BakeKind[] = [{}];", list(&|k| json_str(k))));
    ts.extend([
        "".to_string(),
        "/** What a tile source declares of itself: SOURCE's shape, which the dev tile".into(),
        " * server answers too. */".into(),
    ]);
    ts.extend(["export interface TileSource {".to_string(), "  readonly top_level: number;".into(), "}".into(), "".into(), "/**".into()]);
    ts.extend(source_doc.iter().map(|l| if l.is_empty() { " *".to_string() } else { format!(" * {l}") }));
    ts.extend([" */".to_string(), format!("export const PUBLISHED_SOURCE: TileSource = {{ top_level: {top_level} }};")]);

    let mut rs = vec!["// pxl-spec/bake/published.spec.rs".to_string()];
    rs.extend(head);
    rs.extend(rs_doc(&doc, "", "///"));
    rs.push("pub struct PublishedVersion {".into());
    rs.extend(kinds.iter().map(|(k, _)| format!("    pub {k}: &'static str,")));
    rs.extend(["}".to_string(), String::new(), "pub const PUBLISHED_VERSION: PublishedVersion = PublishedVersion {".into()]);
    rs.extend(kinds.iter().map(|(k, v)| format!("    {k}: {},", json_str(v))));
    rs.extend(["};".to_string(), String::new()]);
    rs.extend(
        [
            "/// The kinds a version is published for: the fields of `PUBLISHED_VERSION`,",
            "/// numbered in their order.",
            "#[allow(non_camel_case_types)]",
            "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
            "#[repr(u32)]",
            "pub enum BakeKind {",
        ]
        .map(String::from),
    );
    rs.extend(kinds.iter().map(|(k, _)| format!("    {k},")));
    rs.extend([
        "}".to_string(),
        String::new(),
        "impl BakeKind {".into(),
        format!("    pub const ALL: [BakeKind; {}] = [{}];", kinds.len(), list(&|k| format!("BakeKind::{k}"))),
        String::new(),
        "    /// The kind a number names, or none for a number nobody gave out.".into(),
        "    pub fn of(number: u32) -> Option<BakeKind> {".into(),
        "        BakeKind::ALL.into_iter().find(|k| *k as u32 == number)".into(),
        "    }".into(),
        "}".into(),
        String::new(),
        "impl PublishedVersion {".into(),
        "    /// `PUBLISHED_VERSION[kind]`.".into(),
        "    pub fn of(&self, kind: BakeKind) -> &'static str {".into(),
        "        match kind {".into(),
    ]);
    rs.extend(kinds.iter().map(|(k, _)| format!("            BakeKind::{k} => self.{k},")));
    rs.extend(["        }", "    }", "}"].map(String::from));
    rs.push(String::new());
    rs.extend(rs_doc(&source_doc, "", "///"));
    rs.push(format!("pub const PUBLISHED_TOP_LEVEL: u32 = {top_level};"));
    rs.extend([
        String::new(),
        "const _: () = assert!(PUBLISHED_TOP_LEVEL <= crate::space::pyramid::TOP_LEVEL, \"a published level over the pyramid's top\");".to_string(),
    ]);
    Ok(vec![
        Output::new("apps/web/src/config/published.spec.ts", file(&ts)),
        Output::new("crates/pxl/spec/src/bake/published.spec.rs", file(&rs)),
    ])
}

// ---- the POI badges ----
//
// The shell reads the table by a place's category key, which a search result
// carries as text (the data spec writes that). What the Rust reads is a kind
// as the number a POI page carries it by, so it is written as lists in the
// JSON's order, indexed alike: the categories, which the bake numbers a place
// by, and the icons and colors, which the kernel draws a badge from — apart,
// so a module that only draws carries no category name.

pub fn poi_badge_outputs() -> Result<Vec<Output>, String> {
    let json = "spec/pxl/spec/bake/poi_badge.json";
    let spec = read(json)?;
    let kinds: Vec<(&str, &str, &str)> = spec
        .get("CATEGORY_BADGE")
        .map(|b| b.named().map(|(k, v)| (k, v.str_at("icon").unwrap_or_default(), v.str_at("color").unwrap_or_default())).collect())
        .unwrap_or_default();
    // A kind is a byte on the wire, and 0 is none.
    if kinds.len() > 255 {
        return Err(format!("{json}: {} kinds do not fit a byte beside none", kinds.len()));
    }
    let color = |c: &str| packed(c).map(|n| format!("0x{n:06x}ff"));
    let default = spec.get("DEFAULT_BADGE").ok_or(format!("{json}: no DEFAULT_BADGE"))?;
    let mut rs = vec![
        "// pxl-spec/bake/poi_badge.spec.rs".to_string(),
        "//".into(),
        "// GENERATED by pxl-tool/bin/spec.rs from poi_badge.json — do not edit.".into(),
        "//".into(),
    ];
    rs.extend(line_comments(&spec.lines_at("$doc").unwrap_or_default(), ""));
    rs.extend([
        String::new(),
        "/// Each kind's category, kind k at `KIND_CATEGORIES[k - 1]`: what the bake".into(),
        "/// numbers a place by. The kernel reads none of it.".into(),
        format!("pub const KIND_CATEGORIES: [&str; {}] = [", kinds.len()),
    ]);
    rs.extend(kinds.iter().map(|(k, _, _)| format!("    {},", json_str(k))));
    rs.extend([
        "];".to_string(),
        String::new(),
        "/// Each kind's badge icon, an emoji, kind k at `KIND_ICONS[k - 1]`.".into(),
        format!("pub const KIND_ICONS: [&str; {}] = [", kinds.len()),
    ]);
    rs.extend(kinds.iter().map(|(_, icon, _)| format!("    {},", json_str(icon))));
    rs.extend([
        "];".to_string(),
        String::new(),
        "/// Each kind's badge color as `0xRRGGBBAA`, kind k at `KIND_COLORS[k - 1]`.".into(),
        format!("pub const KIND_COLORS: [u32; {}] = [", kinds.len()),
    ]);
    for (_, _, c) in &kinds {
        rs.push(format!("    {},", color(c)?));
    }
    rs.extend([
        "];".to_string(),
        String::new(),
        "/// The badge of a place of no kind the table names.".into(),
        format!("pub const DEFAULT_ICON: &str = {};", json_str(default.str_at("icon").unwrap_or_default())),
        format!("pub const DEFAULT_COLOR: u32 = {};", color(default.str_at("color").unwrap_or_default())?),
    ]);
    Ok(vec![Output::new("crates/pxl/spec/src/bake/poi_badge.spec.rs", file(&rs))])
}
