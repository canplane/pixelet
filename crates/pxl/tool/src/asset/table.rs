//! The ingested-asset table, rendered into TypeScript and Rust from the same rows.

use std::fmt::Write;

use crate::asset::pack::Slot;

pub struct Row {
    pub path: String,
    pub key: String,
    pub bytes: u64,
    pub extent: Option<[f64; 3]>,
}

pub struct Sheet {
    pub key: String,
    pub bytes: u64,
    pub cell: u32,
    pub columns: u32,
    pub tiles: Vec<String>,
    pub means: Vec<[u8; 3]>,
    pub faces: Vec<TileFace>,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Face {
    Top,
    Side,
    Bottom,
}

impl Face {
    fn member(self) -> &'static str {
        match self {
            Face::Top => "Top",
            Face::Side => "Side",
            Face::Bottom => "Bottom",
        }
    }

    fn name(self) -> &'static str {
        match self {
            Face::Top => "top",
            Face::Side => "side",
            Face::Bottom => "bottom",
        }
    }
}

pub struct TileFace {
    pub channel: String,
    pub ty: String,
    pub side: bool,
    pub tile: u32,
}

/// A slot naming no catalog type is an error: a renamed type once left its
/// blocks untextured silently.
pub fn faces(slots: &[Slot], channels: &[(String, Vec<String>)]) -> Result<Vec<TileFace>, String> {
    let mut out = Vec::new();
    for (n, slot) in slots.iter().enumerate() {
        let (side, ty, wanted) = match slot {
            Slot::Top { channel, ty } => (false, ty, Some(channel.as_str())),
            Slot::Side { ty } => (true, ty, None),
        };
        let before = out.len();
        for (channel, types) in channels.iter().filter(|(ch, _)| *ch != "common" && wanted.is_none_or(|w| w == *ch)) {
            if types.contains(ty) {
                out.push(TileFace {
                    channel: channel.clone(),
                    ty: ty.clone(),
                    side,
                    tile: n as u32,
                });
            }
        }
        if out.len() == before {
            return Err(format!("the manifest's {slot:?} is no cube type in spec/pxl/spec/cell/cube_type.json"));
        }
    }
    Ok(out)
}

/// An integral double needs a `.0`, or Rust reads it as an integer.
fn f64_literal(x: f64) -> String {
    let text = format!("{x}");
    if text.contains(['.', 'e', 'E']) {
        text
    } else {
        format!("{text}.0")
    }
}

pub fn ident(path: &str) -> String {
    path.chars().map(|c| if c.is_ascii_alphanumeric() || c == '_' { c } else { '_' }).collect()
}

pub fn render_ts(rows: &[Row], sheet: &Sheet) -> String {
    let mut out = String::with_capacity(rows.len() * 160);
    out.push_str(
        r#"// @pxl/web/catalog/asset/ingested.spec.ts
//
// GENERATED by pxl-tool/bin/ingest_asset.rs — do not edit.
// Every shipped asset by its path under asset/: the bucket key (its own path
// under `asset/`, with a hash of its bytes in the stem), its size, and for a model its
// extent in ENU world units, measured from the glb. A catalog names an asset
// by its path and reads its key here; the bytes themselves are in the bucket.

export interface IngestedAsset {
  key: string;
  bytes: number;
  /** ENU (x, y, z-up); absent for an image. */
  extent?: readonly [number, number, number];
}

export const INGESTED: Readonly<Record<string, IngestedAsset>> = {
"#,
    );
    for r in rows {
        let extent = match r.extent {
            Some(e) => format!(", extent: [{}, {}, {}]", e[0], e[1], e[2]),
            None => String::new(),
        };
        let _ = writeln!(out, "  \"{}\": {{ key: \"{}\", bytes: {}{} }},", r.path, r.key, r.bytes, extent);
    }
    out.push_str(
        r#"};

/** The texture pack as one sheet: `columns` tiles of `cell` pixels per
 * row, tile n at column n % columns and row n / columns, `tiles` the asset
 * path each holds, and `faces` the cube face — channel, type, face — each
 * tile is. */
export const SHEET = {
"#,
    );
    let _ = writeln!(out, "  key: \"{}\",", sheet.key);
    let _ = writeln!(out, "  bytes: {},", sheet.bytes);
    let _ = writeln!(out, "  cell: {},", sheet.cell);
    let _ = writeln!(out, "  columns: {},", sheet.columns);
    out.push_str("  tiles: [\n");
    for t in &sheet.tiles {
        let _ = writeln!(out, "    \"{t}\",");
    }
    out.push_str("  ],\n  faces: [\n");
    for f in &sheet.faces {
        let _ = writeln!(out, "    [\"{}\", \"{}\", \"{}\", {}],", f.channel, f.ty, if f.side { "side" } else { "top" }, f.tile);
    }
    out.push_str("  ],\n} as const;\n");
    out
}

pub fn render_rs(rows: &[Row], sheet: &Sheet) -> String {
    let mut out = String::with_capacity(rows.len() * 160);
    out.push_str(
        r##"// pxl-spec/asset/ingested.spec.rs
//
// GENERATED by pxl-tool/bin/ingest_asset.rs — do not edit.
// Every shipped asset as a member of `Asset`, in the ingest's sorted order:
// its size, and for a model its extent in ENU world units, measured from the
// glb. A catalog names an asset by its member; its path and its bucket key are
// the shell's (ingested.spec.ts), and the bytes themselves are in the bucket.

#![allow(non_camel_case_types)]

use crate::cell::cube_types;
use crate::cell::object::PlaceableCube;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[repr(u16)]
pub enum Asset {
"##,
    );
    for (i, r) in rows.iter().enumerate() {
        let _ = writeln!(out, "    {} = {i},", ident(&r.path));
    }
    out.push_str("}\n\nimpl Asset {\n    /// Every asset, in the table's order.\n");
    let _ = writeln!(out, "    pub const ALL: [Asset; {}] = [", rows.len());
    for r in rows {
        let _ = writeln!(out, "        Asset::{},", ident(&r.path));
    }
    out.push_str(
        r##"    ];

    /// The asset a number names, or none for a number the table does not
    /// give out.
    pub fn of(value: u16) -> Option<Asset> {
        Asset::ALL.into_iter().find(|a| *a as u16 == value)
    }

    /// What the ingest measured of it.
    pub fn ingested(self) -> IngestedAsset {
        INGESTED[self as usize]
    }
}

#[derive(Clone, Copy, Debug, PartialEq)]
pub struct IngestedAsset {
    pub bytes: u64,
    /// ENU (x, y, z-up); None for an image.
    pub extent: Option<[f64; 3]>,
}

/// Each asset's row, at its member's number.
"##,
    );
    let _ = writeln!(out, "pub const INGESTED: [IngestedAsset; {}] = [", rows.len());
    for r in rows {
        let extent = match r.extent {
            Some(e) => format!("Some([{}, {}, {}])", f64_literal(e[0]), f64_literal(e[1]), f64_literal(e[2])),
            None => "None".to_string(),
        };
        let _ = writeln!(out, "    IngestedAsset {{ bytes: {}, extent: {extent} }},", r.bytes);
    }
    out.push_str(
        r##"];

/// Which of a box's images a tile is. The split is the renderer's own: a face
/// is lateral at `abs(normal.z) < 0.5`, so a bottom face wears the top image
/// just as the top face does.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum CubeFace {
    Top,
    Side,
}

/// The texture pack as one sheet: `columns` tiles of `cell` pixels per
/// row, tile n at column n % columns and row n / columns, and `tiles` the
/// cube face each tile is.
pub struct Sheet {
    pub bytes: u64,
    pub cell: u32,
    pub columns: u32,
    pub tiles: &'static [(PlaceableCube, CubeFace, u32)],
    /// What each tile reads as from far enough away that the tile itself is
    /// gone: its own mean color, taken in linear light. A mesh that
    /// summarizes a patch of ground takes its color from here rather than
    /// from the catalog's swatch, which is the color a type is filed under
    /// and not the color its material shows.
    pub means: &'static [[u8; 3]],
}

pub const SHEET: Sheet = Sheet {
"##,
    );
    let _ = writeln!(out, "    bytes: {},", sheet.bytes);
    let _ = writeln!(out, "    cell: {},", sheet.cell);
    let _ = writeln!(out, "    columns: {},", sheet.columns);
    out.push_str("    tiles: &[\n");
    for f in &sheet.faces {
        let mut c = f.channel.chars();
        let upper: String = c.next().map(|first| first.to_ascii_uppercase().to_string() + c.as_str()).unwrap_or_default();
        let face = if f.side { "Side" } else { "Top" };
        let _ = writeln!(out, "        (PlaceableCube::{upper}(cube_types::{upper}::{}), CubeFace::{face}, {}),", f.ty, f.tile);
    }
    out.push_str("    ],\n    means: &[\n");
    for m in &sheet.means {
        let _ = writeln!(out, "        [{}, {}, {}],", m[0], m[1], m[2]);
    }
    out.push_str("    ],\n};\n");
    out
}
