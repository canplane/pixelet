// @pxl/client/plugin/prebuilt-flavor.ts

/**
 * Makes `pod install` leave React Native's prebuilt parts marked as built for
 * no configuration, so that the next build extracts the one it needs.
 *
 * The core, its dependencies and Hermes each sit in one folder that holds
 * either the Debug or the Release build, beside a file that says which
 * (.last_build_configuration, in Pods/React-Core-prebuilt,
 * Pods/ReactNativeDependencies, and in Pods itself for Hermes). A phase of
 * every build extracts the other build when they differ. `pod install` makes
 * the folders again without that file but keeps what was extracted, and a
 * missing file reads as Debug. So a Release build followed by an install
 * leaves the Release core under a Debug app, whose link fails on what only
 * the Debug core defines (`facebook::react::Sealable`). Marking neither makes
 * the next build of either kind extract its own, once after each install.
 *
 * This is a config plugin because `ios/` is generated by `expo prebuild` and
 * not kept. The plugin puts the step into the Podfile that prebuild writes.
 */

import { withPodfile } from "expo/config-plugins";
import type { ConfigPlugin } from "expo/config-plugins";

const MARK = "# pxl: React Native's prebuilt parts, of no configuration";

const STEP = `
    ${MARK} (plugin/prebuilt-flavor.ts)
    pods = installer.sandbox.root.to_s
    { 'React-Core-prebuilt' => 'React-Core-prebuilt', 'ReactNativeDependencies' => 'ReactNativeDependencies', 'hermes-engine' => '.' }.each do |pod, marked|
      File.write(File.join(pods, marked, '.last_build_configuration'), 'None') if File.directory?(File.join(pods, pod))
    end
`;

const plugin: ConfigPlugin = (cfg) =>
  withPodfile(cfg, (cfg) => {
    const podfile = cfg.modResults.contents;
    if (!podfile.includes(MARK)) {
      const at = podfile.indexOf("post_install do |installer|");
      if (at < 0) {
        throw new Error("prebuilt-flavor: the Podfile has no post_install");
      }
      const end = podfile.indexOf("\n", at) + 1;
      cfg.modResults.contents =
        podfile.slice(0, end) + STEP.slice(1) + podfile.slice(end);
    }
    return cfg;
  });

export default plugin;
